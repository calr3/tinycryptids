import tm, build

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF LEMOINE'S CONJECTURE IS
; FALSE, i.e. iff some odd n >= 7 is not p + 2q with p, q prime.
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/Lemoine/{lean}.lean, theorem TM.Lemoine.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / lemoine.txt with states
;   merged. States are merged only when their defined transitions agree, so
;   each state below plays one or more ROLES of the design (its name joins
;   them). Each transition line is tagged [role] with the role(s) that use it.
;   A '-' line is never used. The seed roles run once at the start and only
;   ever read 0, so most of them double as a step of some other routine.
;
; TAPE LAYOUT
;
;      1 0 [Dp 00 Rp] 0^G [Dq 00 Rq] 0 1
;
;   A PAIR D 00 R holds a number m = d + r under trial division by d (as in
;   ../legendre): D has d+2 cells, its HOLE (a single 0) at cell c+1 is a
;   cyclic counter c in [0, d); R has r+2 cells. The pair is NORMALIZED when
;   d = 2 (D = 1011). P holds p = n - 2q, Q holds q.
;   The SENTINELS 1 0 (left) and 0 1 (right) tell the two pairs apart.
;   The GAP G = 2q (even, so the hole parsers cross it): every q += 1 erases
;   two cells at the end of Rp.
;
; ALGORITHM (n = 7, 9, 11, ...; q = 2, 3, ... while p = n - 2q >= 3)
;   test p    normalize P (d := 2), then trial division: mod walk (r times
;             advance the D hole cyclically, then the R hole; d | m iff the D
;             hole is back at cell 1), shift (d+1, r-1), until a divisor or
;             r = 0. If R has a single cell, p = 1: no q is left: HALT.
;   test q    after p prime: normalize Q, the same trial division.
;   q += 1    after a composite: a cell after Rq (the sentinel moves), two
;             cells off Rp, then test p.
;   next n    after q prime: erase Q, fill the gap into Rp (p' = p + 2q - 2
;             after the two cells), write a new gap 00, Q = 1011 00 1, the
;             sentinel, then as q += 1.
;   seed      write 1 0 1011 00 11111 00 1011 00 1 0 1, then as q += 1:
;             n = 7, q = 2.
; ============================================================================

blank_symbol: 0
"""

R = 'right'; L = 'left'
def parser(direction, then):
    return f'scan {direction} to the next hole, then {then}'

