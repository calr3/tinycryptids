HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF THE AGOH-GIUGA
; CONJECTURE IS FALSE, i.e. iff some composite n >= 2 divides
; 1^(n-1) + 2^(n-1) + ... + (n-1)^(n-1) + 1.
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/AgohGiuga/{lean}.lean,
; theorem TM.AgohGiuga.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / agoh_giuga.txt with
;   states merged. States are merged only when their defined transitions
;   agree, so each state below plays one or more ROLES of the design (its name
;   joins them). Each transition line is tagged [role] with the role(s) that
;   use it. A '-' line is never used. The seed roles run once at the start and
;   only ever read 0, so all of them double as a step of some other routine.
;
; THE IDEA
;   For n = 4, 5, 6, ... and the bases i = n - 1, ..., 2: compute i^(n-1) in
;   unary and add i^(n-1) - 1 to B, a counter mod n. After each base, if B is
;   not 0, set a flag. A prime never sets it (Fermat: i^(n-1) = 1 mod n); a
;   composite always does (at a divisor i of n, i^(n-1) != 1 mod n). At the
;   end of round n, B = 1^(n-1) + ... + (n-1)^(n-1) + 1 - n mod n: HALT iff
;   the flag is set and B = 0.
;
; TAPE LAYOUT
;
;      N 00 I 00 J 00 K 00 S 00 R [00 Q]
;
;   A block of v + 2 cells holds v; its cells 1..v are the positions of a
;   cyclic HOLE (a single 0).
;   N: holds n; its hole (at cell 1 at rest) is the Horner run's exponent.
;   I: holds the base i, hole at cell 1. J: no hole, n - i + flag cells;
;   |I| + |J| is fixed in a round, and i - 1 moves the I/J separator left.
;   K: no hole; 2 cells, 1 once the flag is set (J then has a cell more).
;   S: holds n; its hole at cell B + 1.
;   R: 101 (holds 1) between bases; the Horner run makes it i^(n-1), with
;   copies Q appended after it.
;
; ALGORITHM (one base)
;   horner    ../firoozbakht's Horner run (exponent N, base I, skipped hole
;             S): n - 1 rounds R := i * R (i - 1 copies of R, then a merge).
;   consume   erase R's last cell and advance S's hole, until R = 101:
;             B += R - 1.
;   check     S's hole at cell 1? If not, set the flag (K 2 -> 1 cells).
;   shift     I's last cell joins the I/J separator: i - 1, then the next
;             Horner run. If i was 2, the round ends: S's hole at cell 1 and
;             K = 1: HALT. Otherwise the reset for n + 1: S's hole filled, S
;             a cell longer on its left with its hole at the new cell 1,
;             K := 11, J := 1, I := n (taking two cells of N), N three cells
;             longer on its left with its hole at the new cell 1.
;   seed      write the end of round 3 and do the reset: round 4 starts.
; ============================================================================

blank_symbol: 0
"""


