"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design
(mersenne.txt, generated by build.py). The merged state is named after its
roles, listed with a description, and every transition line is tagged with the
roles that use it; the beep transition is marked BEEP.
Usage: python3 annotate.py merged.txt out.txt LeanName
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))  # tm.py
from collections import defaultdict
import tm, leangen

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol BEEPING Turing machine that QUASIHALTS IFF THE
; MERSENNE PRIME CONJECTURE IS FALSE.
;
; THE BEEP is the transition of state {beep} reading 0 (marked BEEP below).
; Started on a blank tape in the first state, the machine never halts, and it
; takes the beep transition exactly once for every Mersenne prime 2^k - 1, in
; increasing order: 3, 7, 31, 127, 8191, ...
; So it beeps infinitely often iff there are infinitely many Mersenne primes,
; and it quasihalts (beeps only finitely often) iff the conjecture is false.
; Lean proof: lean/TinyCryptids/Mersenne/{lean}.lean,
; theorem TM.Mersenne.{lean}.quasihalts_iff (and never_halts).
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / mersenne.txt with states
;   merged. States are merged only when their defined transitions agree, and
;   no state that reads 0 joins the beep state, so the beep transition is taken
;   exactly where the design takes it. Each state below plays one or more
;   ROLES of the design (its name joins them); each transition line is tagged
;   [role] with the role(s) that use it. A '-' line is never used.
;
; THE IDEA
;   For odd m >= 3, m is a Mersenne prime iff no odd d with 3 <= d < m divides
;   m or m + 1 (no odd divisor of m: m is prime; no odd divisor >= 3 of m + 1:
;   m + 1 is a power of 2). The machine tests m = 5, 7, 9, ... in turn, each
;   with d = 3, 5, 7, ...; one mod walk per d tests both m and m + 1. When
;   every d has passed, it beeps. (The start beeps for m = 3.)
;
; TAPE LAYOUT (blank left of D and right of R)
;
;      D 0 R
;
;   D: d cells, all 1 except a HOLE (a single 0) at cell c: a counter mod d.
;      Before a walk the hole is on cell 0, the blank left of D's d - 1 ones.
;   one 0: the separator.
;   R: r cells, d + r = m - 1; during the mod walk a hole moves right in it.
;   Holes are found by scanners that count zeros: from one block, pass the
;   separator, stop at the next 0. A hole may sit next to the separator.
;
; ALGORITHM (candidate m, divisor d)
;   walk     D's hole starts on cell 0. r times: make the next cell of R the
;            R hole (R's cell 0 first), scan left to D's hole and move it one
;            cell right (from the last cell back to cell 0), scan right to R's
;            hole and fill it. D's hole ends on cell c = (m - 1) mod d:
;            d | m iff c = d - 1, d | m + 1 iff c = d - 2.
;   end      erase R's last cell (r := r - 1), scan left to the separator and
;            fill it. X1 and X2 alternately erase D's cells leftwards to the
;            hole and fill it; C4 then reads the filled separator (FAIL: c =
;            d - 1 or d - 2) or an erased cell (d passed).
;   shift    d passed: refill the erased cells; the old separator becomes a
;            cell of D and R's cell 0 the new separator; the blank left of D
;            is the next hole: d := d + 2, r := r - 2. R empty: d = m - 2 was
;            the last odd d below m, every d passed: BEEP.
;   rebuild  FAIL or after the beep: one block of m - 1 ones. Write 1 1 at its
;            left end and the separator after them: candidate m + 2, d = 3.
;   start    1 1 and G0 on a blank: the beep for m = 3, then the rebuild.
; ============================================================================

blank_symbol: 0
"""

ROLE = {
    'B2': 'make R\'s hole here and scan left to D\'s hole (Y1); 0: past R\'s end, the walk is over, or (d passed) an erased cell: step back (E)',
    'Y1': 'scan left to the separator, then to D\'s hole (Y2)',
    'Y2': 'scan left to D\'s hole, fill it, step right (A2)',
    'A2': 'advance D\'s hole: the new hole here, then to R\'s hole (Z1); 0: the separator, wrap (W1)',
    'W1': 'wrap: run left to the blank before D',
    'W2': 'wrap: the new hole on D\'s cell 0, then to R\'s hole (Z1)',
    'Z1': 'scan right to the separator, then to R\'s hole (Z2)',
    'Z2': 'scan right to R\'s hole (the 0 after the separator), fill it, step right (B2)',
    'E': 'erase R\'s last cell, then to the separator (V); 0 (d passed): write 1, refill (H1)',
    'V': 'scan left to the separator, fill it, check (X1)',
    'X1': 'erase D\'s cells d - 1, d - 3, ... leftwards; 0: the hole, fill it, step right (C4)',
    'X2': 'erase D\'s cells d - 2, d - 4, ...; 0: the hole, fill it, step right (X1 refills)',
    'C4': 'the filled separator: FAIL, run left to the blank before D, write a 1 (H1); 0 (d passed): write 1, step back (H1)',
    'H1': 'refill erased cells going right; 1: the old separator, the cell C4 filled, or the rebuild\'s 1 1 (G0)',
    'G0': '1: write the separator, start the walk (B2), or (d passed) erase the cell C4 filled; 0: R is empty, every d passed: BEEP, then rebuild (C4)',
}

SECTIONS = [
    ('WALK: trial division of m = d + r + 1 by d', 'B2 Y1 Y2 A2 W1 W2 Z1 Z2'),
    ('END OF THE WALK and the CHECK: does d divide m or m + 1?', 'E V X1 X2'),
    ('SHIFT: d := d + 2, r := r - 2, the BEEP, and the REBUILD for m + 2', 'C4 H1 G0'),
]

def main(src, dst, lean):
    o, S, _ = tm.parse(open('mersenne.txt').read())
    o2, S2, _ = tm.parse(open(src).read())
    phi = leangen.state_map(o, S, o2, S2)
    assert set(ROLE) == set(o), set(o) ^ set(ROLE)
    bs, bb = 'G0', 0
    cls = defaultdict(list)
    for q in o: cls[phi[q]].append(q)
    sec_of = {r: i for i, (_, rs) in enumerate(SECTIONS) for r in rs.split()}
    pos = {r: i for i, r in enumerate(o)}
    name = {c: '_'.join(m) for c, m in cls.items()}
    name[o2[0]] = 'start_' + name[o2[0]]
    def key(c):
        return (c != o2[0], sec_of.get(cls[c][0], -1), pos[cls[c][0]])
    out = [HEADER.format(n=len(o2), N=len(o), lean=lean, beep=name[phi[bs]])]
    cur = None
    for c in sorted(o2, key=key):
        sec = key(c)[1] if c != o2[0] else -1
        if sec != cur:
            title = 'START (the rebuild\'s scan to the left end)' if sec == -1 else SECTIONS[sec][0]
            out += ['', f'; ---------- {title} ' + '-' * max(0, 60 - len(title)), '']
            cur = sec
        for r in cls[c]:
            out.append(f'; {r:6} {ROLE[r]}')
        out.append(name[c])
        for b, t in enumerate(S2[c]):
            if t is None:
                out.append('    -'); continue
            users = [r for r in cls[c] if S[r][b] is not None]
            tgt = name.get(t[2], t[2])
            mark = '   BEEP' if (c, b) == (phi[bs], bb) else ''
            out.append(f'    {b} {t[0]} {t[1]} {tgt:20} ; [{", ".join(users)}]{mark}')
    text = '\n'.join(out) + '\n'
    # the annotated machine must be the same machine (up to state names)
    o3, S3, _ = tm.parse(text)
    assert o3[0] == name[o2[0]] and len(o3) == len(o2)
    for c in o2:
        assert S3[name[c]] == [None if t is None else (t[0], t[1], name.get(t[2], t[2])) for t in S2[c]]
    open(dst, 'w').write(text)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'M14')
