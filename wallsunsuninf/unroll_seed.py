"""Write wallsunsuninf_seeded.txt, the design the Lean proof is about: the seedless design
(build.build(with_seed=False)) plus the seed run of a merged machine, unrolled into one seed
state per step (sd0, sd1, ...; each defined only on the symbol it reads, going to the next,
the last to e1).  The merged machine is then a merge of this design (phi(sd_i) is the merged
state at step i), so the Lean transfer applies.
Usage: python3 unroll_seed.py machines/wallsunsuninf_48.txt"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [HERE, os.path.join(HERE, '..', 'tools')]
import tm, build

def main(merged):
    mo, ms, _ = tm.parse(open(merged).read())
    order, states = build.build(with_seed=False)
    # the merged run from a blank tape to the round start canon(m) in e1's class
    T, head, q, run = {}, 0, mo[0], []
    for step in range(10 ** 5):
        if q == 'e1':
            ones = [k for k, v in T.items() if v] or [0]
            lo, hi = min(ones), max(ones)
            tp = ''.join(str(T.get(i, 0)) for i in range(lo, hi + 1))
            n = tp.count('1'); m = (n - 4) // 3
            if m >= 1 and tp == build.canon(m) and head == hi - m - 1: break
        b = T.get(head, 0)
        w, d, nq = ms[q][b]
        run.append((q, b, w, d))
        T[head] = w; head += 1 if d == 'R' else -1; q = nq
    else:
        raise SystemExit('no round start')
    seed = []
    for i, (q, b, w, d) in enumerate(run):
        nxt = f'sd{i + 1}' if i + 1 < len(run) else 'e1'
        t = [None, None]; t[b] = (w, d, nxt)
        seed.append((f'sd{i}', t))
    with open(os.path.join(HERE, 'wallsunsuninf_seeded.txt'), 'w') as f:
        f.write(f'; The Lean design: wallsunsuninf_noseed.txt plus the seed run of {os.path.basename(merged)}\n'
                f'; ({len(run)} steps to round {m}) unrolled into seed states. Generated by unroll_seed.py.\n'
                f'; {len(order) + len(seed)} states, 2 symbols.\n; Beep: q9 reading 0.\n\nblank_symbol: 0\n\n')
        for name, t in seed + [(n, states[n]) for n in order]:
            f.write(name + '\n')
            for r, x in enumerate(t):
                f.write('    -\n' if x is None else f'    {r} {x[0]} {x[1]} {x[2]}\n')
        f.write('\n')
    print(len(seed), 'seed states, round', m, '->', 'wallsunsuninf_seeded.txt')

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'machines', 'wallsunsuninf_48.txt'))
