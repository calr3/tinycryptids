"""Emit the generated parts of the Lean proof of the 10-symbol machine (D = 8), in
../lean/TinyCryptids/PAK/ (namespace TMK.PA):

    Tree.lean   the program tree of kary.py: slots, values, writes, skips, subtree heights, break
                and continue levels, the erase / advance / return tables, the register numbering
    Nodes.lean  every node's denotation d<i> and the proof e<i> that the node runs it
    Comp.lean   the composite subroutines and main's chunks on the abstract registers (k<i>_emb)
    Cand.lean   the candidates' codes (configs.CONFIGS[8]), main's iteration grouped (iterK)
    M10.lean    the machine of machines/pa_10sym_470.txt (parsed from the file), the state map
                from the compiled machine (Machine.lean), compat, and TMK.PA.M10.halts_iff

    python3 gen_klean.py

The hand-written files (Machine, Sem, Tape, Ops, Frame, Shape, Abs, Step, Boot, Run) name node
numbers and slots of this tree; if the program or its configuration changes, regenerate and fix
them (see ../lean/TinyCryptids/PAK and PROOF.md).
"""
