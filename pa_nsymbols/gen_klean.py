# subroutine nodes with a hand-written `*_emb` lemma (PAK/Abs.lean, PAK/GenDet.lean): Lean index,
# expected name, A operation, lemma
PRIM = {20: ('pushwff().0', 'push', 'push_emb'), 26: ('par1().0', 'par1', 'par1_emb'),
        46: ('par2().0', 'par2', 'par2_emb'), 52: ('par3().0', 'par3', 'par3_emb'),
        32: ('cons().0', 'cons', 'cons_emb'), 40: ('select().0', 'select', 'select_emb'),
        82: ('drop().0', 'drop', 'drop_emb'), 2: ('if_not_decnz(prooflist,120).0', 'reload', 'reload_emb'),
        8: ('fn_125().0', 'zeroAc', 'zeroAc_emb'), 9: ('fn_127().0', 'zeroP1', 'zeroP1_emb'),
        10: ('fn_129().0', 'zeroP3', 'zeroP3_emb'), 81: ('s#146', 'gen', 'gen_emb'),
        83: ('s#148', 'det', 'det_emb')}
DECODE = {15: 'decAc', 16: 'decP1', 18: 'decP2', 19: 'decP3'}
B6 = [72, 73, 74, 18, 72, 74]


def abstract(c):
    """For every node made of subroutines: (ops, start, end, steps).  ops: its A operations; start:
    'emb' (it runs on A.emb a) or 'pre' (on b6pre b); end: 'emb', 'pre' (it leaves b6pre) or
    'halt' (its outcome is the halt test's); steps: (kind, op, node) in order."""
    order, idx = numbering(c)
    S = {k: [parse_slot(t) for t in sl] for k, sl in lean_slots(c, idx, order).items()}
    for k, (nm, _, _) in PRIM.items():
        assert c.names[order[k]] == nm, (k, c.names[order[k]], nm)
    assert S[11] == [('node', 12), ('node', 7)] and S[85] == [('node', 86), ('halt', None)]
    comp = {}

    def expand(k):
        if k in comp:
            return comp[k]
        sl, ops, steps = S[k], [], []
        state = 'pre' if k == 80 else 'emb'
        start, j = state, 0
        while j < len(sl):
            kind, a = sl[j]
            last = j == len(sl) - 1
            if state == 'pre':
                assert kind == 'node'
                if a == 16:                       # B6a's check, last loop
                    ops.append('b6check')
                    steps.append(('b6check', None, None))
                    state = 'emb'
                    j += 1
                    continue
                sub = expand(a)
                assert sub and sub[1] == 'pre', (k, a)
                ops += sub[0]
                steps.append(('comp', sub[2], a))
                state = sub[2]
                j += 1
                continue
            if kind == 'node' and a == 11 and not last and sl[j + 1][0] == 'node' and sl[j + 1][1] in DECODE:
                op = DECODE[sl[j + 1][1]]
                ops.append(op)
                steps.append(('dec', op, None))
                j += 2
            elif sl[j:j + 6] == [('node', b) for b in B6]:
                steps.append(('b6pre', None, None))
                state = 'pre'
                j += 6
            elif (kind, a) == ('dec', 2) and sl[j + 1:] == [('node', 85)]:
                steps.append(('halt', None, None))
                state = 'halt'
                j += 2
            elif (kind, a) == ('inc', 2):
                ops.append('incT')
                steps.append(('incT', None, None))
                j += 1
            elif kind == 'node' and a in PRIM:
                ops.append(PRIM[a][1])
                steps.append(('prim', PRIM[a][1], a))
                j += 1
            elif kind == 'node':
                sub = expand(a)
                if sub is None or sub[1] != 'emb':
                    comp[k] = None
                    return None
                ops += sub[0]
                steps.append(('comp', sub[2], a))
                state = sub[2]
                j += 1
            else:
                comp[k] = None
                return None
            if state == 'halt':
                assert j == len(sl), (k, sl)
        comp[k] = (ops, start, state, steps)
        return comp[k]
    expand(0)
    return S, comp


