def nodes_lean(c):
    order, idx = numbering(c)
    S = lean_slots(c, idx, order)
    post, seen = [], set()

    def visit(k):
        if k in seen:
            return
        seen.add(k)
        for t in S[k]:
            kind, a = parse_slot(t)
            if kind == 'node':
                visit(a)
        post.append(k)
    visit(0)
    name = {k: c.names[i] for k, i in enumerate(order)}
    # the special nodes, found by shape
    unpairs, pair, lock = {}, None, None
    for k, sl in S.items():
        ks = [parse_slot(t) for t in sl]
        if [x[0] for x in ks] == ['dec', 'inc', 'node', 'cnt'] and ks[1] == ('inc', 9) and ks[3] == ('cnt', 0):
            C = ks[2][1]
            B = parse_slot(S[C][0])[1]
            unpairs[k] = (ks[0][1], C, B)
        if [x[0] for x in ks] == ['node', 'dec', 'inc', 'node', 'node', 'jmp'] and ks[1] == ('dec', 2):
            pair = (k, ks[0][1], ks[3][1])
        if [x[0] for x in ks] == ['dec', 'node', 'node', 'brk'] and ks[0] == ('dec', 6):
            lock = (k, ks[1][1], ks[2][1])
    assert len(unpairs) == 2 and pair and lock, (unpairs, pair, lock)
    steps = {C: (U, B) for U, (r, C, B) in unpairs.items()}

    def ss(t):
        kind, a = parse_slot(t)
        return f'.ch {a} d{a}' if kind == 'node' else f'.op ({t})'

    def smatch(sl, tail=None):
        parts = []
        for t in sl:
            kind, a = parse_slot(t)
            parts += ['rfl', f'e{a}'] if kind == 'node' else ['rfl', 'rfl']
        parts.append(tail if tail else 'rfl')
        return '⟨' + ', '.join(parts) + '⟩'

    L = ['import TinyCryptids.PAK.Shape', 'import TinyCryptids.PA.Pair', '',
         '/-! Every node of the program tree: its denotation `d<i>` (outcome and registers) and the',
         'proof `e<i>` that the node runs it, generated by `pa_nsymbols/gen_klean.py`.  Nodes without',
         'loops are `den` of their slots (`straight_sound`); loops are `zero_sound`, `xfer_sound`,',
         '`xfer2_sound`, or, for the pairing loops and `if_eq`\'s lockstep, `loop_sound` with a',
         'closed form. -/', '', 'namespace TMK.PA', '', 'open TM.PA (R)', '']
    kinds = {}
    for k in post:
        sl = S[k]
        ks = [parse_slot(t) for t in sl]
        L.append(f'-- {k}: {name[k]}')
        if k in unpairs:
            r, C, B = unpairs[k]
            L.append(UNPAIR.format(U=k, r=r, C=C, name=name[k]).strip('\n'))
            kinds[k] = 'unpair'
        elif pair and k == pair[0]:
            L.append(PAIR.format(P=k, W=pair[1], T=pair[2]).strip('\n'))
            kinds[k] = 'pair'
        elif lock and k == lock[0]:
            L.append(LOCK.format(L=k, M=lock[1], Z=lock[2]).strip('\n'))
            kinds[k] = 'lock'
        elif [x[0] for x in ks] == ['dec', 'cnt'] and ks[1] == ('cnt', 0):
            r = ks[0][1]
            L.append(f'def d{k} : Den := fun s => (.brk 0, s.set {r} 0)')
            L.append(f'theorem e{k} : ∀ s, Ex {k} s (d{k} s).1 (d{k} s).2 :=')
            L.append(f'  zero_sound (i := {k}) (k := 0) (by decide) ⟨rfl, rfl, rfl, rfl, rfl⟩ (fun _ => rfl)')
            kinds[k] = 'zero'
        elif [x[0] for x in ks] == ['dec', 'inc', 'cnt'] and ks[2] == ('cnt', 0):
            r, x = ks[0][1], ks[1][1]
            L.append(f'def d{k} : Den := fun s => (.brk 0, (s.set {r} 0).set {x} (s.get {x} + s.get {r}))')
            L.append(f'theorem e{k} : ∀ s, Ex {k} s (d{k} s).1 (d{k} s).2 :=')
            L.append(f'  xfer_sound (i := {k}) (k := 0) (by decide) (by decide) ⟨rfl, rfl, rfl, rfl, rfl, rfl, rfl⟩ (fun _ => rfl)')
            kinds[k] = 'xfer'
        elif ([x[0] for x in ks] == ['dec', 'node', 'cnt'] and ks[2] == ('cnt', 0)
              and [parse_slot(t)[0] for t in S[ks[1][1]]] == ['inc', 'inc']):
            r, cc = ks[0][1], ks[1][1]
            x, y = [parse_slot(t)[1] for t in S[cc]]
            L.append(f'def d{k} : Den := fun s => (.brk 0, ((s.set {r} 0).set {x} (s.get {x} + s.get {r})).set {y} (s.get {y} + s.get {r}))')
            L.append(f'theorem e{k} : ∀ s, Ex {k} s (d{k} s).1 (d{k} s).2 :=')
            L.append(f'  xfer2_sound (i := {k}) (k := 0) (by decide) (by decide) (by decide) (by decide) (g := d{cc}) (fun _ => rfl)')
            L.append(f'    ⟨rfl, rfl, rfl, e{cc}, rfl, rfl, rfl⟩ (fun _ => rfl)')
            kinds[k] = 'xfer2'
        elif len(ks) >= 3 and ks[-1][0] == 'jmp' and ks[-1][1] == len(ks) - 3 and [x[0] for x in ks[-3:-1]] == ['dec', 'inc']:
            j = len(ks) - 3
            r, x = ks[-3][1], ks[-2][1]
            pre = ', '.join(ss(t) for t in sl[:j])
            F = f'fun s => (.brk 0, (s.set {r} 0).set {x} (s.get {x} + s.get {r}))'
            tail = (f'xfer_sound (i := {k}) (k := {j}) (by decide) (by decide) '
                    f'⟨rfl, rfl, rfl, rfl, rfl, rfl, rfl⟩ (fun _ => rfl)')
            L.append(f'def d{k} : Den := den [{pre}, .tail ({F})]')
            L.append(f'theorem e{k} : ∀ s, Ex {k} s (d{k} s).1 (d{k} s).2 :=')
            L.append(f'  straight_sound (by decide) {smatch(sl[:j], tail)} rfl')
            kinds[k] = 'jtail'
        else:
            assert not any(x[0] == 'jmp' or x == ('cnt', 0) for x in ks), (k, sl)
            L.append(f'def d{k} : Den := den [{", ".join(ss(t) for t in sl)}]')
            L.append(f'theorem e{k} : ∀ s, Ex {k} s (d{k} s).1 (d{k} s).2 :=')
            L.append(f'  straight_sound (by decide) {smatch(sl)} rfl')
            kinds[k] = 'straight'
        if k in steps:
            U, B = steps[k]
            L.append(SPECIAL_UNPAIR.format(C=k, B=B, U=U).strip('\n'))
        L.append('')
    L += ['end TMK.PA', '']
    return '\n'.join(L), kinds


