def lean_slots(c, idx, order):
    """Lean index -> list of slot terms (strings like '.dec 0', '.node 3')"""
    return {k: [slot_lean(c, idx, i, j, x) for j, x in enumerate(c.nodes[i])] for k, i in enumerate(order)}


def parse_slot(t):
    p = t.split()
    return (p[0][1:], int(p[1]) if len(p) > 1 else None)


