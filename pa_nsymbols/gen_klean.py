def iter_lean(c):
    """Comp.lean: the composite subroutines and main's chunks on the abstract registers"""
    S, comp = abstract(c)
    order, idx = numbering(c)
    post, seen = [], set()

    def visit(k):
        if k in seen or (k in PRIM and k not in (81, 83)):
            return
        seen.add(k)
        for kind, a in S[k]:
            if kind == 'node':
                visit(a)
        if comp.get(k) or k in (81, 83):
            post.append(k)
    visit(0)
    L = ['import TinyCryptids.PAK.Abs', '',
         '/-! The composite subroutines and main\'s chunks on the abstract registers, generated by',
         '`pa_nsymbols/gen_klean.py`: each node `X` made of subroutines computes `k<X>` (`k<X>_emb`).',
         'B6a\'s check runs across two of main\'s chunks: the first ends in `b6pre`, the second starts',
         'from it and ends in the halt test. -/', '',
         'namespace TMK.PA', '', 'open TM.PA (R A)', '']
    for k in post:
        if k in (81, 83):
            L.append(GENDET[k])
            continue
        ops, start, end, steps = comp[k]
        arg = 'b' if start == 'pre' else 'a'
        cur, rws = arg, []
        for kind, op, a in steps:
            if kind == 'prim':
                rws.append(f'run_ch ({PRIM[a][2]} {cur})')
                cur = f'(A.{op} {cur})'
            elif kind == 'dec':
                rws += [f'run_ch (dec_emb {cur})', f'run_ch ({op}_emb {cur})']
                cur = f'(A.{op} {cur})'
            elif kind == 'incT':
                rws.append(f'run_incT _ {cur}')
                cur = f'(A.incT {cur})'
            elif kind == 'b6pre':
                rws.append(f'b6pre_run {cur}')
            elif kind == 'b6check':
                rws.append(f'run_ch (b6check_emb {cur})')
                cur = f'(A.b6check {cur})'
            elif kind == 'halt':
                rws.append(f'halt_run {cur}')
            elif kind == 'comp':
                rws.append(f'{"run_last_h" if op == "halt" else "run_ch"} (k{a}_emb {cur})')
                cur = f'(k{a} {cur})'
        L.append(f'-- {k}: {c.names[order[k]]}')
        L.append(f'def k{k} ({arg} : A) : A := {cur}')
        lhs = f'd{k} (b6pre b)' if start == 'pre' else f'd{k} a.emb'
        rhs = {'emb': f'(.brk 0, (k{k} {arg}).emb)', 'pre': f'(.brk 0, b6pre (k{k} {arg}))',
               'halt': f'(if (k{k} {arg}).top = 1 then .halt else .brk 0, (A.haltT (k{k} {arg})).emb)'}[end]
        L.append(f'theorem k{k}_emb ({arg} : A) : {lhs} = {rhs} := by')
        L.append(f'  simp only [d{k}, den]')
        L.append(f'  rw [{", ".join(rws)}]')
        L.append('  rfl')
        L.append('')
    L += ['end TMK.PA', '']
    return '\n'.join(L), comp


