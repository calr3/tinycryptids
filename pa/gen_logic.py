"""Emit lean/TinyCryptids/PA/Luk.lean from cd_proofs.txt (cd_search.py): Hilbert derivations in
Lukasiewicz's system B1-B3 of the propositional laws the proof needs, one lemma per derived
theorem (modus ponens on two earlier ones, instantiated by the unifier).

    python3 gen_logic.py
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import cd_search as cd, gen_lean

HEADER = '''import TinyCryptids.Defs

/-! Derivations in Łukasiewicz's propositional system (the axioms B1–B3 of T), generated by
`pa/gen_logic.py` from a condensed-detachment search (`pa/cd_search.py`).  `Prop3 Ax` says the
axiom set has B1–B3; each lemma below is modus ponens on two earlier ones. -/

namespace TM.PA

open TinyCryptids Wff

/-- closure of an axiom set under modus ponens and generalisation -/
inductive Prov (Ax : Wff → Prop) : Wff → Prop
  | ax {φ : Wff} : Ax φ → Prov Ax φ
  | mp {φ ψ : Wff} : Prov Ax (imp φ ψ) → Prov Ax φ → Prov Ax ψ
  | gen (x : Nat) {φ : Wff} : Prov Ax φ → Prov Ax (all x φ)

/-- the axiom set proves Łukasiewicz's axioms B1–B3 -/
structure Prop3 (Ax : Wff → Prop) : Prop where
  b1 : ∀ φ ψ χ, Prov Ax (imp (imp φ ψ) (imp (imp ψ χ) (imp φ χ)))
  b2 : ∀ φ, Prov Ax (imp (imp (neg φ) φ) φ)
  b3 : ∀ φ ψ, Prov Ax (imp φ (imp (neg φ) ψ))

variable {Ax : Wff → Prop} (hP : Prop3 Ax)
include hP
'''

VN = 'pqrstuvwxyzabcdefghijklmno'


def lean(t, names):
    if isinstance(t, int): return names[t]
    if t[0] == 'N': return f'(neg {lean(t[1], names)})'
    return f'(imp {lean(t[1], names)} {lean(t[2], names)})'


def nvars(t):
    return cd.maxvar(t) + 1


def main():
    lines = open(os.path.join(HERE, 'cd_proofs.txt')).read().splitlines()
    thm, proof, targets = {}, {}, {}
    for l in lines:
        p = l.split()
        if p[0] == 'target':
            targets[p[1]] = p[2]; continue
        name, f = p[0], p[1]
        thm[name] = cd.canon(cd.parse(f))
        proof[name] = (p[2], p[3]) if len(p) > 3 else None
    out = [HEADER]
    lname = {}
    for name in [l.split()[0] for l in lines if l.split()[0] != 'target']:
        t = thm[name]
        k = nvars(t)
        args = ' '.join(VN[i] for i in range(k))
        ln = {'B1': 'luk1', 'B2': 'luk2', 'B3': 'luk3'}.get(name, 'luk_' + name)
        lname[name] = ln
        names = [VN[i] for i in range(k)]
        stmt = f'theorem {ln} ({args} : Wff) : Prov Ax {lean(t, names)} :='
        if proof[name] is None:
            body = {'B1': 'hP.b1 p q r', 'B2': 'hP.b2 p', 'B3': 'hP.b3 p q'}[name]
        else:
            M, Nn = proof[name]
            maj, mnr = thm[M], thm[Nn]
            kk = cd.maxvar(maj) + 1
            mn = cd.shift(mnr, kk)
            s = cd.unify(maj[1], mn, {})
            res = cd.subst(maj[2], s)
            # map the result's variables to the canonical ones of t
            m = {}
            def go(a, b):
                if isinstance(a, int):
                    assert m.get(a, b) == b; m[a] = b; return
                for x, y in zip(a[1:], b[1:]): go(x, y)
            go(res, t)
            def inst(v):
                u = cd.subst(v, s)
                def tr(u):
                    if isinstance(u, int): return names[m[u]] if u in m else 'p' if names else '(eq 0 0)'
                    if u[0] == 'N': return f'(neg {tr(u[1])})'
                    return f'(imp {tr(u[1])} {tr(u[2])})'
                return tr(u)
            a_maj = ' '.join(inst(v) for v in range(nvars(maj)))
            a_mnr = ' '.join(inst(v + kk) for v in range(nvars(mnr)))
            body = f'Prov.mp ({lname[M]} hP {a_maj}) ({lname[Nn]} hP {a_mnr})'
        out.append(stmt)
        out.append('  ' + body)
        out.append('')
    # the targets under readable names
    for tg, nm in targets.items():
        f = cd.canon(cd.parse(cd.TARGETS[tg]))
        k = nvars(f)
        names = [VN[i] for i in range(k)]
        args = ' '.join(names)
        # the derived theorem is more general than the target: instantiate
        s = cd.match(thm[nm], f, {})
        inst = ' '.join(lean(s[v], names) if v in s else 'p' for v in range(nvars(thm[nm])))
        out.append(f'theorem {tg} ({args} : Wff) : Prov Ax {lean(f, names)} :=')
        out.append(f'  {lname[nm]} hP {inst}')
        out.append('')
    out.append('end TM.PA')
    path = os.path.join(gen_lean.LEAN, 'Luk.lean')
    with open(path, 'w') as fh:
        fh.write('\n'.join(out) + '\n')
    print('written', path)


if __name__ == '__main__':
    main()
