"""Emit lean/TinyCryptids/PA/Iter.lean: main's chain of subroutines as one operation on the
abstract registers `A` (Abs.lean), grouped into the decoding and one function per candidate,
and the proof that node 0 (main) computes it (`main_emb`).

    python3 gen_iter.py
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
sys.setrecursionlimit(100000)
import program, gen_lean, gen_nodes

# subroutine nodes with an `*_emb` lemma in Abs.lean (TMBuilder names)
OPS = {'pushwff().0': 'push', 'n_120.0': 'push', 'par1().0': 'par1', 'par2().0': 'par2',
       'par3().0': 'par3', 'cons().0': 'cons', 'select().0': 'select',
       'if_not_decnz(prooflist,79).0': 'reload', 'fn_82().0': 'zeroAc', 'fn_83().0': 'zeroP1',
       'fn_84().0': 'zeroP3', 'main().78.0': 'gen', 'main().79.0': 'det'}
EMB = {'push': 'push_emb', 'par1': 'par1_emb', 'par2': 'par2_emb', 'par3': 'par3_emb',
       'cons': 'cons_emb', 'select': 'select_emb', 'reload': 'reload_emb', 'zeroAc': 'zeroAc_emb',
       'zeroP1': 'zeroP1_emb', 'zeroP3': 'zeroP3_emb', 'gen': 'gen_emb', 'det': 'det_emb'}
DECODE = {'while_decnz(scratch1,3.axiomcode.inc).0': 'decAc',
          'while_decnz(scratch1,3.param1.inc).0': 'decP1',
          'while_decnz(scratch1,3.param2.inc).0': 'decP2',
          'while_decnz(scratch1,3.param3.inc).0': 'decP3'}
B6 = ['while_decnz(param3,53).0', 'while_decnz(param1,3.param3.inc).0',
      'if_eq(param2,scratch2,58).0', 'while_decnz(scratch1,3.param2.inc).0',
      'while_decnz(param3,53).0', 'if_eq(param2,scratch2,58).0',
      'while_decnz(scratch1,3.param1.inc).0']


def main():
    b = program.build(merge_equal=False)
    order, children, names, idx = gen_lean.dag_of(b)
    ch = [(gen_nodes.parse(c), gen_nodes.parse(d)) for c, d in children]
    ops_of = {i: OPS[n] for i, n in enumerate(names) if n in OPS}
    unfold_f, unfold_h = set(), set()

    def flat(c):
        k, v = c
        if k == 'inc':
            assert v == 2
            return ['incT']
        assert k == 'node', c
        if v in ops_of:
            return [ops_of[v]]
        unfold_f.add(v)
        return flat(ch[v][0]) + flat(ch[v][1])

    # main's chain: main().k = (element, main().(k+1)), ending with the halt test
    chain, i = [], 0
    while True:
        unfold_f.add(i); unfold_h.add(i)
        c, d = ch[i]
        chain.append(c[1])
        if names[d[1]] == 'main().80':
            last = d[1]; break
        i = d[1]
    ops, k = [], 0
    while k < len(chain):
        e = chain[k]
        if names[e] == 'main().n_109.0':
            ops.append(DECODE[names[chain[k + 1]]]); k += 2; continue
        if [names[x] for x in chain[k:k + 7]] == B6:
            ops.append('b6check'); k += 7; continue
        ops += flat(('node', e)); k += 1

    # group: decoding, v_0, one function per candidate (ending in select), GEN, DET
    assert ops[:8] == ['reload', 'zeroAc', 'zeroP1', 'zeroP3', 'decAc', 'decP1', 'decP2', 'decP3']
    assert ops[8] == 'push' and ops[-2:] == ['gen', 'det']
    rest = ops[9:-2]
    cands, cur = [], []
    for o in rest:
        cur.append(o)
        if o == 'select':
            cands.append(cur); cur = []
    assert cur == []
    names_c = list(program.ORDER) + ['B6a']
    assert len(cands) == len(names_c), (len(cands), names_c)

    L = ['import TinyCryptids.PA.Abs', '',
         '/-! Main\'s chain of subroutines as one operation on the abstract registers, generated by',
         '`pa/gen_iter.py`: the decoding, `v_0` (push the last theorem), one function per candidate',
         '(its formula built on the stack, then `select`), GEN and DET; `main_emb` proves that node 0',
         'computes it, followed by the halt test. -/', '',
         'namespace TM.PA', '', 'namespace A', '',
         'def decode (a : A) : A := a.reload.zeroAc.zeroP1.zeroP3.decAc.decP1.decP2.decP3', '']
    for nm, ops_c in zip(names_c, cands):
        body = '.'.join(ops_c)
        L.append(f'/-- candidate {nm} -/')
        L.append(f'def cand{nm} (a : A) : A := a.{body}')
        L.append('')
    L.append('/-- one iteration of main, up to the halt test -/')
    L.append('def iter (a : A) : A := a.decode.push.' + '.'.join(f'cand{nm}' for nm in names_c) + '.gen.det')
    L += ['', 'end A', '', 'open N', '']
    fs = ', '.join(f'f{j}' for j in sorted(unfold_f))
    hs = ', '.join(f'h{j}' for j in sorted(unfold_h))
    lem = ', '.join(sorted(set(EMB.values()))) + ', incT_emb, push_emb\', decAc_emb, decP1_emb, decP2_emb, decP3_emb, b6check_emb'
    L += ['set_option maxRecDepth 10000 in',
          '/-- main computes `A.iter`, then the halt test (it halts iff `topwff` is 1) -/',
          'theorem main_emb (a : A) : f0 a.emb = (A.haltT a.iter).emb ∧ h0 a.emb = decide (a.iter.top = 1) := by',
          f'  have e1 : f0 a.emb = f{last} (A.iter a).emb := by',
          f'    simp only [{fs}, {lem}]',
          '    rfl',
          f'  have e2 : h0 a.emb = h{last} (A.iter a).emb := by',
          f'    simp only [{fs}, {hs}, {lem}]',
          '    rfl',
          '  rw [e1, e2]',
          '  exact halt_emb _', '',
          'end TM.PA', '']
    path = os.path.join(gen_lean.LEAN, 'Iter.lean')
    with open(path, 'w') as f:
        f.write('\n'.join(L))
    print(len(ops), 'ops,', len(cands), 'candidates,', len(unfold_f), 'unfolded nodes')


if __name__ == '__main__':
    main()
