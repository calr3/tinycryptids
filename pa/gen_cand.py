"""Emit lean/TinyCryptids/PA/Cand.lean: the candidate formulas of program.py (each axiom in its
form and relabelling, VARIANTS/FORMS) as codes, and for each candidate the lemma that its chain
of operations keeps that code (or the selection when axiomcode is 0).

    python3 gen_cand.py
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import program, gen_lean

OPC = {'eq': 'eqC', 'el': 'elC', 'imp': 'impC', 'all': 'allC', 'ex': 'exC', 'and': 'andC'}


def term(name):
    perm, form = program.VARIANTS.get(name, ((1, 2, 3), 0))
    text = program.PA.FORMS[name][form]
    for k, v in program.PA.E_PARTS.items():
        text = text.replace(k, v)
    par = {'a': f'p{perm[0]}', 'b': f'p{perm[1]}', 'c': f'p{perm[2]}'}
    st = []
    for t in text.split():
        if t in par:
            st.append(par[t])
        elif t[0] == 'v' and t[1:].isdigit():
            st.append(t[1:])
        elif t == 'neg':
            st.append(f'(negC {st.pop()})')
        else:
            y, x = st.pop(), st.pop()
            st.append(f'({OPC[t]} {x} {y})')
    assert len(st) == 1
    return st[0], perm, form


def main():
    names_c = list(program.ORDER) + ['B6a']
    L = ['import TinyCryptids.PA.Iter', 'import TinyCryptids.PA.Code', '',
         '/-! The candidates of an iteration, generated by `pa/gen_cand.py`: each axiom of the',
         'theory in the form and relabelling of `program.py` (`VARIANTS`, `FORMS`), as a code over',
         'the parameters `p1 p2 p3`, and the lemma that its chain of operations computes it. -/', '',
         'namespace TM.PA', '',
         '-- every candidate takes all three parameters, some ignore one',
         'set_option linter.unusedVariables false', '']
    simp = ('A.push_a, A.par1_a, A.par2_a, A.par3_a, A.push_ts, A.incT_ts, A.par1_ts, A.par2_ts, '
            'A.par3_ts, A.cons_ts, A.select_ts, A.b6check_ts, A.ts_ts, A.ts_top, A.ts_stk, A.ts_p1, A.ts_p2, A.ts_p3, A.ts_ac')
    for nm in names_c:
        t, perm, form = term(nm)
        L.append(f'/-- {nm} (formal parameters `a b c` = `p{perm[0]} p{perm[1]} p{perm[2]}`, form {form}) -/')
        L.append(f'def ax{nm} (p1 p2 p3 : Nat) : Nat := {t}')
        L.append('')
        if nm == 'B6a':
            L.append(f'theorem cand{nm}_eq (a : A) : a.cand{nm} = {{ a with ac := a.ac - 1, p2 := 0, p3 := 0, '
                     f'top := if a.ac = 0 then a.top else if a.p2 = a.p3 ∨ a.p3 = a.p1 then 0 else ax{nm} a.p1 a.p2 a.p3 }} := by')
            L.append(f'  simp only [A.cand{nm}, {simp}]')
            L.append(f'  rfl')
        else:
            L.append(f'theorem cand{nm}_eq (a : A) : a.cand{nm} = {{ a with ac := a.ac - 1, '
                     f'top := if a.ac = 0 then a.top else ax{nm} a.p1 a.p2 a.p3 }} := by')
            L.append(f'  simp only [A.cand{nm}, {simp}]')
            L.append(f'  rfl')
        L.append('')
    L += ['end TM.PA', '']
    path = os.path.join(gen_lean.LEAN, 'Cand.lean')
    with open(path, 'w') as f:
        f.write('\n'.join(L))
    print('written', path)


if __name__ == '__main__':
    main()
