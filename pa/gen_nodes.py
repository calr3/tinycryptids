"""Emit lean/TinyCryptids/PA/Nodes.lean: for every node of the decision DAG (gen_lean.dag_of),
its effect on the registers (`f<i>`), its outcome, and a proof `e<i>` that running the node
has that effect and outcome, using the shape lemmas of Prog.lean.

Shapes (checked here; anything else is an error):
  zero      (decnz r, continue 1)                       r := 0
  while     (decnz r, Y), Y = (B, continue 2)            loopN r B
  seq       (C, D), both done                            D after C
  breaker   (break 0, D)                                 D
  test      (decnz r, D), D done or break 1              done if r = 0, else D's outcome
  testSeq   (C, D), C a test, D done                     D only if C's test was done
  lockstep  if_eq's loop                                 Prog.ex_lockstep
  seqB1     (C, break 1)                                 break 1
  haltTest  (C, halt), C a test                          halt iff C was done
  ifHalt    (decnz r, D), D halting                      D's outcome when r > 0
  seqH      (C, D), C done, D halting
The nodes `Y` of while loops and the inner nodes of if_eq's loop get no spec of their own.

    python3 gen_nodes.py
"""
import os, sys, re
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
sys.setrecursionlimit(100000)
import program, gen_lean

FIELD = ['pl', 'np', 'top', 'ws', 'ac', 'p1', 'p2', 'p3', 's1', 's2']


def parse(c):
    t = c.split()
    k = t[0][1:]
    return (k, int(t[1]) if len(t) > 1 else None)


def main():
    b = program.build(merge_equal=False)
    order, children, names, idx = gen_lean.dag_of(b)
    N = len(order)
    ch = [(parse(c), parse(d)) for c, d in children]

    kind, info = {}, {}
    skip = set()          # nodes handled inside a pattern
    out = {}              # outcome type: 'b0', 'b1', ('test', pexpr), ('halt',)

    def is_while(i):
        (ck, cv), (dk, dv) = ch[i]
        return ck == 'dec' and dk == 'node' and ch[dv][1] == ('cnt', 2)

    def is_lockstep(i):
        (ck, cv), (dk, dv) = ch[i]
        if not (ck == 'dec' and dk == 'node'): return False
        (jc, jcv), (jd, jdv) = ch[dv]
        return jc == 'node' and jd == 'node' and ch[jcv][0][0] == 'dec' and ch[jcv][1] == ('cnt', 2)

    # mark pattern-internal nodes
    for i in range(N):
        if is_while(i):
            skip.add(ch[i][1][1])
        elif is_lockstep(i):
            j = ch[i][1][1]
            skip.add(j); skip.add(ch[j][0][1])

    # topological order: children first
    seen, topo = set(), []
    def visit(i):
        if i in seen: return
        seen.add(i)
        for k, v in ch[i]:
            if k == 'node': visit(v)
        topo.append(i)
    for i in range(N): visit(i)

    def ocls(c):
        k, v = c
        if k == 'node': return out[v]
        if k == 'inc': return 'b0'
        if k == 'brk': return f'b{v}' if v in (0, 1) else None
        if k == 'halt': return 'haltleaf'
        return None

    for i in topo:
        if i in skip: continue
        (ck, cv), (dk, dv) = ch[i]
        if ck == 'dec' and (dk, dv) == ('cnt', 1):
            kind[i] = 'zero'; out[i] = 'b0'
        elif is_while(i):
            kind[i] = 'while'; out[i] = 'b0'
        elif is_lockstep(i):
            kind[i] = 'lockstep'; out[i] = ('test', i)
        elif (ck, cv) == ('brk', 0):
            assert ocls(ch[i][1]) == 'b0', i
            kind[i] = 'breaker'; out[i] = 'b0'
        elif ck == 'dec' and ocls(ch[i][1]) in ('b0', 'b1'):
            kind[i] = 'test'
            out[i] = 'b0' if ocls(ch[i][1]) == 'b0' else ('test', i)
        elif ck == 'dec' and isinstance(ocls(ch[i][1]), tuple) and ocls(ch[i][1])[0] == 'halt':
            kind[i] = 'ifHalt'; out[i] = ('halt',)
        elif ocls(ch[i][0]) == 'b0' and ocls(ch[i][1]) == 'b0':
            kind[i] = 'seq'; out[i] = 'b0'
        elif ocls(ch[i][0]) == 'b0' and (dk, dv) == ('brk', 1):
            kind[i] = 'seqB1'; out[i] = 'b1'
        elif isinstance(ocls(ch[i][0]), tuple) and ocls(ch[i][0])[0] == 'test' and ocls(ch[i][1]) == 'b0':
            kind[i] = 'testSeq'; out[i] = 'b0'
        elif isinstance(ocls(ch[i][0]), tuple) and ocls(ch[i][0])[0] == 'test' and dk == 'halt':
            kind[i] = 'haltTest'; out[i] = ('halt',)
        elif ocls(ch[i][0]) == 'b0' and isinstance(ocls(ch[i][1]), tuple) and ocls(ch[i][1])[0] == 'halt':
            kind[i] = 'seqH'; out[i] = ('halt',)
        else:
            raise SystemExit(f'node {i} {names[i]} {children[i]}: no shape')

    L = ['import TinyCryptids.PA.Prog', 'import TinyCryptids.PA.Dag', '',
         '/-! Every node of the DAG: its effect `f<i>` on the registers, its outcome, and the proof',
         '`e<i>`.  Generated by `pa/gen_nodes.py` from the shapes of `Prog.lean`. -/', '',
         'namespace TM.PA.N', '', 'open TM.PA', '']

    def F(c):  # effect term of a child applied to s
        k, v = c
        if k == 'node': return f'f{v}'
        if k == 'inc': return f'(fun s : R => s.inc {v})'
        raise ValueError(c)

    def E(c, s):
        k, v = c
        if k == 'node': return f'(e{v} {s})'
        if k == 'inc': return f'(Ex.inc {v} {s})'
        raise ValueError(c)

    has_eq = set()

    def deps(c):
        """simp set unfolding the effect of child c down to closed forms"""
        res, todo, seen2 = [], [c], set()
        while todo:
            k, v = todo.pop()
            if k != 'node' or v in seen2: continue
            seen2.add(v)
            if v in has_eq:
                res.append(f'f{v}_eq'); continue
            res.append(f'f{v}')
            if kind.get(v) in ('test', 'testSeq', 'lockstep', 'haltTest', 'ifHalt'):
                res.append(f'p{v}') if kind.get(v) in ('test', 'lockstep') and out[v] != 'b0' else None
            for cc in ch[v]:
                todo.append(cc)
        return res

    def body_eq(i, j):
        """closed form of a while node whose body j is inc / inc,inc"""
        r = ch[i][0][1]
        B = ch[j][0]
        if B[0] == 'inc':
            ts = [B[1]]
        elif B[0] == 'node' and ch[B[1]][0][0] == 'inc' and ch[B[1]][1][0] == 'inc':
            ts = [ch[B[1]][0][1], ch[B[1]][1][1]]
        else:
            return None
        if r in ts or len(set(ts)) != len(ts): return None
        return r, ts

    for i in topo:
        if i in skip: continue
        (ck, cv), (dk, dv) = ch[i]
        L.append(f'-- {i}: {names[i]}')
        k = kind[i]
        if k == 'zero':
            r = cv
            L.append(f'def f{i} (s : R) : R := {{ s with {FIELD[r]} := 0 }}')
            L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (.brk 0) (f{i} s) :=')
            L.append(f'  ex_zero (i := {i}) (r := {r}) rfl s')
        elif k == 'while':
            r = cv; j = dv; B = ch[j][0]
            g = F(B)
            L.append(f'def f{i} (s : R) : R := loopN {r} {g} (s.get {r}) s')
            be = body_eq(i, j)
            if names[i].startswith('pair(') and names[i].endswith('.1'):
                # pair's main loop: the body keeps the count only while in1 is 0
                m = re.match(r'pair\((\w+),(\w+),(\w+)\)', names[i])
                in1 = FIELD[gen_lean.REGS.index(m.group(2))]
                info[i] = in1
                L.append(f'theorem e{i} (s : R) (h : s.{in1} = 0) : Ex dag (.node {i}) s (.brk 0) (f{i} s) :=')
                L.append(f'  ex_while (i := {i}) (j := {j}) (r := {r}) rfl rfl {g} (fun s => {E(B, "s")})')
                L.append(f'    (fun s => s.{in1} = 0) (fun s hs _ => by simp [{", ".join(deps(B))}, hs] <;> omega) s h')
            else:
                L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (.brk 0) (f{i} s) :=')
                L.append(f'  ex_while\' (i := {i}) (j := {j}) (r := {r}) rfl rfl {g} (fun s => {E(B, "s")})')
                if B[0] == 'inc':
                    L.append(f'    (fun s => by simp) s')
                else:
                    L.append(f'    (fun s => by simp [{", ".join(deps(B))}] <;> (try split) <;> simp) s')
            if be:
                has_eq.add(i)
                r, ts = be
                upd = ', '.join([f'{FIELD[r]} := 0'] + [f'{FIELD[t]} := s.{FIELD[t]} + s.{FIELD[r]}' for t in ts])
                L.append(f'@[simp] theorem f{i}_eq (s : R) : f{i} s = {{ s with {upd} }} := by')
                if len(ts) == 1:
                    L.append(f'  simp only [f{i}]; rw [loopN_inc {r} {ts[0]} (by decide) _ s (Nat.le_refl _)]; simp')
                else:
                    if B[0] == 'node':
                        L.append(f'  have e : f{B[1]} = fun s => (s.inc {ts[0]}).inc {ts[1]} := rfl')
                        L.append(f'  simp only [f{i}, e]')
                    else:
                        L.append(f'  simp only [f{i}]')
                    L.append(f'  rw [loopN_inc2 {r} {ts[0]} {ts[1]} (by decide) (by decide) (by decide) _ s (Nat.le_refl _)]; simp')
        elif k == 'seq':
            c, d = ch[i]
            if d[0] == 'node' and d[1] in info and kind.get(d[1]) == 'while':
                pre = info[d[1]]
                L.append(f'def f{i} (s : R) : R := {F(d)} ({F(c)} s)')
                L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (.brk 0) (f{i} s) :=')
                L.append(f'  ex_seq (i := {i}) rfl {E(c, "s")} (e{d[1]} _ (by simp))')
            else:
                L.append(f'def f{i} (s : R) : R := {F(d)} ({F(c)} s)')
                L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (.brk 0) (f{i} s) :=')
                L.append(f'  ex_seq (i := {i}) rfl {E(c, "s")} {E(d, "_")}')
        elif k == 'breaker':
            d = ch[i][1]
            L.append(f'def f{i} (s : R) : R := {F(d)} s')
            L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (.brk 0) (f{i} s) :=')
            L.append(f'  ex_breaker (i := {i}) rfl {E(d, "s")} (by decide)')
        elif k == 'test':
            r = cv; d = ch[i][1]
            if d == ('brk', 1):
                fd, ed, kk = '(fun s : R => s)', '(fun s => Ex.brk 1 s)', 1
            else:
                fd, ed, kk = F(d), f'(fun s => e{d[1]} s)', (0 if out[d[1]] == 'b0' else 1)
            L.append(f'def f{i} (s : R) : R := if s.get {r} = 0 then s else {fd} (s.dec {r})')
            if kk == 0:
                L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (.brk 0) (f{i} s) := by')
                L.append(f'  have := ex_if (i := {i}) (r := {r}) (k := 0) rfl {fd} {ed} s')
                L.append(f'  simpa only [ite_self] using this')
            else:
                L.append(f'abbrev p{i} (s : R) : Prop := s.get {r} = 0')
                L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (if p{i} s then .brk 0 else .brk 1) (f{i} s) :=')
                L.append(f'  ex_if (i := {i}) (r := {r}) (k := 1) rfl {fd} {ed} s')
        elif k == 'lockstep':
            a = cv; j = dv; m = ch[j][0][1]; z = ch[j][1][1]; bb = ch[m][0][1]
            L.append(f'abbrev p{i} (s : R) : Prop := s.get {a} ≤ s.get {bb}')
            L.append(f'def f{i} (s : R) : R := if s.get {a} ≤ s.get {bb} then (s.set {a} 0).set {bb} (s.get {bb} - s.get {a})')
            L.append(f'  else (s.set {a} 0).set {bb} 0')
            L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (if p{i} s then .brk 0 else .brk 1) (f{i} s) :=')
            L.append(f'  ex_lockstep (i := {i}) (j := {j}) (m := {m}) (z := {z}) (a := {a}) (b := {bb}) (by decide)')
            L.append(f'    rfl rfl rfl (fun s => e{z} s) s')
        elif k == 'seqB1':
            c = ch[i][0]
            L.append(f'def f{i} (s : R) : R := {F(c)} s')
            L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (.brk 1) (f{i} s) :=')
            L.append(f'  ex_seqB1 (i := {i}) rfl {E(c, "s")}')
        elif k == 'testSeq':
            c, d = ch[i]
            L.append(f'def f{i} (s : R) : R := if p{c[1]} s then {F(d)} (f{c[1]} s) else f{c[1]} s')
            L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (.brk 0) (f{i} s) :=')
            L.append(f'  ex_test (i := {i}) rfl p{c[1]} f{c[1]} {F(d)} (fun s => e{c[1]} s) (fun s => {E(d, "s")}) s')
        elif k == 'haltTest':
            c = ch[i][0]
            L.append(f'def f{i} (s : R) : R := f{c[1]} s')
            L.append(f'def h{i} (s : R) : Bool := decide (p{c[1]} s)')
            L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (hres (h{i} s)) (f{i} s) :=')
            L.append(f'  ex_haltTest (i := {i}) rfl p{c[1]} f{c[1]} (fun s => e{c[1]} s) s')
        elif k == 'ifHalt':
            r = cv; d = ch[i][1]
            L.append(f'def f{i} (s : R) : R := if s.get {r} = 0 then s else f{d[1]} (s.dec {r})')
            L.append(f'def h{i} (s : R) : Bool := s.get {r} != 0 && h{d[1]} (s.dec {r})')
            L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (hres (h{i} s)) (f{i} s) :=')
            L.append(f'  ex_ifHalt (i := {i}) (r := {r}) rfl h{d[1]} f{d[1]} (fun s => e{d[1]} s) s')
        elif k == 'seqH':
            c, d = ch[i]
            L.append(f'def f{i} (s : R) : R := f{d[1]} ({F(c)} s)')
            L.append(f'def h{i} (s : R) : Bool := h{d[1]} ({F(c)} s)')
            L.append(f'theorem e{i} (s : R) : Ex dag (.node {i}) s (hres (h{i} s)) (f{i} s) :=')
            L.append(f'  ex_seqH (i := {i}) rfl {F(c)} f{d[1]} h{d[1]} (fun s => {E(c, "s")}) (fun s => e{d[1]} s) s')
        L.append('')

    # aliases for named subroutines
    L.append('/-! Names for the subroutine nodes (TMBuilder names). -/')
    L.append('')
    for i in topo:
        if i in skip: continue
        nm = names[i]
        m = re.fullmatch(r'(\w+)\(([^)]*)\)\.0', nm)
        if not m: continue
        args = m.group(2)
        alias = m.group(1) + ('_' + re.sub(r'[^A-Za-z0-9]+', '_', args).strip('_') if args else '')
        L.append(f'abbrev F.{alias} := f{i}   -- node {i}: {nm}')
    L += ['', 'end TM.PA.N', '']
    path = os.path.join(gen_lean.LEAN, 'Nodes.lean')
    with open(path, 'w') as f:
        f.write('\n'.join(L))
    from collections import Counter
    print(Counter(kind.values()), 'skipped', sorted(skip))


if __name__ == '__main__':
    main()
