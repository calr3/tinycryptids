"""Emit the Lean files for the PA machine from the builder (program.build()):

  lean/TinyCryptids/PA/Dag.lean   the decision DAG (`dag`, `main`), its certificate tables
  lean/TinyCryptids/PA/M309.lean  the 309-state machine (machines/pa_309.txt), the state map
                                  from the compiled machine and the transferred theorem

Nodes are numbered breadth-first from main (main = 0).

    python3 gen_lean.py
"""
import os, sys, re, functools
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
sys.setrecursionlimit(100000)
import program

LEAN = os.path.join(HERE, '..', 'lean', 'TinyCryptids', 'PA')
REGS = ['prooflist', 'nextproof', 'topwff', 'wffstack', 'axiomcode', 'param1', 'param2',
        'param3', 'scratch1', 'scratch2']


def dag_of(b):
    """(order, children, names): nodes breadth-first from main, children as Lean `Ch` terms."""
    seqs = b.sequences
    root = b.find_seq('main().0')
    order, seen = [root], {root}
    k = 0
    while k < len(order):
        for v in seqs[order[k]].seq:
            if isinstance(v, int) and v not in seen:
                seen.add(v); order.append(v)
        k += 1
    idx = {s: i for i, s in enumerate(order)}

    def ch(v):
        if isinstance(v, int):
            return f'.node {idx[v]}'
        if v.startswith('3.'):
            _, r, op = v.split('.')
            assert b.registers[r] is not None
            return f'.{"inc" if op == "inc" else "dec"} {REGS.index(r)}'
        if v.startswith('_break.'):
            return f'.brk {int(v.split(".")[1])}'
        if v.startswith('_continue.'):
            return f'.cnt {int(v.split(".")[1])}'
        assert v == 'halt', v
        return '.halt'
    children = [(ch(seqs[s].seq[0]), ch(seqs[s].seq[1])) for s in order]
    names = [seqs[s].name for s in order]
    return order, children, names, idx


def certs(b, order, idx):
    """zr[i]: most trailing zeros of a program counter reaching node i (main is entered by the
    root's 0 bit); dep[i]: the furthest cell of node i's bit (main reads cell 3)."""
    seqs = b.sequences
    n = len(order)
    zr = [None] * n; dep = [None] * n
    # longest-path DP in topological order (children after parents)
    indeg = [0] * n
    for s in order:
        for v in seqs[s].seq:
            if isinstance(v, int): indeg[idx[v]] += 1
    topo, ready = [], [0]
    while ready:
        i = ready.pop(); topo.append(i)
        for v in seqs[order[i]].seq:
            if isinstance(v, int):
                indeg[idx[v]] -= 1
                if indeg[idx[v]] == 0: ready.append(idx[v])
    assert len(topo) == n, 'not a DAG'
    zr[0] = 1; dep[0] = 3
    for i in topo:
        c, d = seqs[order[i]].seq
        if isinstance(c, int):
            j = idx[c]; zr[j] = max(zr[j] or 0, zr[i] + 1); dep[j] = max(dep[j] or 0, dep[i] + 1)
        if isinstance(d, int):
            j = idx[d]; zr[j] = max(zr[j] or 0, 0); dep[j] = max(dep[j] or 0, dep[i] + 1)
    return zr, dep


def lean_list(items, per=8):
    lines, cur = [], []
    for x in items:
        cur.append(x)
        if len(cur) == per:
            lines.append(', '.join(cur)); cur = []
    if cur: lines.append(', '.join(cur))
    return '[' + ',\n   '.join(lines) + ']'


def write_dag(b, path):
    order, children, names, idx = dag_of(b)
    zr, dep = certs(b, order, idx)
    out = ['import TinyCryptids.PA.Machine', '',
           '/-! The decision DAG of the 309-state machine, generated by `pa/gen_lean.py` from',
           '`pa/program.py` (nodes numbered breadth-first from `main`, which is node 0).', '',
           'Registers: ' + ', '.join(f'{i} {r}' for i, r in enumerate(REGS)) + '. -/', '',
           'namespace TM.PA', '',
           f'/-- Number of DAG nodes. -/\ndef nNodes : Nat := {len(order)}', '',
           '/-- `table[i]` = (car, cdr) of node `i`; TMBuilder names in the comments. -/',
           'def table : List (Ch × Ch) := [']
    for i, ((c, d), nm) in enumerate(zip(children, names)):
        out.append(f'  ({c}, {d}){"," if i + 1 < len(order) else ""}   -- {i}: {nm}')
    out += [']', '',
            'def dag (i : Nat) : Option (Ch × Ch) := table.get? i', '',
            'set_option maxRecDepth 100000 in',
            'theorem table_length : table.length = nNodes := by decide', '',
            '/-- Certificate: the most trailing zeros of a program counter reaching each node. -/',
            'def zrT : List Nat := ' + lean_list([str(x) for x in zr], 20), '',
            '/-- Certificate: the furthest cell read by each node. -/',
            'def depT : List Nat := ' + lean_list([str(x) for x in dep], 20), '',
            'end TM.PA', '']
    with open(path, 'w') as f:
        f.write('\n'.join(out))
    return order, children, names, idx, zr, dep


def clean(n):
    c = re.sub(r'[^A-Za-z0-9_]', '_', n)
    return 'S_' + c if c[0].isdigit() else c


FW = {  # TMBuilder framework state -> Lean `St` constructor
    '0a.boot1.A': '.bA', '0a.boot1.B': '.bB', '0a.boot1.C': '.bC', '0a.boot1.D': '.bD',
    '0a.boot1.E': '.bE', '0b.boot2.0': '.b2s0', '0b.boot2.1': '.b2s1', '0b.boot2.2': '.b2s2',
    '1b.reg.prep_1': '.prep1', '1b.reg.prep_2': '.prep2',
    '2b.reg.dec.check': '.dcheck', '2b.reg.dec.scan_1': '.dscan1', '2b.reg.dec.scan_2': '.dscan2',
    '2b.reg.dec.shift_1': '.dshift1', '2b.reg.dec.shift_2': '.dshift2',
    '2b.reg.inc.shift_1': '.ishift1', '2b.reg.inc.shift_2': '.ishift2',
    '2c.reg.return_0_1': '.r0a', '2c.reg.return_0_2': '.r0b', '2c.reg.return_1_1': '.r1a',
    '2c.reg.return_1_2': '.r1b', '2e.reg.cleanup_1': '.cl1', '2e.reg.cleanup_2': '.cl2',
    '4.dispatch.scan': '.scan', '5.root.1': '.root1', '5.root.2': '.root2',
    '6.break.0': '.brk0', '6.break.1': '.brk1', '6.continue.0': '.cnt0', '6.continue.1': '.cnt1',
}


def lean_state(n, idx_by_name):
    if n in FW: return FW[n]
    m = re.fullmatch(r'2b\.reg\.(-?\d+)\.(inc|dec)', n)
    if m: return f'.ch{"I" if m.group(2) == "inc" else "D"} {int(m.group(1)) + 2}'
    m = re.fullmatch(r'3\.(\w+)\.(inc|decnz)', n)
    if m: return f'.{"incL" if m.group(2) == "inc" else "decL"} {REGS.index(m.group(1))}'
    m = re.fullmatch(r'4\.dispatch\.(\d+)', n)
    if m: return f'.disp {m.group(1)}'
    return f'.node {idx_by_name[n]}'


def write_m309(b, bu, path, order, names):
    """b: the merged build (machines/pa_309.txt), bu: the unmerged build."""
    idx_by_name = {nm: i for i, nm in enumerate(names)}
    order2, table, cl = b.named_states()
    st2 = set(cl[n] for n in {s for s, _ in b.tm.states})
    # merged representative of each unmerged state (merge_equal keeps one per class)
    unm = sorted({s for s, _ in bu.tm.states})
    # the merge classes, as merge_equal_states computes them on the unmerged machine
    st = bu.tm.states
    cls = {n: 0 for n in unm}
    while True:
        sig, new = {}, {}
        for n in unm:
            key = (cls[n],) + tuple(None if (n, r) not in st else (st[(n, r)].write, st[(n, r)].direction,
                                    cls.get(st[(n, r)].nextstate, st[(n, r)].nextstate)) for r in "01")
            new[n] = sig.setdefault(key, len(sig))
        if len(sig) == len(set(cls.values())):
            break
        cls = new
    kept = {s for s, _ in b.tm.states}
    rep = {}
    for n in unm:
        ks = [m for m in kept if cls[m] == cls[n]]
        assert len(ks) == 1, (n, ks)
        rep[n] = ks[0]
    out = ['import TinyCryptids.PA.Main', '',
           f'/-! M309: the {len(order2)}-state machine `pa/machines/pa_309.txt` (TMBuilder output with',
           '`merge_equal`), generated by `pa/gen_lean.py`: its transition function, the map from the',
           'compiled machine `delta dag 0`, and the transferred theorem. -/', '',
           'namespace TM.PA', '', 'namespace M309', '', 'inductive St2']
    for n in order2:
        out.append(f'  | {n}')
    out.append('  | halt2')
    out += ['  deriving DecidableEq, Repr', '', 'open St2 Dir in',
            'def delta2 : St2 → Bool → Option (Bool × Dir × St2)']
    for n in order2:
        for r, t in enumerate(table[n]):
            if t is None:
                out.append(f'  | {n}, {"true" if r else "false"} => none')
            else:
                w, d, nx = t
                nx = 'halt2' if nx == 'halt' else nx
                out.append(f'  | {n}, {"true" if r else "false"} => some ({"true" if w else "false"}, Dir.{d}, {nx})')
    out.append('  | halt2, _ => none')
    out += ['', '/-- Each compiled state to its merged state. -/', 'def phi : St → St2']
    fw_lines, node_lines = [], []
    for n in unm:
        ls = lean_state(n, idx_by_name)
        tgt = cl[rep[n]]
        if ls.startswith('.node'):
            node_lines.append((int(ls.split()[1]), tgt))
        else:
            fw_lines.append((ls, tgt))
    # Lean match: parametrised constructors with literal arguments
    for ls, tgt in fw_lines:
        parts = ls.split()
        if len(parts) == 1:
            out.append(f'  | {ls} => St2.{tgt}')
        else:
            out.append(f'  | {parts[0]} {parts[1]} => St2.{tgt}')
    out.append('  | .halt => St2.halt2')
    out.append('  | .node i => nodeMap i')
    out.append('  | _ => St2.halt2')
    node_lines.sort()
    assert [i for i, _ in node_lines] == list(range(len(node_lines)))
    out.insert(out.index('def phi : St → St2') - 1,
               'def nodeT : List St2 := ' + lean_list(['St2.' + t for _, t in node_lines], 6) + '\n')
    out.insert(out.index('def phi : St → St2') - 1,
               'def nodeMap (i : Nat) : St2 := (nodeT.get? i).getD St2.halt2\n')
    out += ['', '/-- `Compat phi` as a Boolean test. -/',
            'def compatB : Option (Bool × Dir × St) → Option (Bool × Dir × St2) → Bool',
            '  | none, _ => true',
            '  | some (w, d, q), x => x == some (w, d, phi q)', '',
            'theorem compat_of {a : Option (Bool × Dir × St)} {x : Option (Bool × Dir × St2)}',
            '    (h : compatB a x = true) : Compat phi a x := by',
            '  match a, h with',
            '  | none, _ => trivial',
            '  | some (w, d, q), h => exact beq_iff_eq.mp h', '',
            '/-- All node states, tested one by one. -/',
            'def nodesOK : Nat → Bool',
            '  | 0 => true',
            '  | n + 1 => nodesOK n && compatB (delta dag 0 (.node n) false) (delta2 (phi (.node n)) false)',
            '      && compatB (delta dag 0 (.node n) true) (delta2 (phi (.node n)) true)', '',
            'theorem nodesOK_le : ∀ n, nodesOK n = true → ∀ i, i < n → ∀ b : Bool,',
            '    compatB (delta dag 0 (.node i) b) (delta2 (phi (.node i)) b) = true := by',
            '  intro n; induction n with',
            '  | zero => intro _ i h; omega',
            '  | succ n ih =>',
            '    intro h i hi b',
            '    simp only [nodesOK, Bool.and_eq_true] at h',
            '    rcases Nat.lt_succ_iff_lt_or_eq.mp hi with hi | rfl',
            '    · exact ih h.1.1 i hi b',
            '    · cases b; exact h.1.2; exact h.2', '',
            'set_option maxRecDepth 100000 in',
            f'theorem nodesOK_all : nodesOK {len(order)} = true := by decide', '',
            f'theorem compat_nodes : ∀ i, i < {len(order)} → ∀ b : Bool,',
            '    compatB (delta dag 0 (.node i) b) (delta2 (phi (.node i)) b) = true :=',
            f'  nodesOK_le {len(order)} nodesOK_all', '',
            'theorem compat : ∀ q b, Compat phi (delta dag 0 q b) (delta2 (phi q) b) := by',
            '  intro q b',
            '  apply compat_of',
            '  cases q with',
            '  | node i =>',
            f'    by_cases h : i < {len(order)}',
            '    · exact compat_nodes i h b',
            '    · have : dag i = none := List.get?_eq_none (by rw [table_length]; exact Nat.le_of_not_lt h)',
            '      simp [delta, this, compatB]',
            '  | chI k => revert k b; decide',
            '  | chD k => revert k b; decide',
            '  | incL r => revert r b; decide',
            '  | decL r => revert r b; decide',
            '  | disp i => revert i b; decide',
            '  | _ => revert b; decide', '',
            'def start2 : Cfg St2 := ⟨St2.S_0a_boot1_A, blank, blank⟩', '',
            '/-- The 309-state machine halts iff the theory T (Tarski\'s S2 plus Friedman\'s set existence',
            'scheme, equiconsistent with PA) proves `v0 ∈ v0`, i.e. iff PA is inconsistent. -/',
            'theorem halts_iff : Halts delta2 start2 ↔ TinyCryptids.Wff.Provable (TinyCryptids.Wff.el 0 0) :=',
            '  halts_iff_of_sim (delta dag 0) delta2 phi compat start TM.PA.halts_iff',
            '    (fun h => let ⟨L, R, hr⟩ := haltAt_of h; ⟨⟨St.halt, L, R⟩, hr, rfl⟩)', '',
            'end M309', '', 'end TM.PA']
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')
    return rep


def check_file(b):
    """the generated table is machines/pa_309.txt"""
    import importlib.util
    spec = importlib.util.spec_from_file_location('repotm', os.path.join(HERE, '..', 'tools', 'tm.py'))
    rtm = importlib.util.module_from_spec(spec); spec.loader.exec_module(rtm)
    order, states, _ = rtm.parse(open(os.path.join(HERE, 'machines', 'pa_309.txt')).read())
    o2, table, _ = b.named_states()
    assert order == o2
    for n in order:
        assert states[n] == [None if t is None else tuple(t) for t in table[n]], n


if __name__ == '__main__':
    b = program.build()
    check_file(b)
    bu = program.build(merge_equal=False)
    order, children, names, idx, zr, dep = write_dag(bu, os.path.join(LEAN, 'Dag.lean'))
    order_m, children_m, names_m, _ = dag_of(b)
    assert children_m == children and names_m == names
    print(len(order), 'nodes; max zr', max(zr), 'max dep', max(dep))
    rep = write_m309(b, bu, os.path.join(LEAN, 'M309.lean'), order, names)
    print('merged:', {k: v for k, v in rep.items() if k != v})
