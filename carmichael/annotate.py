HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF CARMICHAEL'S TOTIENT
; CONJECTURE FAILS: iff some m >= 1 has phi(n) != phi(m) for every n != m.
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/Carmichael/{lean}.lean, theorem TM.Carmichael.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / carmichael.txt with
;   states merged. States are merged only when their defined transitions
;   agree, so each state below plays one or more ROLES of the design (its name
;   joins them). Each transition line is tagged [role] with the role(s) that
;   use it. A '-' line is never used.
;
; TAPE:  1 K 00 1 R 00 V 1 00 f 0 B 1
;   K, R: k and r slots (k + r = M), each with one hole (a single 0);
;   V: v+1 slots, its hole on slot v+1-c after c coprime pairs (none once c > v);
;   f: one M with phi(M) = v found so far in this window;
;   B: s slots, its hole moving left one slot per round.
;
; SEARCH: for v = 2, 3, ...: for M = 2 .. s+1 count the M with phi(M) = v;
;   a second one ends the window early; a window with exactly one HALTS
;   (s + 1 >= 2 v^2, and every n with phi(n) = v has n <= 2 v^2).
;
; ROUND (M): for k = 1 .. M-1, r = M-k:
;   test    ticks advance both holes cyclically; when K's hole wraps (every k
;           ticks), R's hole at old position 0 -> coprime, at r-1 -> not.
;           (the walk 0, k, 2k, ... mod r reaches 1 before 0 iff gcd(k, r) = 1)
;   count   coprime: V's hole one slot left.
;   shift   (k, r) -> (k+1, r-1), until r = 1.
;   end     V's hole on slot 1 iff phi(M) = v; flag; B's hole one slot left
;           (off B: the window is over); V's hole back; (M-1, 1) -> (1, M).
; NEXT v: V gains a slot, B 4 slots per slot of V, K/R -> (1, 1).
; ============================================================================

blank_symbol: 0
"""

