"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design
(amicable.txt, generated by build.py). The merged state is named after its
roles, listed with a description, and every transition line is tagged with the
roles that use it; the beep transition is marked BEEP.
Usage: python3 annotate.py merged.txt out.txt LeanName
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))  # tm.py
from collections import defaultdict
import tm, leangen

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol BEEPING Turing machine that QUASIHALTS IFF THERE ARE
; ONLY FINITELY MANY AMICABLE NUMBERS.
;
; THE BEEP is the transition of state {beep} reading 0 (marked BEEP below).
; Started on a blank tape in the first state, the machine never halts, and it
; takes the beep transition exactly once for every x with s(x) > x and
; s(s(x)) = x (s = sum of proper divisors), i.e. once for the smaller number
; of every amicable pair, in increasing order: 220, 1184, 2620, 5020, ...
; There are infinitely many amicable numbers iff there are infinitely many
; such x, so the machine quasihalts iff there are only finitely many.
; Lean proof: lean/TinyCryptids/Amicable/{lean}.lean,
; theorem TM.Amicable.{lean}.quasihalts_iff (and never_halts).
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / amicable.txt with states
;   merged. States are merged only when their defined transitions agree, and
;   no state that reads 0 joins the beep state, so the beep transition is taken
;   exactly where the design takes it. Each state below plays one or more
;   ROLES of the design (its name joins them); each transition line is tagged
;   [role] with the role(s) that use it. A '-' line is never used.
;
; TAPE (blocks of 1s; 00 between blocks; a HOLE is a single 0 in a block)
;   round for x:   P 0 00 N          pass 1 scans N (x + 4 cells), P = 1^(x+1)
;   pass 2:        A 00 X 00 N       pass 2 scans X = 1^(m+4), m = s(x); N = 1^x
;   SCAN of a block of x + 4 cells (../oddperfect's mod walk): D 00 R with
;   x = d + r + 1, for d = 1 .. x - 1: a mod walk tests d | x, and if so the
;   ADD moves D's hole down D, and each step fills the hole of the
;   ACCUMULATOR left of the block (the third 0 left of D) and makes the next
;   cell left the hole: the accumulator gains a cell, or (a preload: cells
;   left of its hole) loses one there. At the end the block is 1^x 0000.
; ALGORITHM (one round)
;   round    N := N + 4 cells, a marker 2 cells further, copy N (x + 3 units,
;            the add routine with D = N) into a fresh P, N's last new cell;
;            P's last cell erased: P is a preload of x + 1 cells.
;   pass 1   scan N with P: P's hole reaches its far end iff s(x) >= x + 1.
;   check    no: erase P, next round. yes: P (4 cells more) is the block of
;            m + 4 cells for pass 2, with a fresh accumulator A.
;   pass 2   scan it: A = 1^s(m). Fill the block, copy N (x units) into A's
;            right end: one cell of A stays left of the hole iff s(m) = x:
;            BEEP. Erase everything left of N, next round.
; ============================================================================

blank_symbol: 0
"""

