HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF NO ODD k < 509203 IS A
; RIESEL NUMBER, i.e. iff every odd k < 509203 has some n >= 1 with
; k*2^n - 1 prime. (A Sigma_1 statement: the machine halts iff it is TRUE.)
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/Riesel/{lean}.lean, theorem TM.Riesel.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / riesel.txt with
;   states merged. States are merged only when their defined transitions agree,
;   so each state below plays one or more ROLES of the design (its name joins
;   them). Each transition line is tagged [role] with the role(s) that use it.
;   A '-' line is never used. The seed roles run once at the start and only
;   ever read 0, so most of them double as a step of some other routine.
;
; TAPE LAYOUT (blocks of 1s separated by 00):
;
;      C 00 K 00 D 00 R
;
;   C  a binary counter c: five groups of four bits b3 b2 b1 b0, each followed
;      by a marker 1, most significant group first; c is the number of k
;      still to come after the current one
;   K  k + 7 cells while k is tested (no hole)
;   D  d+2 cells: the trial divisor d >= 3; its HOLE (a single 0) at cell c+1
;      is a cyclic counter c in [0, d)
;   R  r+2 cells: r = P - d; during the mod walk its hole counts the steps
;
; ALGORITHM (k = 5, 7, ..., 509201; for each k, P = k*2 - 1, k*4 - 1, ...)
;   mod walk  r times: advance the D hole cyclically, then
;             the R hole. When the R hole runs off its block, d | P iff the D
;             hole is back at cell 1: then P is composite.
;   shift     d := d+1, r := r-1; when r = 0, P is prime.
;   composite rebuild D := 3, R := P - 1 cells with a hole at cell 1, then the
;             loop doubles R: the next P is 2P + 1 = k*2^(n+1) - 1.
;   prime     wipe D and R; the loop moves K one cell at a time into K' on its
;             right and copies each cell to T beyond K'; then decrement C
;             (HALT if it was 0: k was 509201); K and K' join (k := k + 2); T
;             becomes D := 3 and R, and the loop doubles R: P = 2k - 1.
;   loop      erase the last cell of X; it reappears as the first cell of X'
;             (the separator moves left) and one more cell is appended to T.
;             It stops at the first 0: the R hole, or the separator left of K.
;   seed      write C = 254599 and K for the step to k = 5 (k = 1: 3 and
;             k = 3: 5 are prime).
; ============================================================================

blank_symbol: 0
"""

R = 'right'; L = 'left'
