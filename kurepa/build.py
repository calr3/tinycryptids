"""Generator for a 2-symbol Turing machine that halts iff Kurepa's conjecture fails:
iff some n >= 3 divides the left factorial !n = 0! + 1! + ... + (n-1)!
(equivalently, some odd prime p divides !p).

Tape layout (N and B separated by '00'; inside B, single-0 markers m1, m2):
  N 00 B,   B = L m1 F m2 Q
  - N (m+1 cells, cells 0..m) holds m (m = n in the test of round n, n+1 in its
    multiplication); its hole (cells 1..m) steps cyclically in the test and counts the copies.
  - L (lambda = !n + n + 1 cells) holds the left factorial; in the test a hole walks from its
    right end to its left end, one N step per cell.
  - F (n! cells) holds n!; its copy cursor walks f_0 .. f_{n!-1}.
  - Q: the copies of F (absent during the test).
Round n:
  test: lambda - 1 = !n + n N steps from cell n; n | !n iff the N hole is back at cell n: HALT.
  grow N by one cell on its left (filling the old hole), N hole at cell 1.
  multiply: n+1 copies of F onto Q (the N hole steps once per copy and falls off the end of N
    after the last one; it is put back at cell n+1).
  merge: fill m1 (L := L + 1 + F, Q is the new F, m2 the new m1); the L hole starts at the
    right end of L.
The seed writes round 2 right to left as after its test (the test of n = 2 is skipped).
"""
import sys
ST = {}          # name -> [t0, t1]
ORDER = []
def S(name, t0, t1):
    assert name not in ST, name
    ST[name] = [t0, t1]; ORDER.append(name)
def T(w, d, n): return (w, d, n)

def parser_right(prefix, found):
    """Move right to the next hole. Lands at hole+1 (a 1) and performs `found` there."""
    S(prefix+'1', T(0,'R',prefix+'2'), T(1,'R',prefix+'1'))
    S(prefix+'2', T(0,'R',prefix+'1'), found)
def parser_left(prefix, found):
    """Move left to the next hole. Lands at hole-1 (a 1), performs `found`."""
    S(prefix+'1', T(0,'L',prefix+'2'), T(1,'L',prefix+'1'))
    S(prefix+'2', T(0,'L',prefix+'1'), found)

def seed(n0):
    from math import factorial
    lf = sum(factorial(k) for k in range(n0))
    # round n0 after its test, written right to left: F, m1, L, 00, N cells n0 .. 0;
    # then gg grows N by a cell 0 and gh puts the hole at cell 1 (as after a test)
    pat = '1' * (n0 + 1) + '00' + '1' * (lf + n0 + 1 + LOFF) + '0' + '1' * factorial(n0)
    pat = pat[::-1]
    for i, ch in enumerate(pat):
        S(f'seed{i}', T(int(ch),'L', f'seed{i+1}' if i+1 < len(pat) else 'gg'), None)

def test(halt_state):
    parser_right('PT', T(1,'L','p1'))
    S('p1', T(1,'L','p2'), None)
    S('p2', T(0,'L','k1'), T(0,'L','PN1'))      # 0: L used up
    parser_left('PN', T(1,'R','s1'))
    # N step: the hole moves one cell right, from the last cell it wraps to cell 1
    S('s1', T(1,'R','s2'), None)
    S('s2', T(0,'L','s3'), T(0,'R','PT1'))
    S('s3', T(0,'R','s4'), T(1,'L','s3'))
    S('s4', None, T(1,'R','s5'))
    S('s5', None, T(0,'R','PT1'))
    # is the N hole at its last cell?  Else fill it
    S('k1', T(0,'L','k2'), None)
    S('k2', T(0,'L',halt_state), T(1,'L','kk'))
    S('kk', T(1,'L','gg'), T(1,'L','kk'))
    # grow N on the left, hole at cell 1
    S('gg', T(1,'R','gh'), T(1,'L','gg'))
    S('gh', None, T(0,'R','PG1'))

def multiply():
    # set the F cursor at f_0 (right of the marker m1)
    parser_right('PG', T(0,'R','x1'))
    # copy one cell: append a 1 to Q, back to the cursor, advance it
    S('x1', T(0,'R','x2'), T(1,'R','x1'))
    S('x2', T(1,'L','y0'), T(1,'R','x2'))
    S('y0', T(0,'L','y1'), T(1,'L','y0'))
    S('y1', T(1,'R','y2'), T(1,'L','y1'))
    S('y2', T(0,'L','z1'), T(0,'R','x1'))      # 0: one copy done
    S('z1', T(0,'L','PC1'), T(1,'L','z1'))
    parser_left('PC', T(1,'R','c1'))
    # copy counter: the N hole moves right; when it falls off, all copies are made
    S('c1', T(1,'R','c2'), None)
    S('c2', T(0,'L','c3'), T(0,'R','PG1'))
    S('c3', None, T(0,'R','PM1'))

def merge():
    # fill m1 (L := L + F), the L hole starts at the right end of L
    parser_right('PM', T(1,'L','m1'))
    S('m1', T(1,'R','m2'), None)
    S('m2', T(0,'L','m3'), T(1,'R','m2'))
    S('m3', None, T(1,'L','p2'))

LOFF = 0
def build(halt_state='halt', n0=2, loff=0):
    """Variants: n0 = 1 halts at n = 2 (2 | !2); loff = 1 tests n | !n + 1 (halts at n = 5)."""
    global LOFF
    LOFF = loff
    ST.clear(); ORDER.clear()
    seed(n0); test(halt_state); multiply(); merge()
    refs = {t[2] for v in ST.values() for t in v if t}
    missing = refs - set(ST) - {halt_state}
    assert not missing, missing
    unused = set(ST) - refs - {ORDER[0]}
    assert not unused, unused
    lines = ["; Halts iff n | !n for some n >= 3 (Kurepa's conjecture fails)"
             + ('' if (n0, loff) == (2, 0) else f'; test variant n0={n0} loff={loff}') + '.',
             f'; {len(ORDER)} states, 2 symbols. Generated by build.py.', '', 'blank_symbol: 0', '']
    for n in ORDER:
        lines.append(n)
        for r, t in enumerate(ST[n]):
            lines.append('    -' if t is None else f'    {r} {t[0]} {t[1]} {t[2]}')
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    out = build()
    open(sys.argv[1] if len(sys.argv) > 1 else 'kurepa.txt', 'w').write(out)
    print(len(ORDER), 'states')
