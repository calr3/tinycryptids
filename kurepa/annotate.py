"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design
(kurepa.txt, generated by build.py). The merged state is named after its
roles, listed with a description, and every transition line is tagged with the
roles that use it. Usage: python3 annotate.py merged.txt out.txt LeanName
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))  # tm.py
import sys
from collections import defaultdict
import tm

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF KUREPA'S CONJECTURE FAILS:
; iff some odd prime p divides the left factorial !p = 0! + 1! + ... + (p-1)!.
; It tests every n >= 3 for n | !n (equivalent: Lean's kurepa_iff).
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/Kurepa/{lean}.lean, theorem TM.Kurepa.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / kurepa.txt with states
;   merged. States are merged only when their defined transitions agree, so
;   each state below plays one or more ROLES of the design (its name joins
;   them). Each transition line is tagged [role] with the role(s) that use it.
;   A '-' line is never used. The seed roles run once at the start and only
;   ever read 0, so each of them doubles as a step of some other routine.
;
; TAPE LAYOUT
;
;      N 00 L m1 F m2 Q        (m1, m2: markers, single 0s)
;
;   N  cells 0..m, m = n in the test of round n, n+1 in its multiplication.
;      Its HOLE (a single 0, cells 1..m) steps cyclically in the test and
;      counts the copies in the multiplication.
;   L  !n + n + 1 cells: the left factorial. In the test a hole walks from
;      its right end to its left end.
;   F  n! cells. In the multiplication a copy cursor walks it left to right.
;   Q  the copies of F made so far (only during the multiplication).
;
; ALGORITHM (round n = 3, 4, 5, ...)
;   test      for each cell of L but one: one step of the N hole, which starts
;             at cell n and wraps from cell n to cell 1. That is !n + n steps,
;             so the hole is back at cell n iff n | !n: HALT.
;   grow      fill the N hole, add a cell to N on the left, hole at cell 1.
;   multiply  n+1 times copy the n! cells of F onto Q; the N hole steps after
;             each copy and falls off N after the last one (put back at n+1).
;   merge     fill m1: L := L + 1 + F; Q is the new F, m2 the new m1.
;   seed      write round 2 right to left (F = 11, m1, L = 11111, 00, N =
;             111), as after its test; then grow (the test of n = 2 is skipped).
; ============================================================================

blank_symbol: 0
"""

R = 'right'; L = 'left'
def parser(direction, then):
    return f'scan {direction} to the next hole, then {then}'

ROLE = {
    'PT1': parser(R, 'move the L hole (p1)'),
    'PT2': parser(R, 'move the L hole (p1)'),
    'p1': 'test: fill the L hole',
    'p2': 'test: 1: the new L hole, then to the N hole (PN); 0: L is used up, check N (k1)',
    'PN1': parser(L, 'step the N hole (s1)'),
    'PN2': parser(L, 'step the N hole (s1)'),
    's1': 'step the N hole: fill it',
    's2': 'step the N hole: 1: the new hole, back to the L hole (PT); 0: last cell, wrap',
    's3': 'wrap: run left over N',
    's4': 'wrap: step over cell 0 of N',
    's5': 'wrap: N hole at cell 1, back to the L hole (PT)',
    'k1': 'check: step over the separator',
    'k2': 'check: 0: the N hole is at its last cell, n | !n: HALT; 1: not divisible',
    'kk': 'not divisible: run left to the N hole and fill it',
    'gg': 'grow N: run left over N, one more cell on its left',
    'gh': 'grow N: hole at cell 1, then multiply (PG)',
    'PG1': parser(R, 'copy cursor at the cell after the marker m1'),
    'PG2': parser(R, 'copy cursor at the cell after the marker m1'),
    'x1': 'copy: run right over the rest of F to the marker m2',
    'x2': 'copy: run right over Q and append a 1',
    'y0': 'copy: run left over Q to the marker m2',
    'y1': 'copy: run left over F to the cursor, fill it',
    'y2': 'copy: 1: the new cursor, copy the next cell (x1); 0: the marker m2, one copy done',
    'z1': 'one copy done: run left over F to the marker m1, then to the N hole (PC)',
    'PC1': parser(L, 'step the copy counter (c1)'),
    'PC2': parser(L, 'step the copy counter (c1)'),
    'c1': 'copy counter: fill the N hole',
    'c2': 'copy counter: 1: the new hole, next copy (PG); 0: all copies made',
    'c3': 'all copies made: N hole at the last cell again, then merge (PM)',
    'PM1': parser(R, 'fill the marker m1 (m1)'),
    'PM2': parser(R, 'fill the marker m1 (m1)'),
    'm1': 'merge: fill the marker m1 (L := L + 1 + F)',
    'm2': 'merge: run right over F to the marker m2 (the new m1)',
    'm3': 'merge: step left; the next cell becomes the L hole (p2): the test starts',
}
import build
build.build()
SEED = [r for r in build.ORDER if r.startswith('seed')]
for r in SEED:
    ROLE[r] = f'seed: write {build.ST[r][0][0]} and step left'

SECTIONS = [
    ('TEST: n | !n ?', 'PT1 PT2 p1 p2 PN1 PN2 s1 s2 s3 s4 s5 k1 k2'),
    ('GROW N', 'kk gg gh'),
    ('MULTIPLY: F := (n+1) F', 'PG1 PG2 x1 x2 y0 y1 y2 z1 PC1 PC2 c1 c2 c3'),
    ('MERGE: L := L + 1 + F', 'PM1 PM2 m1 m2 m3'),
    ('SEED only', ' '.join(SEED)),
]

def main(src, dst, lean):
    o, S, _ = tm.parse(open('kurepa.txt').read())
    o2, S2, _ = tm.parse(open(src).read())
    phi, todo = {o[0]: o2[0]}, [o[0]]
    while todo:
        q = todo.pop()
        for b, t in enumerate(S[q]):
            if t is None or t[2] not in S: continue
            t2 = S2[phi[q]][b]
            assert t2 is not None and t2[:2] == t[:2]
            if t[2] in phi: assert phi[t[2]] == t2[2]
            else: phi[t[2]] = t2[2]; todo.append(t[2])
    assert set(phi) == set(o) and set(ROLE) == set(o), set(o) ^ set(ROLE)
    cls = defaultdict(list)
    for q in o: cls[phi[q]].append(q)
    sec_of = {r: i for i, (_, rs) in enumerate(SECTIONS) for r in rs.split()}
    pos = {r: i for i, r in enumerate(o)}
    name = {}
    for c, members in cls.items():
        work = [r for r in members if not r.startswith('seed')]
        name[c] = '_'.join(work) if work else members[0]
    name[o2[0]] = 'start_' + name[o2[0]]
    def key(c):
        prim = next((r for r in cls[c] if not r.startswith('seed')), cls[c][0])
        return (c != o2[0], sec_of[prim], pos[prim])
    out = [HEADER.format(n=len(o2), N=len(o), lean=lean)]
    cur = None
    for c in sorted(o2, key=key):
        sec = key(c)[1] if c != o2[0] else -1
        if sec != cur:
            title = 'START' if sec == -1 else SECTIONS[sec][0]
            out += ['', f'; ---------- {title} ' + '-' * max(0, 60 - len(title)), '']
            cur = sec
        for r in cls[c]:
            out.append(f'; {r:6} {ROLE[r]}')
        out.append(name[c])
        for b, t in enumerate(S2[c]):
            if t is None:
                out.append('    -'); continue
            users = [r for r in cls[c] if S[r][b] is not None]
            tgt = name.get(t[2], t[2])
            out.append(f'    {b} {t[0]} {t[1]} {tgt:20} ; [{", ".join(users)}]')
    text = '\n'.join(out) + '\n'
    # the annotated machine must be the same machine (up to state names)
    o3, S3, _ = tm.parse(text)
    assert o3[0] == name[o2[0]] and len(o3) == len(o2)
    for c in o2:
        assert S3[name[c]] == [None if t is None else (t[0], t[1], name.get(t[2], t[2])) for t in S2[c]]
    open(dst, 'w').write(text)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'M38')
