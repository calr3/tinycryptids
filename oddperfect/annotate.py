"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design
(oddperfect.txt, generated by build.py). The merged state is named after its
roles, listed with a description, and every transition line is tagged with the
roles that use it. Usage: python3 annotate.py merged.txt out.txt LeanName
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))  # tm.py
import sys
from collections import defaultdict
import tm

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF AN ODD PERFECT NUMBER
; EXISTS, i.e. iff some odd n has sum of proper divisors equal to n.
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/OddPerfect/{lean}.lean, theorem TM.OddPerfect.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / oddperfect.txt with states
;   merged. States are merged only when their defined transitions agree, so
;   each state below plays one or more ROLES of the design (its name joins
;   them). Each transition line is tagged [role] with the role(s) that use it.
;   A '-' line is never used. The seed roles run once at the start and only
;   ever read 0, so each of them doubles as a step of some other routine.
;
; TAPE LAYOUT during the round for n (blocks of 1s separated by 00):
;
;      T 00 D 00 R
;
;   T  n+3 cells: a saturating counter u = min(s, n+1) of the sum s of the
;      proper divisors of n found so far, as a HOLE (a single 0) at cell u+1;
;      at u = n+1 the hole is T's last cell (three 0s with the separator)
;   D  d+1 cells: the candidate divisor d; during the mod walk its hole steps
;      cyclically over cells 1..d, and cell d (the last) is its HOME
;   R  r+1 cells: r = n - d; during the mod walk its hole (cells 0..r-1)
;      counts the steps
;   2-state "scan to the next hole" routines (parsers) do the navigation.
;
; ALGORITHM (n = 1, 3, 5, ...; d = 1, ..., n-1 with r = n - d)
;   mod walk  r times: advance the D hole cyclically, then the R hole. When
;             the R hole runs off R, back over R: d divides r (so d divides n)
;             iff the D hole is home, the first cell met.
;   add       if d | n: the D hole walks down from home to cell 0; each step
;             advances the T hole (on T's last cell it stays: saturation).
;   shift     d := d+1, r := r-1: the first separator cell becomes D's new
;             home, R gives up its cell 0, its hole at its new cell 0.
;   round end when r = 0: six cells for the next R, mark cell 1 of D, then the
;             T hole: at cell n+1 iff s = n: HALT. Else T gets 2 cells on the
;             left (hole at cell 1), D := 1, R := n+1: the round for n+2.
;   seed      write 10 00 1: the end of a pseudo-round n = -1.
; ============================================================================

blank_symbol: 0
"""

R = 'right'; L = 'left'
def parser(direction, then):
    return f'scan {direction} to the next hole, then {then}'

ROLE = {
    'ma1': 'advance the D hole: fill it',
    'ma2': 'advance the D hole: 1: the next cell is the new hole, go to the R hole (PR); 0: it was home, wrap around',
    'mw1': 'wrap around: run left to the start of D',
    'mw2': 'wrap around: step over cell 0',
    'mw3': 'wrap around: new hole at cell 1, go to the R hole (PR)',
    'PR1': parser(R, 'advance the R hole (ra1)'),
    'PR2': parser(R, 'advance the R hole (ra1)'),
    'ra1': 'advance the R hole: fill it',
    'ra2': 'advance the R hole: step over the next cell',
    'ra3': 'advance the R hole: 0: R is used up, the walk is over (e1); 1: go on',
    'ra4': 'advance the R hole: make the new hole, then back to the D hole (PM)',
    'PM1': parser(L, 'advance the D hole (ma1)'),
    'PM2': parser(L, 'advance the D hole (ma1); entered on the new R hole after a shift'),
    'e1': 'walk over: run left over R',
    'e2': 'walk over: step over the separator',
    'e3': 'divisor test on D\'s home: 0: d | n, fill it and add d to T (a2); 1: no, shift (f1)',
    'f1': 'shift: run left to the D hole and fill it',
    'f2': 'shift: run right over D; its first separator cell stays 0: the new home',
    'f3': 'shift: step over the old second separator cell',
    'f4': 'shift: R\'s cell 0 becomes the new separator',
    'f5': 'shift: R\'s new cell 0 is its hole',
    'f6': 'shift: 1: start the walk (PM2); 0: r = 0, the round is over (h1)',
    'a1': 'add: fill the D hole',
    'a2': 'add: 1: the D hole one cell down, then to the T hole (PT); 0: done, shift (f2)',
    'PT1': parser(L, 'advance the T hole (t1)'),
    'PT2': parser(L, 'advance the T hole (t1)'),
    't1': 'advance the T hole: fill it',
    't2': 'advance the T hole: 1: the new hole, back to D (PA); 0: T\'s last cell was the hole: write it back',
    'PA1': parser(R, 'move the D hole down (a1)'),
    'PA2': parser(R, 'move the D hole down (a1)'),
    'h1': 'round end: write R\'s new cells, from the right, up to D',
    'k1': 'round end: run left to the start of D',
    'k2': 'round end: step over D\'s cell 0',
    'k3': 'round end: mark D\'s cell 1 (the next D), then to the T hole (PC)',
    'PC1': parser(L, 'check (x1)'),
    'PC2': parser(L, 'check (x1)'),
    'x1': 'check: fill the T hole',
    'x2': 'check: 0: T was saturated (s > n), next round (z1); 1: look one cell further',
    'x3': 'check: 0: the hole was at cell n+1, s = n: HALT; 1: s < n, next round (z1)',
    'z1': 'next round: run left to the end of T',
    'z2': 'next round: one more cell for T (the old blank left of it is the new hole)',
    'PZ1': parser(R, 'D := 1 (f4)'),
    'PZ2': parser(R, 'D := 1 (f4): the mark is the new home; entered on the new T hole'),
}
SEED = '1000100'
for i, ch in enumerate(SEED):
    ROLE[f'seed{i}'] = f'seed: write {ch} and step right'

SECTIONS = [
    ('MOD WALK: does d divide n?', 'ma1 ma2 mw1 mw2 mw3 PR1 PR2 ra1 ra2 ra3 ra4 PM1 PM2 e1 e2 e3'),
    ('ADD d TO THE T COUNTER', 'a1 a2 PT1 PT2 t1 t2 PA1 PA2'),
    ('SHIFT: d+1, r-1', 'f1 f2 f3 f4 f5 f6'),
    ('ROUND END: CHECK s = n (HALT), NEXT ROUND', 'h1 k1 k2 k3 PC1 PC2 x1 x2 x3 z1 z2 PZ1 PZ2'),
    ('SEED only', ' '.join(f'seed{i}' for i in range(len(SEED)))),
]

def main(src, dst, lean):
    o, S, _ = tm.parse(open('oddperfect.txt').read())
    o2, S2, _ = tm.parse(open(src).read())
    phi, todo = {o[0]: o2[0]}, [o[0]]
    while todo:
        q = todo.pop()
        for b, t in enumerate(S[q]):
            if t is None or t[2] not in S: continue
            t2 = S2[phi[q]][b]
            assert t2 is not None and t2[:2] == t[:2]
            if t[2] in phi: assert phi[t[2]] == t2[2]
            else: phi[t[2]] = t2[2]; todo.append(t[2])
    assert set(phi) == set(o) and set(ROLE) == set(o), set(o) ^ set(ROLE)
    cls = defaultdict(list)
    for q in o: cls[phi[q]].append(q)
    sec_of = {r: i for i, (_, rs) in enumerate(SECTIONS) for r in rs.split()}
    pos = {r: i for i, r in enumerate(o)}
    name = {}
    for c, members in cls.items():
        work = [r for r in members if not r.startswith('seed')]
        name[c] = '_'.join(work) if work else members[0]
    name[o2[0]] = 'start_' + name[o2[0]]
    def key(c):
        prim = next((r for r in cls[c] if not r.startswith('seed')), cls[c][0])
        return (c != o2[0], sec_of[prim], pos[prim])
    out = [HEADER.format(n=len(o2), N=len(o), lean=lean)]
    cur = None
    for c in sorted(o2, key=key):
        sec = key(c)[1] if c != o2[0] else -1
        if sec != cur:
            title = 'START' if sec == -1 else SECTIONS[sec][0]
            out += ['', f'; ---------- {title} ' + '-' * max(0, 60 - len(title)), '']
            cur = sec
        for r in cls[c]:
            out.append(f'; {r:6} {ROLE[r]}')
        out.append(name[c])
        for b, t in enumerate(S2[c]):
            if t is None:
                out.append('    -'); continue
            users = [r for r in cls[c] if S[r][b] is not None]
            tgt = name.get(t[2], t[2])
            out.append(f'    {b} {t[0]} {t[1]} {tgt:20} ; [{", ".join(users)}]')
    text = '\n'.join(out) + '\n'
    # the annotated machine must be the same machine (up to state names)
    o3, S3, _ = tm.parse(text)
    assert o3[0] == name[o2[0]] and len(o3) == len(o2)
    for c in o2:
        assert S3[name[c]] == [None if t is None else (t[0], t[1], name.get(t[2], t[2])) for t in S2[c]]
    open(dst, 'w').write(text)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'M37')
