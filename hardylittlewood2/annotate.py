HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF THE SECOND HARDY-LITTLEWOOD
; CONJECTURE IS FALSE, i.e. iff pi(x) + pi(y) < pi(x + y) for some x, y >= 2.
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/HardyLittlewood2/{lean}.lean,
; theorem TM.HardyLittlewood2.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / hardylittlewood2.txt with
;   states merged. States are merged only when their defined transitions agree,
;   so each state below plays one or more ROLES of the design (its name joins
;   them). Each transition line is tagged [role] with the role(s) that use it.
;   A '-' line is never used. The seed roles run once at the start and only
;   ever read 0, so most of them double as a step of some other routine.
;
; THE SEARCH
;   q_0 = 1, q_1 = 3, q_2 = 5, ... are 1 and the odd primes (for x >= 2 they
;   are counted by pi(x): 1 stands in for 2); h_i = (q_i - q_{{i-1}})/2 are the
;   half gaps. A counterexample with x + y = n exists iff there is one for the
;   largest prime m <= n, and for m = q_G iff for some 1 <= i <= G-1
;       h_G + ... + h_{{G+1-i}}  <  h_1 + ... + h_i
;   The machine tests m = 5, 7, 9, ... by trial division and at each prime runs
;   E := 0; for i = 1 .. G-1: E += h_{{G+1-i}}, then E -= h_i, HALTING if E
;   would drop below 0.
;
; TAPE LAYOUT (blocks of 1s separated by 00; a gap block for h has h+2 cells):
;
;      [E 0000] B' 00 A 00 C 00 D 00 R
;
;   B' h_{{G-1}} ... h_2 h_1 (newest first); grows at its left end
;   A  h_1 h_2 ... h_{{G-1}} (oldest first); its first block h_1 = 1 holds a
;      hole at cell 1 (the PARKED cursor), marking where B' ends
;   C  c+2 cells: c = (m - q)/2 for the candidate m and the last prime q (the
;      next gap); it joins A when m is prime
;   D, R  trial division of m = d + r (legendre/'s mod walk, from d = 3)
;   E  during the test only: e+1 cells (none before the first add), four 0s
;      from B'
;
; ALGORITHM
;   mod walk  r times: advance the D hole cyclically, then the R hole; d | m
;             iff the D hole is back at cell 1 when the R hole runs off.
;   shift     d := d+1, r := r-1; when r = 0, m is prime.
;   composite C gets a cell; D := 3, R := m + 2 - 3 cells (fill the D/R
;             separator, append 3 cells, write the pattern left of the hole).
;   prime     the test: the top cursor (a hole) walks C, then A, right to
;             left; the bottom cursor walks B' from its right end. Per cell a
;             trip home to E: a top cell adds a cell to E, a bottom cell
;             removes one (HALT if only the base cell is left). When B' is used
;             up, E (h_G cells) gets two more and becomes B''s new first block;
;             the top cursor stops on A's first block: parked again. Then a new
;             C, D := 3, R := m + 2 - 3 (the hole moved 4 cells right, so the
;             same pattern lands after the new C; 7 cells appended).
;   seed      write the tape at the prime 5: B' = A = [1], C = 1, D = 1 0 1^5,
;             R = 11, and enter the test.
; ============================================================================

blank_symbol: 0
"""

