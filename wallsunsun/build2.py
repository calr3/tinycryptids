"""Generator of wallsunsun2.txt, the 79-state design without trial division: it halts iff
some m >= 2 has m^2 | F(m - 1) (m = 1, 4 mod 5) or m^2 | F(m + 1) (otherwise).  That holds
iff a Wall-Sun-Sun prime exists: a prime p passes iff it is one, and every prime factor of
an m that passes is one (README.md; Lean: TM.WallSunSun2.halts_iff).

It is ../wallsunsuninf's design (build.py there, seed writing round 2) with the beep (q9
reading 0) replaced by a halt.  Its round-1 transition (r3 reading 0) is never used here.
Usage: python3 build2.py   (writes wallsunsun2.txt)"""
import os, sys, importlib.util
HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('wssinf_build', os.path.join(HERE, '..', 'wallsunsuninf', 'build.py'))
B = importlib.util.module_from_spec(spec); spec.loader.exec_module(B)

def build(**kw):
    order, states = B.build(**kw)
    states['q9'][0] = (0, 'L', 'halt')
    return order, states

def write(order, states, path, title):
    with open(path, 'w') as f:
        f.write(f'; {title}\n; {len(order)} states, 2 symbols. Generated by build2.py.\n\nblank_symbol: 0\n\n')
        for s in order:
            f.write(s + '\n')
            for r, t in enumerate(states[s]):
                f.write('    -\n' if t is None else f'    {r} {t[0]} {t[1]} {t[2]}\n')
        f.write('\n')

if __name__ == '__main__':
    order, states = build()
    write(order, states, os.path.join(HERE, 'wallsunsun2.txt'),
          'Halts iff some m >= 2 has m^2 | F(m -+ 1), i.e. iff a Wall-Sun-Sun prime exists.')
    print(len(order), 'states -> wallsunsun2.txt')
