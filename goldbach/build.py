"""Generator for a 6-symbol Turing machine that halts iff Goldbach's conjecture fails:
some even n >= 4 is not the sum of two primes.

Symbols: 0 blank, 1 cell, 2 = x (a marked cell), 3 = B (the boundary, marked), 4 = b (the
boundary, unmarked), 5 = s (the separator).

Tape at the start of each pair (p, q), p + q = n:

    0 0 [P: 1^p] s [Q: 1^q] 0 0          (Q may hold one stale b, at its 4th cell or later)

For each even n the pairs run (n - 2, 2), (n - 3, 3), ..., (2, n - 2): first P is tested for
primality, then (if P is prime) Q.  If both are prime, n += 2 and the next stage starts at
(n, 2).  If one is composite the separator moves one cell left (p -= 1, q += 1).  The pair
(1, n - 1) is the counterexample: the entry of the P test reads the separator on P's second
cell, an undefined transition, and the machine halts.

Primality of a block X (x >= 2 cells, between two delimiters) by trial division with the
divisor d = 2, 3, ... as a prefix D of X: the boundary b is the first cell of the rest R
(r = x - d cells), and d | x iff d | r.  A round for d: a zigzag marks one cell of R
(right of D, `zr`) and then one cell of D (from its right end, `zl`); when D is fully marked
it is reset lazily (`rst`).  When R runs out, `chk` unmarks everything from the right: D
fully marked iff d | r (composite, since r >= 1); otherwise b moves one cell right (`inc`), and
if it falls off the block, d = x and X is prime.  A stale b (left by a composite Q, which
skips the clean-up) only ever lies in R during the first round, where `zr` treats it as a 1.
"""
import sys
ST, ORDER = {}, []
NSYM = 6
SYM = {'0': 0, '1': 1, 'x': 2, 'B': 3, 'b': 4, 's': 5}

def S(name, **t):
    assert name not in ST, name
    row = [None] * NSYM
    for k, v in t.items():
        w, d, n = v.split()
        row[SYM[k[1:] if k.startswith('_') else k]] = (SYM[w], d, n)
    ST[name] = row; ORDER.append(name)

def build():
    ST.clear(); ORDER.clear()
    # start a round: mark R's first cell as the boundary B; a delimiter instead: d = x, prime
    #   (s: P is prime, test Q; 0: Q is prime too, grow to the next stage).  Start state:
    #   on the blank tape it runs the growth, as after a success at (0, 0) and (p, q) = (1, 1).
    S('mark', _1='B L zl', s='s R e1', _0='1 R g1')
    # zigzag: zl marks D's rightmost unmarked cell, zr marks R's first unmarked cell
    S('zl', x='x L zl', B='B L zl', _1='x R zr', _0='0 R rst', s='s R rst')
    S('zr', x='x R zr', B='B R zr', _1='x L zl', b='x L zl', _0='0 L chk', s='s L chk')
    S('rst', x='1 R rst', B='B L zl')           # D fully marked: unmark it, mark its last cell
    # R ran out: unmark from the right.  D fully marked (delimiter reached): composite.
    S('chk', x='1 L chk', B='b L chk', _1='1 R inc', _0='0 R kr', s='1 L sh')
    S('inc', _1='1 R inc', b='1 R mark')       # d += 1
    # test entry at X's first cell: the boundary at the third cell (d = 2)
    S('e1', _1='1 R e2')
    S('e2', _1='1 R mark')                      # e2 reading s: p = 1, halt
    # P composite: erase b, go to the separator; the shift: s one cell left
    S('kr', _1='1 R kr', b='1 R kr', s='1 L sh')
    S('sh', _1='s L wl', _0='1 R e1')           # _0: the boot only
    S('wl', _1='1 L wl', _0='0 R e1', s='1 L wl')  # back to P; s: the old separator (growth)
    # growth: two cells after Q, the separator on Q's last cell, the old one erased (wl)
    S('g1', _0='1 L g2')
    S('g2', _1='1 L sh')
    refs = {t[2] for v in ST.values() for t in v if t}
    assert refs <= set(ST), refs - set(ST)
    assert not (set(ST) - refs - {ORDER[0]}), set(ST) - refs
    lines = ['; Halts iff some even n >= 4 is not the sum of two primes (Goldbach fails).',
             f'; {len(ORDER)} states, {NSYM} symbols (0 blank, 1, 2 = x, 3 = B, 4 = b, 5 = s).'
             ' Generated by build.py.', '', 'blank_symbol: 0', '']
    for n in ORDER:
        lines.append(n)
        for r, t in enumerate(ST[n]):
            lines.append('    -' if t is None else f'    {r} {t[0]} {t[1]} {t[2]}')
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    out = build()
    open(sys.argv[1] if len(sys.argv) > 1 else 'goldbach.txt', 'w').write(out)
    print(len(ORDER), 'states', sum(t is not None for v in ST.values() for t in v), 'instructions')
