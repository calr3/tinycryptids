"""Emit lean/TinyCryptids/Goldbach/Machine.lean (the design, goldbach.txt) and
lean/TinyCryptids/Goldbach/M10.lean (the merged machine, machines/goldbach_10.txt, with the
state map and the transfer of the main theorem).  Multi-symbol model: Core/Multi.lean."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))
import tm, leangen
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'lean', 'TinyCryptids', 'Goldbach')

def delta(name, order, S, st):
    L = [f'def {name} : {st} → Nat → Option (Nat × Dir × {st})']
    for q in order:
        for b, t in enumerate(S[q]):
            if t: L.append(f'  | .{q}, {b} => some ({t[0]}, .{t[1]}, .{t[2]})')
    L.append('  | _, _ => none')
    return L

def main():
    o, S, _ = tm.parse(open(os.path.join(HERE, 'goldbach.txt')).read())
    o2, S2, _ = tm.parse(open(os.path.join(HERE, 'machines', 'goldbach_10.txt')).read())
    nsym = len(S[o[0]])
    L = ['import TinyCryptids.Core.Multi', '',
         '/-! The design machine, generated by `goldbach/gen_lean.py` from `goldbach/goldbach.txt`.',
         f'{len(o)} states, {nsym} symbols: 0 blank, 1, 2 = x, 3 = B, 4 = b, 5 = s. -/', '',
         'namespace TMK.Goldbach', '', 'open TM (Dir)', '', 'inductive St']
    L += [f'  | {q}' for q in o] + ['deriving DecidableEq, Repr', '']
    L += delta('delta', o, S, 'St')
    L += ['', f'def start : Cfg St := ⟨.{o[0]}, blank, blank⟩', '', 'end TMK.Goldbach', '']
    open(os.path.join(OUT, 'Machine.lean'), 'w').write('\n'.join(L))
    phi = leangen.state_map(o, S, o2, S2)
    L = ['import TinyCryptids.Goldbach.Main', '',
         f'/-! The merged machine ({len(o2)} states, {nsym} symbols), generated by `goldbach/gen_lean.py`',
         'from `goldbach/machines/goldbach_10.txt`, and the main theorem carried over to it. -/', '',
         'namespace TMK.Goldbach', '', 'open TM (Dir)', 'open TinyCryptids', '', 'namespace M10', '',
         'inductive St2'] + [f'  | {q}' for q in o2] + ['deriving DecidableEq, Repr', '']
    L += delta('delta2', o2, S2, 'St2')
    L += ['', f'def start2 : Cfg St2 := ⟨.{o2[0]}, blank, blank⟩', '', 'def phi : St → St2']
    L += [f'  | .{q} => .{phi[q]}' for q in o]
    L += ['', 'theorem compat : ∀ q a, Compat phi (delta q a) (delta2 (phi q) a) := by',
          '  intro q a',
          '  rcases a with _ | _ | _ | _ | _ | _ | a <;> cases q <;> first | trivial | rfl', '',
          '/-- **Main theorem**, for the merged machine. -/',
          'theorem halts_iff : Halts delta2 start2 ↔',
          '    ∃ n, 2 ≤ n ∧ ∀ p q, Prime p → Prime q → p + q ≠ 2 * n :=',
          '  halts_iff_of_sim delta delta2 phi compat start TMK.Goldbach.halts_iff',
          '    (fun h => let ⟨c, hr, hq, hs⟩ := haltAt_of h; ⟨c, hr, by rw [hq, hs]; rfl⟩)', '',
          '/-- The same, with the conjecture as a definition (`TinyCryptids.GoldbachConjecture`). -/',
          'theorem halts_iff_not : Halts delta2 start2 ↔ ¬ GoldbachConjecture := by',
          '  rw [halts_iff]',
          '  constructor',
          '  · rintro ⟨n, hn, h⟩ hg',
          '    obtain ⟨p, q, hp, hq, e⟩ := hg n hn',
          '    exact h p q hp hq e',
          '  · intro hg',
          '    apply Classical.byContradiction; intro hno',
          '    apply hg; intro n hn',
          '    apply Classical.byContradiction; intro hpq',
          '    exact hno ⟨n, hn, fun p q hp hq e => hpq ⟨p, q, hp, hq, e⟩⟩', '',
          'end M10', '', 'end TMK.Goldbach', '']
    open(os.path.join(OUT, 'M10.lean'), 'w').write('\n'.join(L))

if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True); main()
