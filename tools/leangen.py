"""Emit the generated Lean files of a hand-designed machine.

`machine_lean` writes `lean/TinyCryptids/<ns>/Machine.lean` (the design: `St`,
`delta`, `start`). `reduced_lean` writes `lean/TinyCryptids/<ns>/<name>.lean` for a
merged machine: `St2`, `delta2`, the state map `phi` (found by walking both
machines in step), `compat`, and `<name>.halts_iff`, transferred from the
design's `halts_iff` by `halts_iff_of_sim` (`TinyCryptids/Core/Basic.lean`).
Each conjecture folder's `gen_lean.py` / `gen_reduced_lean.py` calls these.
"""
import os
import tm

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')

def _out(ns, name):
    return os.path.join(ROOT, 'lean', 'TinyCryptids', ns, name + '.lean')

def _delta_lines(name, order, states, halt, st):
    # state names that clash with the directions `Dir.L` / `Dir.R` are qualified
    q = lambda n: f'{st}.{n}' if n in ('L', 'R') else n
    L = [f'def {name} : {st} → Bool → Option (Bool × Dir × {st})']
    for n in order:
        for b, t in enumerate(states[n]):
            L.append(f'  | {q(n)}, {"true" if b else "false"} => ' + ('none' if t is None else
                     f'some ({"true" if t[0] else "false"}, {t[1]}, {q(t[2]) if t[2] in states else halt})'))
    return L + [f'  | {halt}, _ => none']

def machine_lean(design, ns):
    """`design`: the named-state file of the design (e.g. 'weakcollatz.txt')."""
    order, ST, _ = tm.parse(open(design).read())
    L = ['import TinyCryptids.Core.Basic', '',
         f'/-! The {len(order)}-state design, generated by `gen_lean.py` from `{design}`. -/',
         '', f'namespace TM.{ns}', '', 'inductive St']
    L += [f'  | {n}' for n in order] + ['  | halt', 'deriving DecidableEq, Repr', '', 'open St Dir in']
    L += _delta_lines('delta', order, ST, 'halt', 'St')
    L += ['', f'def start : Cfg St := ⟨St.{order[0]}, blank, blank⟩', '', f'end TM.{ns}', '']
    open(_out(ns, 'Machine'), 'w').write('\n'.join(L))
    return len(order)

def state_map(o, S, o2, S2):
    """Map each design state to the merged state that plays it, by walking both
    machines from their start states along the used transitions."""
    phi, todo = {o[0]: o2[0]}, [o[0]]
    while todo:
        q = todo.pop()
        for b, t in enumerate(S[q]):
            if t is None or t[2] not in S: continue
            t2 = S2[phi[q]][b]
            assert t2 is not None and t2[:2] == t[:2], (q, b)
            if t[2] in phi: assert phi[t[2]] == t2[2], (q, b)
            else: phi[t[2]] = t2[2]; todo.append(t[2])
    assert set(phi) == set(o), set(o) - set(phi)
    return phi

def reduced_lean(design, merged, ns, name, statement, halt_at, opens=()):
    """`statement`: the right-hand side of the main theorem; `halt_at`: an
    expression in `h : statement` giving `HaltAt start` (the design reaches its
    halting state); `opens`: namespaces the statement needs (e.g. 'TinyCryptids')."""
    o, S, _ = tm.parse(open(design).read())
    o2, S2, _ = tm.parse(open(merged).read())
    phi = state_map(o, S, o2, S2)
    H = 'halt2'
    L = [f'import TinyCryptids.{ns}.Main', '',
         f'/-! {name}: {len(o2)}-state machine generated by `gen_reduced_lean.py` from `{merged}`. -/',
         '', f'namespace TM.{ns}', '']
    L += [f'open {x}' for x in opens] + ([''] if opens else [])
    L += [f'namespace {name}', '', 'inductive St2']
    L += [f'  | {n}' for n in o2] + [f'  | {H}', 'deriving DecidableEq, Repr', '', 'open St2 Dir in']
    L += _delta_lines('delta2', o2, S2, H, 'St2')
    L += ['', 'def phi : St → St2']
    L += [f'  | St.{q} => St2.{phi[q]}' for q in o] + [f'  | St.halt => St2.{H}', '',
          'theorem compat : ∀ q b, Compat phi (delta q b) (delta2 (phi q) b) := by',
          '  intro q b; cases q <;> cases b <;> first | trivial | rfl', '',
          f'def start2 : Cfg St2 := ⟨St2.{o2[0]}, blank, blank⟩', '',
          'theorem halts_iff :',
          f'    Halts delta2 start2 ↔ {statement} :=',
          f'  halts_iff_of_sim delta delta2 phi compat start TM.{ns}.halts_iff',
          f'    (fun h => let ⟨L, R, hr⟩ := {halt_at}; ⟨⟨St.halt, L, R⟩, hr, rfl⟩)', '',
          f'end {name}', '', f'end TM.{ns}', '']
    open(_out(ns, name), 'w').write('\n'.join(L))
    return len(o2)
