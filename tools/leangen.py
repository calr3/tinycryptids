"""Emit the generated Lean files of a hand-designed machine.

`machine_lean` writes `lean/TinyCryptids/<ns>/Machine.lean` (the design: `St`,
`delta`, `start`). `reduced_lean` writes `lean/TinyCryptids/<ns>/<name>.lean` for a
merged machine: `St2`, `delta2`, the state map `phi` (found by walking both
machines in step), `compat`, and `<name>.halts_iff`, transferred from the
design's `halts_iff` by `halts_iff_of_sim` (`TinyCryptids/Core/Basic.lean`).
Each conjecture folder's `gen_lean.py` / `gen_reduced_lean.py` calls these.
"""
import os
import tm

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')

def _out(ns, name):
    return os.path.join(ROOT, 'lean', 'TinyCryptids', ns, name + '.lean')

def _delta_lines(name, order, states, halt, st):
    # state names that clash with the directions `Dir.L` / `Dir.R` are qualified
    q = lambda n: f'{st}.{n}' if n in ('L', 'R') else n
    L = [f'def {name} : {st} → Bool → Option (Bool × Dir × {st})']
    for n in order:
        for b, t in enumerate(states[n]):
            L.append(f'  | {q(n)}, {"true" if b else "false"} => ' + ('none' if t is None else
                     f'some ({"true" if t[0] else "false"}, {t[1]}, {q(t[2]) if t[2] in states else halt})'))
    return L + [f'  | {halt}, _ => none']

def machine_lean(design, ns, beep=None, boop=None):
    """`design`: the named-state file of the design (e.g. 'weakcollatz.txt').
    `beep`: (state, symbol) of a beeping machine's beep transition; then `deltaNB`, the
    design without that transition, is emitted too.  `boop` (with `beep`): a beeping booping
    machine's boop; then `deltaQ`, the design without both, is emitted instead."""
    order, ST, _ = tm.parse(open(design).read())
    L = ['import TinyCryptids.Core.Basic', '',
         f'/-! The {len(order)}-state design, generated by `gen_lean.py` from `{design}`. -/',
         '', f'namespace TM.{ns}', '', 'inductive St']
    L += [f'  | {n}' for n in order] + ['  | halt', 'deriving DecidableEq, Repr', '', 'open St Dir in']
    L += _delta_lines('delta', order, ST, 'halt', 'St')
    if beep and boop:
        sp = [beep, boop]
        nb = {n: [None if (n, b) in sp else t for b, t in enumerate(v)] for n, v in ST.items()}
        L += ['', 'open St Dir in', f'/-- The design without its beep (`{beep[0]}` reading {beep[1]}) and its boop '
              f'(`{boop[0]}` reading {boop[1]}). -/']
        L += _delta_lines('deltaQ', order, nb, 'halt', 'St')
    elif beep:
        bs, bb = beep
        nb = {n: [None if (n, b) == (bs, bb) else t for b, t in enumerate(v)] for n, v in ST.items()}
        L += ['', 'open St Dir in', f'/-- The design without its beep transition (`{bs}` reading {bb}). -/']
        L += _delta_lines('deltaNB', order, nb, 'halt', 'St')
    L += ['', f'def start : Cfg St := ⟨St.{order[0]}, blank, blank⟩', '', f'end TM.{ns}', '']
    open(_out(ns, 'Machine'), 'w').write('\n'.join(L))
    return len(order)

def state_map(o, S, o2, S2):
    """Map each design state to the merged state that plays it, by walking both
    machines from their start states along the used transitions."""
    phi, todo = {o[0]: o2[0]}, [o[0]]
    while todo:
        q = todo.pop()
        for b, t in enumerate(S[q]):
            if t is None or t[2] not in S: continue
            t2 = S2[phi[q]][b]
            assert t2 is not None and t2[:2] == t[:2], (q, b)
            if t[2] in phi: assert phi[t[2]] == t2[2], (q, b)
            else: phi[t[2]] = t2[2]; todo.append(t[2])
    assert set(phi) == set(o), set(o) - set(phi)
    return phi

def reduced_lean(design, merged, ns, name, statement, halt_at, opens=()):
    """`statement`: the right-hand side of the main theorem; `halt_at`: an
    expression in `h : statement` giving `HaltAt start` (the design reaches its
    halting state); `opens`: namespaces the statement needs (e.g. 'TinyCryptids')."""
    o, S, _ = tm.parse(open(design).read())
    o2, S2, _ = tm.parse(open(merged).read())
    phi = state_map(o, S, o2, S2)
    H = 'halt2'
    L = [f'import TinyCryptids.{ns}.Main', '',
         f'/-! {name}: {len(o2)}-state machine generated by `gen_reduced_lean.py` from `{merged}`. -/',
         '', f'namespace TM.{ns}', '']
    L += [f'open {x}' for x in opens] + ([''] if opens else [])
    L += [f'namespace {name}', '', 'inductive St2']
    L += [f'  | {n}' for n in o2] + [f'  | {H}', 'deriving DecidableEq, Repr', '', 'open St2 Dir in']
    L += _delta_lines('delta2', o2, S2, H, 'St2')
    L += ['', 'def phi : St → St2']
    L += [f'  | St.{q} => St2.{phi[q]}' for q in o] + [f'  | St.halt => St2.{H}', '',
          'theorem compat : ∀ q b, Compat phi (delta q b) (delta2 (phi q) b) := by',
          '  intro q b; cases q <;> cases b <;> first | trivial | rfl', '',
          f'def start2 : Cfg St2 := ⟨St2.{o2[0]}, blank, blank⟩', '',
          'theorem halts_iff :',
          f'    Halts delta2 start2 ↔ {statement} :=',
          f'  halts_iff_of_sim delta delta2 phi compat start TM.{ns}.halts_iff',
          f'    (fun h => let ⟨L, R, hr⟩ := {halt_at}; ⟨⟨St.halt, L, R⟩, hr, rfl⟩)', '',
          f'end {name}', '', f'end TM.{ns}', '']
    open(_out(ns, name), 'w').write('\n'.join(L))
    return len(o2)

def reduced_beep_lean(design, merged, ns, name, beep, statement, opens=()):
    """Like `reduced_lean`, for a beeping machine whose design proves
    `TM.<ns>.quasihalts_iff : QuasiHalts delta St.<beep state> <sym> start ↔ <statement>` and
    `TM.<ns>.never_halts`. `beep`: (state, symbol) of the design's beep transition. Emits
    `excl` (every design state played by the merged beep state is the beep state or has no
    transition on the beep symbol) and transfers both theorems with
    `quasihalts_iff_of_sim` / `not_halts_of_sim` (`TinyCryptids/Core/Beep.lean`)."""
    o, S, _ = tm.parse(open(design).read())
    o2, S2, _ = tm.parse(open(merged).read())
    phi = state_map(o, S, o2, S2)
    bs, bb = beep
    bsym = 'true' if bb else 'false'
    for q in o:   # the merged beep transition is taken only where the design takes its beep
        assert phi[q] != phi[bs] or q == bs or S[q][bb] is None, q
    t = S2[phi[bs]][bb]
    H = 'halt2'
    L = [f'import TinyCryptids.{ns}.Main', '',
         f'/-! {name}: {len(o2)}-state machine generated by `gen_reduced_lean.py` from `{merged}`.',
         f'Its beep transition is `{phi[bs]}` reading {bb}. -/', '', f'namespace TM.{ns}', '']
    L += [f'open {x}' for x in opens] + ([''] if opens else [])
    L += [f'namespace {name}', '', 'inductive St2']
    L += [f'  | {n}' for n in o2] + [f'  | {H}', 'deriving DecidableEq, Repr', '', 'open St2 Dir in']
    L += _delta_lines('delta2', o2, S2, H, 'St2')
    L += ['', 'def phi : St → St2']
    L += [f'  | St.{q} => St2.{phi[q]}' for q in o] + [f'  | St.halt => St2.{H}', '',
          'theorem compat : ∀ q b, Compat phi (delta q b) (delta2 (phi q) b) := by',
          '  intro q b; cases q <;> cases b <;> first | trivial | rfl', '',
          f'/-- the merged beep state plays only the design\'s beep state on symbol {bb} -/',
          f'theorem excl : ∀ q, phi q = phi St.{bs} → q = St.{bs} ∨ delta q {bsym} = none := by',
          '  intro q h; cases q <;> first | exact Or.inl rfl | exact Or.inr rfl | exact absurd h (by decide)', '',
          f'def start2 : Cfg St2 := ⟨St2.{o2[0]}, blank, blank⟩', '',
          f'/-- The beep transition: `{phi[bs]}` reading {bb}. -/',
          f'theorem beep_transition : delta2 St2.{phi[bs]} {bsym} = '
          f'some ({"true" if t[0] else "false"}, Dir.{t[1]}, St2.{t[2]}) := rfl', '',
          'theorem never_halts : ¬ Halts delta2 start2 :=',
          f'  not_halts_of_sim delta delta2 phi compat start TM.{ns}.never_halts', '',
          'theorem quasihalts_iff :',
          f'    QuasiHalts delta2 St2.{phi[bs]} {bsym} start2 ↔ {statement} :=',
          f'  (quasihalts_iff_of_sim delta delta2 phi compat start TM.{ns}.never_halts St.{bs} {bsym}',
          f'    excl).trans TM.{ns}.quasihalts_iff', '',
          f'end {name}', '', f'end TM.{ns}', '']
    open(_out(ns, name), 'w').write('\n'.join(L))
    return len(o2)


def reduced_beepboop_lean(design, merged, ns, name, beep, boop, statement, opens=()):
    """Like `reduced_beep_lean`, for a beeping booping machine whose design proves
    `TM.<ns>.repeats_iff : RepeatsForever delta St.<beep> <sym> St.<boop> <sym> start ↔ <statement>`
    and `TM.<ns>.never_halts`. `beep`, `boop`: (state, symbol) of the two special transitions.
    Emits `excl_beep` and `excl_boop` and transfers both theorems with `repeatsForever_iff_of_sim`
    (`TinyCryptids/Core/BeepBoop.lean`) and `not_halts_of_sim`."""
    o, S, _ = tm.parse(open(design).read())
    o2, S2, _ = tm.parse(open(merged).read())
    phi = state_map(o, S, o2, S2)
    for (xs, xb) in (beep, boop):   # each special transition is taken only where the design takes it
        for q in o:
            assert phi[q] != phi[xs] or q == xs or S[q][xb] is None, (xs, q)
    sym = lambda b: 'true' if b else 'false'
    def tr(xs, xb):
        t = S2[phi[xs]][xb]
        return f'some ({sym(t[0])}, Dir.{t[1]}, St2.{t[2]})'
    (bs, bb), (os_, ob) = beep, boop
    H = 'halt2'
    L = [f'import TinyCryptids.{ns}.Main', '',
         f'/-! {name}: {len(o2)}-state machine generated by `gen_reduced_lean.py` from `{merged}`.',
         f'Its beep is `{phi[bs]}` reading {bb}, its boop `{phi[os_]}` reading {ob}. -/', '',
         f'namespace TM.{ns}', '']
    L += [f'open {x}' for x in opens] + ([''] if opens else [])
    L += [f'namespace {name}', '', 'inductive St2']
    L += [f'  | {n}' for n in o2] + [f'  | {H}', 'deriving DecidableEq, Repr', '', 'open St2 Dir in']
    L += _delta_lines('delta2', o2, S2, H, 'St2')
    L += ['', 'def phi : St → St2']
    L += [f'  | St.{q} => St2.{phi[q]}' for q in o] + [f'  | St.halt => St2.{H}', '',
          'set_option maxHeartbeats 0 in',
          'theorem compat : ∀ q b, Compat phi (delta q b) (delta2 (phi q) b) := by',
          '  intro q b; cases q <;> cases b <;> first | trivial | rfl', '']
    for (tag, xs, xb) in (('beep', bs, bb), ('boop', os_, ob)):
        L += ['set_option maxHeartbeats 0 in',
              f'/-- the merged {tag} state plays only the design\'s {tag} state on symbol {xb} -/',
              f'theorem excl_{tag} : ∀ q, phi q = phi St.{xs} → q = St.{xs} ∨ delta q {sym(xb)} = none := by',
              '  intro q h; cases q <;> first | exact Or.inl rfl | exact Or.inr rfl | exact absurd h (by decide)', '']
    L += [f'def start2 : Cfg St2 := ⟨St2.{o2[0]}, blank, blank⟩', '',
          f'/-- The beep transition: `{phi[bs]}` reading {bb}. -/',
          f'theorem beep_transition : delta2 St2.{phi[bs]} {sym(bb)} = {tr(bs, bb)} := rfl', '',
          f'/-- The boop transition: `{phi[os_]}` reading {ob}. -/',
          f'theorem boop_transition : delta2 St2.{phi[os_]} {sym(ob)} = {tr(os_, ob)} := rfl', '',
          'theorem never_halts : ¬ Halts delta2 start2 :=',
          f'  not_halts_of_sim delta delta2 phi compat start TM.{ns}.never_halts', '',
          'theorem repeats_iff :',
          f'    RepeatsForever delta2 St2.{phi[bs]} {sym(bb)} St2.{phi[os_]} {sym(ob)} start2 ↔ {statement} :=',
          f'  (repeatsForever_iff_of_sim delta delta2 phi compat start TM.{ns}.never_halts St.{bs} {sym(bb)}',
          f'    St.{os_} {sym(ob)} excl_beep excl_boop).trans TM.{ns}.repeats_iff', '',
          f'end {name}', '', f'end TM.{ns}', '']
    open(_out(ns, name), 'w').write('\n'.join(L))
    return len(o2)
