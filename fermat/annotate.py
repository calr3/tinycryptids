HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF FERMAT'S LAST THEOREM
; IS FALSE, i.e. iff x^E + y^E = z^E for some E >= 3 and x, y, z >= 1.
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/Fermat/{lean}.lean, theorem TM.Fermat.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the 127-state design of build.py / fermat.txt with states
;   merged. States are merged only when their defined transitions agree, so
;   each state below plays one or more ROLES of the design (its name joins
;   them). Each transition line is tagged [role] with the role(s) that use it.
;   A '-' line is never used. The seed roles seed0..seed23 run once at the
;   start and only ever read 0, so many states double as a seed step.
;
; TAPE LAYOUT (unary blocks of 1s, separated by 00; a block of length v+2
; holds the value v):
;
;      B1=E 00 B2=x 00 B3=y 00 B4=z 00 M 00 A 0 R 0 Q
;
;   B1..B4  the current tuple (E, x, y, z), with E >= 3 and x, y, z >= 1
;   M       a 1-cell block ending the tuple
;   A       accumulator: 1 + x^E + y^E is built up here (empty between tuples)
;   R       running power base^k, r cells for the value r, after a single 0
;   Q       scratch area for copies of R, after another single 0
;   A HOLE is a single 0 inside a block, used as a cursor. B1 always holds
;   one: the exponent counter, on cell 1 (the anchor) between powers and on
;   cells 1 .. E+1 during a power (on the last cell it sits next to the
;   separator). The base being powered holds a MARKER hole on its cell 1 and,
;   during a round, a cursor on cells 3 .. base+1. The single 0 between A and
;   R is R's hole (with A empty, it and the separator after M make three 0s);
;   during a copy, R also holds a copy cursor. "Scan to the next hole"
;   routines (2 states each) find them: a hole is a run of one or three 0s,
;   unlike the 00 separators.
;
; ALGORITHM
;   seed      write the first tuple (4,1,1,1), i.e. the 24-cell pattern
;             10 1111 00 111 00 111 00 111 00 1 (B1 with its hole, B2..B4, M),
;             then restore A and R via `cr4`. One seed role per pattern cell.
;   enumerate step (E,x,y,z) to the next tuple (NEXCOM order of compositions,
;             which reaches every tuple). On values: E>=4 -> (E-1, x+1, y, z);
;             else (E = 3) x>=2 -> (x+1, 1, y+1, z); else y>=2 -> (y+1, 1, 1, z+1);
;             else z>=2 -> (z+3, 1, 1, 1); this is done by moving separators.
;   setup     the anchor plays the marker of a "next base" step: the marker
;             goes on x, R = 1 is added into the empty A (A = 1), R = 1.
;   power     E rounds: R := R * base (copy R onto Q base-1 times, then merge
;             Q into R). Then the marker moves to the next base (x, y, then z)
;             and R is added into A: the 0 between them is filled and a new
;             R = 1 is cut from the end of the block. After z, A = 1 + x^E + y^E
;             and R = z^E: compare.
;   compare   erase one cell of A (from the right) and one of R (from the
;             left) in turn; if R runs out with exactly one cell of A left,
;             x^E + y^E = z^E: HALT. Otherwise clear the work area, restore A
;             and R and go back to enumerate.
; ============================================================================

blank_symbol: 0
"""

