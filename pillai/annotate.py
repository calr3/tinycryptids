def roles():
    """design state -> description, from the routine and line of build.py that made it"""
    desc = {}
    src = open(build.__file__).read().splitlines()
    orig = build.S
    secs = {f for f, _ in SECTIONS}
    def S(name, t0, t1):
        stack = inspect.stack()[1:]
        sec = next(fr for fr in stack if fr.filename == build.__file__ and fr.function in secs)
        helpers = [HELPERS[fr.function] for fr in stack
                   if fr.filename == build.__file__ and fr.function in HELPERS]
        hcall = next((fr for fr in stack if fr.filename == build.__file__ and fr.function in secs), None)
        line = stack[0]
        m0 = re.search(r'#\s*(.*)$', src[line.lineno - 1]) if line.function not in HELPERS else None
        mh = re.search(r'#\s*(.*)$', src[hcall.lineno - 1]) if helpers else None
        parts = helpers[:1] + [x.group(1) for x in (m0, mh) if x]
        text = '; '.join(dict.fromkeys(parts)) or 'step'
        if name.startswith('sd'):
            text = 'write x = 1 0 1 1 1 (the hole on cell 1 counts the blocks still to write)'
        if name in DESC:
            text = DESC[name] if not helpers else helpers[0] + '; ' + DESC[name]
        desc[name] = (sec.function, text)
        orig(name, t0, t1)
    build.S = S
    build.build()
    build.S = orig
    return desc

def main(src, dst, lean):
    o, S, _ = tm.parse(open('pillai.txt').read())
    o2, S2, _ = tm.parse(open(src).read())
    phi = leangen.state_map(o, S, o2, S2)
    ROLE = roles()
    assert set(ROLE) == set(o), set(o) ^ set(ROLE)
    (bs, bb), (os_, ob) = build.BEEP, build.BOOP
    cls = defaultdict(list)
    for q in o: cls[phi[q]].append(q)
    sec_of = {f: i for i, (f, _) in enumerate(SECTIONS)}
    pos = {r: i for i, r in enumerate(o)}
    name = {c: '_'.join(m) for c, m in cls.items()}
    name[o2[0]] = 'start_' + name[o2[0]]
    def key(c):
        prim = next((r for r in cls[c] if ROLE[r][0] != 'seed'), cls[c][0])
        return (c != o2[0], sec_of[ROLE[prim][0]], pos[prim])
    out = [HEADER.format(n=len(o2), N=len(o), lean=lean, beep=name[phi[bs]])]
    cur = None
    for c in sorted(o2, key=key):
        sec = key(c)[1] if c != o2[0] else -1
        if sec != cur:
            title = 'START' if sec == -1 else SECTIONS[sec][1]
            out += ['', f'; ---------- {title} ' + '-' * max(0, 60 - len(title)), '']
            cur = sec
        for r in cls[c]:
            out.append(f'; {r:6} [{ROLE[r][0]}] {ROLE[r][1]}')
        out.append(name[c])
        for b, t in enumerate(S2[c]):
            if t is None:
                out.append('    -'); continue
            users = [r for r in cls[c] if S[r][b] is not None]
            tgt = name.get(t[2], t[2])
            mark = ('   BEEP' if (c, b) == (phi[bs], bb) else '') + ('   BOOP' if (c, b) == (phi[os_], ob) else '')
            out.append(f'    {b} {t[0]} {t[1]} {tgt:20} ; [{", ".join(users)}]{mark}')
    text = '\n'.join(out) + '\n'
    # the annotated machine must be the same machine (up to state names)
    o3, S3, _ = tm.parse(text)
    assert o3[0] == name[o2[0]] and len(o3) == len(o2)
    for c in o2:
        assert S3[name[c]] == [None if t is None else (t[0], t[1], name.get(t[2], t[2])) for t in S2[c]]
    open(dst, 'w').write(text)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3])
