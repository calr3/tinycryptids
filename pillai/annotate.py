"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design (pillai.txt, generated by
build.py). The merged state is named after its roles, each role is listed with a description
(the routine of build.py that made it, the helper it belongs to, and the comment on its line
there), and every transition line is tagged with the roles that use it; the beep and the
boop transitions are marked BEEP and BOOP.
Usage: python3 annotate.py merged.txt out.txt LeanName
"""
import os, sys, inspect, re
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))  # tm.py
from collections import defaultdict
import tm, leangen, build

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol BEEPING BOOPING Turing machine whose output repeats a
; value forever IFF PILLAI'S CONJECTURE IS FALSE.
;
; THE BEEP is the transition of state {beep} reading 1 (marked BEEP below),
; THE BOOP the transition of the same state reading 0 (marked BOOP below).
; Started on a blank tape in the first state, the machine never halts. Its
; output is the sequence of beep counts between consecutive boops (Bram
; Cohen's Beeping Booping Busy Beavers). Some value occurs in it infinitely
; often iff some k >= 1 has infinitely many solutions of a^x - b^y = k with
; a, b, x, y >= 2, i.e. iff Pillai's conjecture fails.
; Lean proof: lean/TinyCryptids/Pillai/{lean}.lean,
; theorem TM.Pillai.{lean}.repeats_iff (and never_halts).
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / pillai.txt with states
;   merged. States are merged only when their defined transitions agree, and
;   no other state joins the beep/boop state (it reads both symbols), so the
;   two special transitions are taken exactly where the design takes them.
;   Each state below plays one or more ROLES of the design (its name joins
;   them); each transition line is tagged [role] with the role(s) that use
;   it. A '-' line is never used.
;
; THE IDEA
;   For every (x, y, a, b) with x, y, a, b >= 2 (NEXCOM order of the block
;   lengths, which reaches every tuple): A := 1 + a^x, R := b^y, then erase a
;   cell of A and a cell of R in turn. If R runs out first with A - R >= 2,
;   i.e. a^x > b^y, the next cell of A is erased, each further one with a
;   BEEP (a^x - b^y - 1 beeps), then the BOOP. Otherwise no event. So a
;   value v repeats forever iff a^x - b^y = v + 1 has infinitely many
;   solutions.
;
; TAPE LAYOUT (unary blocks of 1s separated by 00; a single 0 inside a
; block is a HOLE, a cursor)
;
;      x 00 y 00 a 00 b 00 M 00 A 0 R 0 Q
;
;   x, y: E + 2 cells for the exponent E; the exponent cursor on cells
;         1 .. E + 1 (x's cell 1 is the anchor between tuples).
;   a, b: v + 2 cells for the base v; a marker hole on cell 1 of the base
;         being powered, its round cursor on cells 3 .. v + 1.
;   M: one cell. A: 1 + a^x after the first power. R: the running power
;   (its hole is the single 0 after A). Q: scratch for copies of R.
; ============================================================================

blank_symbol: 0
"""

