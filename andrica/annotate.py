HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF ANDRICA'S CONJECTURE IS
; FALSE, i.e. iff some consecutive primes p < q have 4p <= (q - p - 1)^2
; (sqrt(q) - sqrt(p) >= 1).
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/Andrica/{lean}.lean,
; theorem TM.Andrica.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / andrica.txt with states
;   merged. States are merged only when their defined transitions agree, so
;   each state below plays one or more ROLES of the design (its name joins
;   them). Each transition line is tagged [role] with the role(s) that use it.
;   A '-' line is never used. The seed roles run once at the start and only
;   ever read 0, so all of them double as a step of some other routine.
;
; THE IDEA
;   Let t(m) be the least t with t^2 >= 4m. Then 4p <= g^2 iff t(p) <= g, so
;   the conjecture fails iff after some prime p the next t(p) numbers are all
;   composite. The machine tests m = 2, 3, 4, ... and keeps a countdown: a
;   prime sets it to t(m), a composite counts down, and it halts when the
;   countdown runs out.
;
; TAPE LAYOUT
;
;      H 00 U 00 T 00 D 00 R
;
;   H: t + 1 cells, t = t(m), with a HOLE (a single 0) at cell 2j - 1 when m
;   is the j-th number with t(m) = t (there are floor(t/2) of them).
;   U 00 T: |U| + |T| = t (U may be empty: four 0s); |T| is the countdown.
;   D 00 R (as in ../legendre): D = 1 0 1^d (d + 2 cells, its hole cycling),
;   R has r + 2 cells, d + r = m.
;
; ALGORITHM (m = 2, 3, 4, ...)
;   test      trial division of m by d = 2, 3, ... (../legendre's mod walk:
;             r times advance the D hole cyclically, then R's hole; the D
;             hole back on cell 1 means d | m). Ends at k1 (composite) or
;             sh6 (r = 0: m is prime).
;   countdown composite: scan left to the U/T separator (the second 00) and
;             move it one cell right; T now empty: HALT. Prime: a parser
;             crosses D's hole, the same scan, then the separator is filled
;             and written again at U's left end (|T| = t).
;   phase     a parser finds H's hole and moves it two cells right. If it
;             would leave H: H's last cell joins the separator, whose last
;             cell becomes U's new cell 0 (t + 1 for U + T), and two new
;             cells on H's left hold the new hole at cell 1.
;   next m    a parser finds D's hole; D := 2, R := m - 1 (a cell more).
;   seed      write m = 2: 1011 00 00 111 00 1011 00 11, left to right.
; ============================================================================

blank_symbol: 0
"""


