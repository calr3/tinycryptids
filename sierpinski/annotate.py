"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design
(sierpinski.txt, generated by build.py). The merged state is named after its
roles, listed with a description, and every transition line is tagged with the
roles that use it. Usage: python3 annotate.py merged.txt out.txt LeanName
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))  # tm.py
from collections import defaultdict
import tm, build

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF NO ODD k < 78557 IS A
; SIERPINSKI NUMBER, i.e. iff every odd k < 78557 has some n >= 1 with
; k*2^n + 1 prime. (A Sigma_1 statement: the machine halts iff it is TRUE.)
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/Sierpinski/{lean}.lean, theorem TM.Sierpinski.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / sierpinski.txt with
;   states merged. States are merged only when their defined transitions agree,
;   so each state below plays one or more ROLES of the design (its name joins
;   them). Each transition line is tagged [role] with the role(s) that use it.
;   A '-' line is never used. The seed roles run once at the start and only
;   ever read 0, so most of them double as a step of some other routine.
;
; TAPE LAYOUT (blocks of 1s; separators 0 or 00):
;
;      C 0 K 0 D 00 R
;
;   C  a binary counter c: four groups of four bits b3 b2 b1 b0, each followed
;      by a marker 1, most significant group first; c is the number of k
;      still to come after the current one
;   K  k + 6 cells while k is tested (no hole)
;   D  d+1 cells (0..d): the trial divisor d >= 3; its HOLE (a single 0)
;      steps cyclically over cells 1..d; its HOME is cell d, D's last cell
;   R  r+1 cells: r = P - d; during the mod walk its hole steps from cell 0
;
; ALGORITHM (k = 3, 5, ..., 78555; for each k, P = k*2 + 1, k*4 + 1, ...)
;   mod walk  r rounds: advance the D hole cyclically, then the R hole. When
;             the R hole falls off, d | P iff the D hole is home; the head
;             comes back over R and reads D's last cell.
;   composite (home) fill the hole and the separator, D := 3 (hole home at
;             cell 3), R := the rest with its hole at cell 0, then the loop
;             doubles R: the next P is 2P - 1 = k*2^(n+1) + 1.
;   shift     (not home) fill the hole; the first separator cell becomes D's
;             new last cell, still 0: d := d+1, hole home; R loses its cell 0
;             (r := r-1) and gets its hole at its new cell 0.  If R is then a
;             single cell, r = 0 and P is prime.
;   prime     wipe D and R and append a cell to K; the loop moves K one cell
;             right into K' and copies it to T beyond K'; then decrement C
;             (HALT if it was 0: k was 78555); fill the cell left of K'
;             (k := k + 2); T becomes D := 3 and R, and the loop doubles R.
;   loop      erase the last cell of X; it reappears as the first cell of X'
;             (single 0s between X, X' and T) and one more cell is appended to
;             T. It stops at the first 0: the R hole, or the separator left of
;             K; t1 reads the cell left of it: 0 for R, C's marker 1 for K.
;   seed      write C = 39278 and K for the step to k = 1, whose region lacks
;             R's cell 0 (g6 makes the hole on a blank cell): its candidate is
;             5, a prime; then the step to k = 3.
; ============================================================================

blank_symbol: 0
"""

R = 'right'; L = 'left'
def parser(direction, then):
    return f'scan {direction} to the next hole, then {then}'

ROLE = {
    'ma1': 'advance the D hole: fill it',
    'ma2': 'advance the D hole: next cell 1: the new hole, go to the R hole (PR); 0: D ended, wrap around',
    'mw1': 'wrap around: run left to the start of D',
    'mw2': 'wrap around: step over cell 0',
    'mw3': 'wrap around: new hole at cell 1, then go to the R hole (PR)',
    'PR1': parser(R, 'advance the R hole (ra1)'),
    'PR2': parser(R, 'advance the R hole (ra1)'),
    'ra1': 'advance the R hole: fill it',
    'ra2': 'advance the R hole: step over the next cell',
    'ra3': 'advance the R hole: last cell of R? 0: yes, the walk is over: back over R (e1)',
    'ra4': 'advance the R hole: make the new hole, then back to the D hole (PM)',
    'PM1': parser(L, 'advance the D hole (ma1)'),
    'PM2': parser(L, 'advance the D hole (ma1)'),
    'e1': 'walk over: run left over R',
    'e2': 'walk over: step over the separator',
    'e3': "divisor test on D's last cell: 0: the hole is home, d | P: composite (fill it, x1); 1: shift (f1)",
    'f1': 'shift: run left to the D hole and fill it',
    'f2': "shift: run right to the separator; its first cell stays 0: D's new home (d+1)",
    'f3': 'shift: step over the separator',
    'f4': "shift: erase R's cell 0 (r-1)",
    'f5': "shift: the R hole at R's new cell 0",
    'f6': 'shift: does R have another cell? 1: the walk for d+1 (PM2); 0: r = 0: P is prime, wipe (w1)',
    'x1': 'composite: fill the separator',
    'x2': 'composite: fill the separator, back',
    'x3': 'composite: run left to the start of D',
    'x4': "composite: step over D's cell 0",
    'g1': "D := 3: step over cell 1 (a new k enters here from b6)",
    'g2': 'D := 3: step over cell 2',
    'g3': "D := 3: its hole, home at cell 3",
    'g4': 'D := 3: separator after D',
    'g5': 'D := 3: separator after D',
    'g6': "the R hole at R's cell 0 (the loop stops there; at the start on a blank cell)",
    'g7': 'run right to the end of R, then the loop (s1)',
    'w1': 'prime: skip the 0s of R and the separator, erase the first 1',
    'w2': "prime: erase D; on K's separator: append a cell to K",
    'w3': "prime: back onto K's new last cell, the loop on K (s1)",
    's1': 'loop: erase the last cell of X; 0: X is used up (t1)',
    's4': "loop: the cell joins X' on its left",
    's6': "loop: run right over X' and the X'/T separator",
    's6c': 'loop: run right over T, append a cell',
    's7': "loop: run left over T and the X'/T separator",
    's7c': "loop: run left over X', to the new last cell of X",
    't1': "loop end: 0: X was R (stopped at its hole), finish the doubling (a1); 1: X was K, C's marker: decrement C (D0)",
    'a1': 'doubling: step over the R hole',
    'a2': 'doubling: fill the gap',
    'a4': "doubling: run right over X', fill the X'/T separator",
    'a6': 'doubling: run left to the R hole, then to the D hole (PM): the mod walk for the next P',
    'Dm': 'counter: a group marker; 0: past the top group, c was 0: HALT',
    'D0': 'counter: bit 0 of the group; 0: borrow (write 1, go on); 1: write 0, done (ret)',
    'D1': 'counter: bit 1 of the group; 0: borrow; 1: write 0, done',
    'D2': 'counter: bit 2 of the group; 0: borrow; 1: write 0, done',
    'D3': 'counter: bit 3 of the group; 0: borrow, to the next group; 1: write 0, done',
    'ret': 'counter: run right over C and its separator',
    'b2': "new k: fill the cell left of K' (K gets 2 cells)",
    'b4': "new k: run right over K' (now part of K) and the separator",
    'b6': "new k: step over T's cell 0 (D's cell 0), then D := 3 (g1)",
}
SEED = build.counter_cells(build.C0 + build.NF) + '0' + '1' * (7 - 2 * build.NF) + '0'
for i, ch in enumerate(SEED):
    ROLE[f'seed{i}'] = f'seed: write {ch} and step right' + (' (then the loop, s4)' if i == len(SEED) - 1 else '')

SECTIONS = [
    ('MOD WALK: does d divide P?', 'ma1 ma2 mw1 mw2 mw3 PR1 PR2 ra1 ra2 ra3 ra4 PM1 PM2 e1 e2 e3'),
    ('SHIFT: d+1, r-1', 'f1 f2 f3 f4 f5 f6'),
    ('COMPOSITE: D := 3, R with a hole', 'x1 x2 x3 x4 g1 g2 g3 g4 g5 g6 g7'),
    ('PRIME: wipe D and R', 'w1 w2 w3'),
    ("LOOP: X moves to X', copied to T", 's1 s4 s6 s6c s7 s7c t1'),
    ('END OF THE DOUBLING', 'a1 a2 a4 a6'),
    ('COUNTER: decrement C, HALT if it was 0', 'Dm D0 D1 D2 D3 ret'),
    ('NEW k: K += 2, T becomes the region', 'b2 b4 b6'),
    ('SEED only', ' '.join(f'seed{i}' for i in range(len(SEED)))),
]

def main(src, dst, lean):
    build.build()
    o, S, _ = tm.parse(open('sierpinski.txt').read())
    assert (o, S) == (build.ORDER, build.ST)
    o2, S2, _ = tm.parse(open(src).read())
    phi, todo = {o[0]: o2[0]}, [o[0]]
    while todo:
        q = todo.pop()
        for b, t in enumerate(S[q]):
            if t is None or t[2] not in S: continue
            t2 = S2[phi[q]][b]
            assert t2 is not None and t2[:2] == t[:2]
            if t[2] in phi: assert phi[t[2]] == t2[2]
            else: phi[t[2]] = t2[2]; todo.append(t[2])
    assert set(phi) == set(o) and set(ROLE) == set(o), set(o) ^ set(ROLE)
    cls = defaultdict(list)
    for q in o: cls[phi[q]].append(q)
    sec_of = {r: i for i, (_, rs) in enumerate(SECTIONS) for r in rs.split()}
    assert set(sec_of) == set(o), set(o) ^ set(sec_of)
    pos = {r: i for i, r in enumerate(o)}
    name = {}
    for c, members in cls.items():
        work = [r for r in members if not r.startswith('seed')]
        name[c] = '_'.join(work) if work else members[0]
    name[o2[0]] = 'start_' + name[o2[0]]
    def key(c):
        prim = next((r for r in cls[c] if not r.startswith('seed')), cls[c][0])
        return (c != o2[0], sec_of[prim], pos[prim])
    out = [HEADER.format(n=len(o2), N=len(o), lean=lean)]
    cur = None
    for c in sorted(o2, key=key):
        sec = key(c)[1] if c != o2[0] else -1
        if sec != cur:
            title = 'START' if sec == -1 else SECTIONS[sec][0]
            out += ['', f'; ---------- {title} ' + '-' * max(0, 60 - len(title)), '']
            cur = sec
        for r in cls[c]:
            out.append(f'; {r:6} {ROLE[r]}')
        out.append(name[c])
        for b, t in enumerate(S2[c]):
            if t is None:
                out.append('    -'); continue
            users = [r for r in cls[c] if S[r][b] is not None]
            tgt = name.get(t[2], t[2])
            out.append(f'    {b} {t[0]} {t[1]} {tgt:20} ; [{", ".join(users)}]')
    text = '\n'.join(out) + '\n'
    # the annotated machine must be the same machine (up to state names)
    o3, S3, _ = tm.parse(text)
    assert o3[0] == name[o2[0]] and len(o3) == len(o2)
    for c in o2:
        assert S3[name[c]] == [None if t is None else (t[0], t[1], name.get(t[2], t[2])) for t in S2[c]]
    open(dst, 'w').write(text)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'M60')
