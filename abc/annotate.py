"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design (abc.txt, generated by
build.py). The merged state is named after its roles, each role is listed with a description
(the routine of build.py that made it, the helper it belongs to, and the comment on its line
there), and every transition line is tagged with the roles that use it; the beep and the
boop transitions are marked BEEP and BOOP.
Usage: python3 annotate.py merged.txt out.txt LeanName
"""
import os, sys, inspect, re
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))  # tm.py
from collections import defaultdict
import tm, leangen, build

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol BEEPING BOOPING Turing machine whose output repeats a
; value forever IFF THE ABC CONJECTURE IS FALSE.
;
; THE BEEP is the transition of state {beep} reading 0 (marked BEEP below),
; THE BOOP the transition of state {boop} reading 0 (marked BOOP below).
; Started on a blank tape in the first state, the machine never halts. Its
; output is the sequence of beep counts between consecutive boops (Bram
; Cohen's Beeping Booping Busy Beavers). Some value occurs in it infinitely
; often iff, for some n >= 1, infinitely many coprime a + b = c have
; c^n > rad(abc)^(n+1), i.e. iff the abc conjecture fails.
; Lean proof: lean/TinyCryptids/ABC/{lean}.lean,
; theorem TM.ABC.{lean}.repeats_iff (and never_halts).
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / abc.txt with states
;   merged. States are merged only when their defined transitions agree, and
;   no state that reads 0 joins the beep state or the boop state, so the two
;   special transitions are taken exactly where the design takes them. Each
;   state below plays one or more ROLES of the design (its name joins them);
;   each transition line is tagged [role] with the role(s) that use it. A '-'
;   line is never used.
;
; THE IDEA
;   For c = 2, 3, ... and a = 1 .. c - 1, b = c - a:
;   factor   trial divisors d = 2 .. c: d HITS if gcd(d, x) > 1 for x = a, b
;            or c (lockstep holes, GCD(D, X)); a hit with gcd(d, R) = 1 does
;            R := R * d. Then R = rad(abc). At d = c a hit on a or b means
;            gcd(a, b) > 1: skip the pair.
;   pretest  c <= R: skip the pair.
;   powers   P := 1, Q := R; repeat: compare P with Q; P <= Q: BEEP,
;            P := P * c, Q := Q * R; P > Q: BOOP, next pair. So a pair that
;            passes beeps v times, v = the least n with c^n > R^(n+1), then
;            boops; a skipped pair is silent.
;
; TAPE LAYOUT (numbers in unary; a block of v + 2 cells holds v, a single 0
; inside it is a HOLE (a cursor); blocks are separated by 00)
;
;      [P 00] K 00 D 00 A 00 B 00 C 00 M 00 R [00 Q]
;
;   K: c - d + 1 cells, no hole: the countdown for d.  D: the divisor d.
;   A, B, C: a, b, c.  M: one cell (a marker).  R: rad so far.
;   P = c^n (grown leftwards), Q = R^(n+1) (grown rightwards) in the powers.
; ============================================================================

blank_symbol: 0
"""

SECTIONS = [
    ('seed', 'SEED: K = 1, D = 2, A = B = 1, C = 2, M; then R := 1 and the pair (1, 1)'),
    ('gcd_routine', 'FACTOR PHASE: the tests GCD(D, X) for X = A, B, C, R'),
    ('next_d', 'd += 1 (K gives a cell to D), or d = c: to the pre-test'),
    ('pretest', 'PRE-TEST: compare C with R'),
    ('compare', 'COMPARE X with Y (the pre-test C, R; the loop P, Q): BEEP, BOOP'),
    ('power_init', 'POWERS: P := 1, Q := 1, then Q := Q * R'),
    ('right_mult', 'R := R * d (factor phase) and Q := Q * R (powers)'),
    ('beep_step', 'AFTER THE BEEP: cursors back, then P := P * c'),
    ('left_mult', 'P := P * c (mirrored multiplication), then Q := Q * R'),
    ('pair_end', 'END OF THE PAIR: erase R and Q, the next pair, R := 1, d := 2'),
]
HELPERS = {
    'parser': 'parser: move to the next hole (00 pairs crossed)',
    'adv': 'advance a cyclic hole one position',
    'copy_loop': 'copy loop: copy Z onto the scratch block',
    'multiply': 'multiplication round',
    'finder': 'finder: move right to the one-cell block M',
}

def roles():
    """design state -> description, from the routine and line of build.py that made it"""
    desc = {}
    src = open(build.__file__).read().splitlines()
    orig = build.S
    secs = {f for f, _ in SECTIONS}
    def S(name, t0, t1):
        stack = inspect.stack()[1:]
        sec = next(fr for fr in stack if fr.filename == build.__file__ and fr.function in secs)
        helpers = [HELPERS[fr.function] for fr in stack
                   if fr.filename == build.__file__ and fr.function in HELPERS]
        m = re.search(r'#\s*(.*)$', src[sec.lineno - 1])
        line = stack[0]
        m0 = re.search(r'#\s*(.*)$', src[line.lineno - 1]) if line.function not in secs else None
        parts = [h for h in helpers[:1]] + [x.group(1) for x in (m0, m) if x]
        text = '; '.join(dict.fromkeys(parts)) or 'step'
        if sec.function == 'seed':
            text = 'write the next cell of the seed 1 00 1111 00 111 00 111 00 1111 00 1'
        desc[name] = (sec.function, text)
        orig(name, t0, t1)
    build.S = S
    build.build()
    build.S = orig
    return desc

def main(src, dst, lean):
    o, S, _ = tm.parse(open('abc.txt').read())
    o2, S2, _ = tm.parse(open(src).read())
    phi = leangen.state_map(o, S, o2, S2)
    ROLE = roles()
    assert set(ROLE) == set(o), set(o) ^ set(ROLE)
    (bs, bb), (os_, ob) = build.BEEP, build.BOOP
    cls = defaultdict(list)
    for q in o: cls[phi[q]].append(q)
    sec_of = {f: i for i, (f, _) in enumerate(SECTIONS)}
    pos = {r: i for i, r in enumerate(o)}
    name = {c: '_'.join(m) for c, m in cls.items()}
    name[o2[0]] = 'start_' + name[o2[0]]
    def key(c):
        return (c != o2[0], sec_of[ROLE[cls[c][0]][0]], pos[cls[c][0]])
    out = [HEADER.format(n=len(o2), N=len(o), lean=lean, beep=name[phi[bs]], boop=name[phi[os_]])]
    cur = None
    for c in sorted(o2, key=key):
        sec = key(c)[1] if c != o2[0] else -1
        if sec != cur:
            title = 'START' if sec == -1 else SECTIONS[sec][1]
            out += ['', f'; ---------- {title} ' + '-' * max(0, 60 - len(title)), '']
            cur = sec
        for r in cls[c]:
            out.append(f'; {r:6} [{ROLE[r][0]}] {ROLE[r][1]}')
        out.append(name[c])
        for b, t in enumerate(S2[c]):
            if t is None:
                out.append('    -'); continue
            users = [r for r in cls[c] if S[r][b] is not None]
            tgt = name.get(t[2], t[2])
            mark = ('   BEEP' if (c, b) == (phi[bs], bb) else '') + ('   BOOP' if (c, b) == (phi[os_], ob) else '')
            out.append(f'    {b} {t[0]} {t[1]} {tgt:20} ; [{", ".join(users)}]{mark}')
    text = '\n'.join(out) + '\n'
    # the annotated machine must be the same machine (up to state names)
    o3, S3, _ = tm.parse(text)
    assert o3[0] == name[o2[0]] and len(o3) == len(o2)
    for c in o2:
        assert S3[name[c]] == [None if t is None else (t[0], t[1], name.get(t[2], t[2])) for t in S2[c]]
    open(dst, 'w').write(text)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3])
