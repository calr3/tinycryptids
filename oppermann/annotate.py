HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF OPPERMANN'S CONJECTURE
; IS FALSE, i.e. iff for some n >= 2 no prime lies in (n^2 - n, n^2) or none
; in (n^2, n^2 + n).
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/Oppermann/{lean}.lean, theorem TM.Oppermann.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / oppermann.txt with states
;   merged. States are merged only when their defined transitions agree, so
;   each state below plays one or more ROLES of the design (its name joins
;   them). Each transition line is tagged [role] with the role(s) that use it.
;   A '-' line is never used. The seed roles run once at the start and only
;   ever read 0, so each of them doubles as a step of some other routine.
;
; THE INTERVALS: with q(j) = floor(j^2/4), (n^2 - n, n^2) = (q(2n-1), q(2n))
;   and (n^2, n^2 + n) = (q(2n), q(2n+1)). Interval j >= 3 is taken as the
;   ceil(j/2) numbers q(j) .. q(j+1) - 1 (q(j) is not prime for j >= 4).
;
; TAPE LAYOUT (blocks of 1s separated by 00):
;
;      [1 0] Q 00 D 00 R
;
;   Q  j+2 cells; its HOLE (a single 0) at cell 2k+1 marks m = q(j) + k, the
;      k-th number of interval j: the hole moves two cells per number
;   1  the flag "a prime was seen in this interval", two cells left of Q
;   D  d+2 cells: the trial divisor d >= 2; its hole at cell c+1 is a cyclic
;      counter c in [0, d)
;   R  r+2 cells: r = m - d; during the mod walk its hole counts the steps
;   A hole is never next to a separator 00, so 2-state "scan to the next
;   hole" routines do all the navigation.
;
; ALGORITHM (m = 2, 3, 4, ...; for each m, d = 2, ..., m-1 with r = m - d)
;   mod walk  r times: advance the D hole cyclically, then the R hole. When
;             the R hole runs off its block, d | m iff the D hole is back at
;             cell 1: then m is composite.
;   shift     d := d+1, r := r-1; when r = 0, m is prime: set the flag.
;   advance   move the Q hole two cells. If it runs off Q, interval j is
;             over: HALT if the flag is not set; else the flag is erased, the
;             0 next to it becomes cell 0 of the next Q (one cell longer) and
;             the old cell 0 its hole.
;   rebuild   D := 2, R := m - 1, i.e. the next number m + 1.
;   seed      write 10111 00 1011 00 11: interval 3 at m = 2.
; ============================================================================

blank_symbol: 0
"""

R = 'right'; L = 'left'
