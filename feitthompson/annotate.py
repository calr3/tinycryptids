SECTIONS = [
    ('CYC(counter, cycled): counter | |cycled| ?',
     'ca1 ca2 ca3 ca4 ca5 ca6 ca7 PC1 PC2 cy1 cy2 cy3 cy4 cy5 cy6 cy7 PN1 PN2 PK1 PK2 '
     'k1 k2 k3 kd3 kd4 kd5 kn3 kn4 kn5 kn6'),
    ('NEXT CANDIDATE: M += 1, L += 1', 'PM1 PM2 ms PX1 PX2 PY1 PY2 lp1 lp2 lp3 lp4 u1 u2'),
    ('PAIR PASS: retreat, push R', 'rt1 rt2 rt3 rt4 rt5 pw1 pw2 pw3 pp2 pp3'),
    ('HORNER: R := b R + 1, e - 1 times',
     'HE1 HE2 HF1 HF2 HG1 HG2 HH1 HH2 ea1 ea2 ea3 ea4 ea5 ea6 ea7 MB1 MB2 '
     'ba1 ba2 ba3 ba4 ba5 ba6 ba7 MC1 MC2 MD1 MD2 MM1 MM2 MN1 MN2 '
     'c1 c2 c3 c4 c5 c6 a2 a3 a4 d1 d2 d3 NB1 NB2 NC1 NC2 mR m2 m3 m4'),
    ('HORNER DONE: H2, the test, or the P0 step', 'hd1 hd2 hd3 hd4 hn5 hz5 hn6 hz6 tw1 tw2 tw3 t1 t2'),
    ('CLEAN UP after a failed test', 'cl1 cl3 cl4 cl5 cl6 cl7 RA1 RA2 RB1 RB2 rf'),
    ('P0 STEP: the new M', 'pz1 pz2 PO1 PO2 pz3'),
    ('SEED only', ' '.join(SEED)),
]

def main(src, dst, lean):
    o, S, _ = tm.parse(open('feitthompson.txt').read())
    o2, S2, _ = tm.parse(open(src).read())
    phi, todo = {o[0]: o2[0]}, [o[0]]
    while todo:
        q = todo.pop()
        for b, t in enumerate(S[q]):
            if t is None or t[2] not in S: continue
            t2 = S2[phi[q]][b]
            assert t2 is not None and t2[:2] == t[:2]
            if t[2] in phi: assert phi[t[2]] == t2[2]
            else: phi[t[2]] = t2[2]; todo.append(t[2])
    assert set(phi) == set(o) and set(ROLE) == set(o), set(o) ^ set(ROLE)
    secs = [r for _, rs in SECTIONS for r in rs.split()]
    assert sorted(secs) == sorted(o), set(o) ^ set(secs)
    cls = defaultdict(list)
    for q in o: cls[phi[q]].append(q)
    sec_of = {r: i for i, (_, rs) in enumerate(SECTIONS) for r in rs.split()}
    pos = {r: i for i, r in enumerate(o)}
    name = {}
    for c, members in cls.items():
        work = [r for r in members if not r.startswith('seed')]
        name[c] = '_'.join(work) if work else members[0]
    name[o2[0]] = 'start_' + name[o2[0]]
    def key(c):
        prim = next((r for r in cls[c] if not r.startswith('seed')), cls[c][0])
        return (c != o2[0], sec_of[prim], pos[prim])
    out = [HEADER.format(n=len(o2), N=len(o), lean=lean)]
    cur = None
    for c in sorted(o2, key=key):
        sec = key(c)[1] if c != o2[0] else -1
        if sec != cur:
            title = 'START' if sec == -1 else SECTIONS[sec][0]
            out += ['', f'; ---------- {title} ' + '-' * max(0, 60 - len(title)), '']
            cur = sec
        for r in cls[c]:
            out.append(f'; {r:6} {ROLE[r]}')
        out.append(name[c])
        for b, t in enumerate(S2[c]):
            if t is None:
                out.append('    -'); continue
            users = [r for r in cls[c] if S[r][b] is not None]
            tgt = name.get(t[2], t[2])
            out.append(f'    {b} {t[0]} {t[1]} {tgt:20} ; [{", ".join(users)}]')
    text = '\n'.join(out) + '\n'
    # the annotated machine must be the same machine (up to state names)
    o3, S3, _ = tm.parse(text)
    assert o3[0] == name[o2[0]] and len(o3) == len(o2)
    for c in o2:
        assert S3[name[c]] == [None if t is None else (t[0], t[1], name.get(t[2], t[2])) for t in S2[c]]
    open(dst, 'w').write(text)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'M106')
