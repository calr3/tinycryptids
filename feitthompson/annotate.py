HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF THE FEIT-THOMPSON
; CONJECTURE FAILS: iff there are distinct primes p, q with rep p q | rep q p,
; where rep b n = 1 + b + ... + b^(n-1). It tests rep m p | rep p m for every
; prime m and every prime p < m (equivalent: Lean's ft_iff).
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/FeitThompson/{lean}.lean,
; theorem TM.FeitThompson.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / feitthompson.txt with
;   states merged. States are merged only when their defined transitions
;   agree, so each state below plays one or more ROLES of the design (its name
;   joins them). Each transition line is tagged [role] with the role(s) that
;   use it. A '-' line is never used. The seed roles run once at the start and
;   only ever read 0, so each of them doubles as a step of some other routine.
;
; TAPE LAYOUT
;
;      L 00 P0 00 P1 00 ... 00 Pk 00 M [00 A [00 B]]
;
;   A block holding v has v + 2 cells; cells 1..v are the positions of a
;   CYCLIC HOLE (a single 0). Advancing the hole moves it one cell right, from
;   cell v back to cell 1 (a wrap).
;   L, M  the candidate m, each with a hole (at cell 1 at rest).
;   P0    111: the value 1. P1 < ... < Pk: the primes < m. These blocks are
;         full except the MARKER (a hole at cell 1) of the block being visited.
;   A, B  the work blocks of a pair test: A = rep p m, B = rep m p.
;
; ALGORITHM (candidate m = 3, 4, 5, ...)
;   trial   for the marked Pi (i = 1..k): CYC(Pi, L): L's hole goes round once,
;           Pi's hole advances before each of its m steps, so it is back at
;           cell 1 iff Pi | m. Composite: M += 1, L += 1, marker on P1, again.
;           Else the marker moves right; on M (M's hole at cell 1): m is prime.
;   pairs   for the marked Pi (i = k..1), at the right end:
;           Horner H1 (skip M, base Pi, exponent L): A = rep p m;
;           Horner H2 (skip A, base M, exponent Pi): B = rep m p;
;           CYC(B, A): B | A: HALT. Else erase A and B, marker one block left.
;   P0      Horner H1 with base P0 writes rep 1 m = m: the next M. The old M
;           (a prime) joins the list; as for a composite, M += 1, L += 1.
;   Horner  pushes R = 101 and finds holes from the right: one skipped, the
;           base b, the exponent e; e - 1 rounds R := b R + 1 (b - 1 copies of
;           R after a '00', then the '00' filled and one cell erased).
;   seed    writes m = 2 (no primes, the marker on P0) and starts its P0 step.
; ============================================================================

blank_symbol: 0
"""

R = 'right'; L = 'left'
def parser(direction, then):
    return f'scan {direction} to the next hole, then {then}'

ROLE = {}
def P(prefix, direction, then):
    for i in '12': ROLE[prefix + i] = parser(direction, then)
def ADV(p, what, nonwrap, wrap):
    ROLE[p+'1'] = f'advance the {what} hole: fill it'
    ROLE[p+'2'] = f'advance the {what} hole: step right'
    ROLE[p+'3'] = f'advance the {what} hole: 1: not its last cell; 0: it was, wrap'
    ROLE[p+'4'] = f'advance the {what} hole: the new hole, then {nonwrap}'
    ROLE[p+'5'] = f'wrap the {what} hole: run left over the block'
    ROLE[p+'6'] = f'wrap the {what} hole: step over cell 0'
    ROLE[p+'7'] = f'wrap the {what} hole: the new hole at cell 1, then {wrap}'
def WALK(p, then):
    ROLE[p+'1'] = 'run right to three 0s in a row'
    ROLE[p+'2'] = 'run right to three 0s: one 0 seen'
    ROLE[p+'3'] = f'run right to three 0s: two 0s seen; on the third: {then}'

