HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF FIROOZBAKHT'S CONJECTURE
; FAILS: iff there are consecutive primes p < q with p^(n+1) <= q^n, where
; n = pi(p) is the number of primes <= p.
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/Firoozbakht/{lean}.lean,
; theorem TM.Firoozbakht.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / firoozbakht.txt with
;   states merged. States are merged only when their defined transitions
;   agree, so each state below plays one or more ROLES of the design (its name
;   joins them). Each transition line is tagged [role] with the role(s) that
;   use it. A '-' line is never used. The seed roles run once at the start and
;   only ever read 0, so each of them doubles as a step of some other routine.
;
; TAPE LAYOUT
;
;      N 00 P1 00 P2 00 ... 00 Pk 00 M [00 M' 00 B [00 A]]
;
;   A block holding v has v + 2 cells; cells 1..v are the positions of a
;   CYCLIC HOLE (a single 0). Advancing the hole moves it one cell right, from
;   cell v back to cell 1 (a wrap).
;   N     k + 2, k = the number of primes < m; its hole at cell 1 at rest.
;   P1 < ... < Pk: the primes < m. Full except the MARKER (a hole at cell 1)
;         of the block being visited.
;   M     the candidate m, with a hole (at cell 1 at rest).
;   M', B, A  the work blocks when m = q is prime: a copy of q, B = p^(k+1),
;         A = q^k (p = Pk, the prime before q).
;
; ALGORITHM (candidate m = 3, 4, 5, ...)
;   trial   for the marked Pi (i = 1..k): CYC(Pi, M): M's hole goes round once,
;           Pi's hole advances before each of its m steps, so it is back at
;           cell 1 iff Pi | m. Composite: M += 1, back to N, marker on P1.
;           Else the marker moves right; on M (M's hole at cell 1): m is prime.
;   prime   the marker back on Pk; M is copied onto M' and joins the list.
;           Power run H_B (skip M', base Pk, exponent N, hole at cell 1):
;           B = p^(k+1). Pk's marker is filled; N grows by a cell on its left,
;           its hole moves to cell 3. Power run H_A (skip B, base M', exponent
;           N): A = q^k. Which run ended is read off the block after the first
;           hole right of N: P(k+1) (cell 1 is a 1) or B (cell 1 is B's hole).
;   compare erase the last cell of B, then of A, in turn: B used up first:
;           HALT (B <= A). A used up first: erase both, M' += 1, next candidate.
;   power   pushes R = 101 and finds holes from the right: one skipped, the
;           base b, the exponent e; one round R := b R per advance of the
;           exponent hole (b - 1 copies of R after a '00', then the '00' filled
;           and two cells erased).
;   seed    writes N = 3, P1 = 2, M = 2 and makes M one longer: m = 3.
; ============================================================================

blank_symbol: 0
"""

R = 'right'; L = 'left'
def parser(direction, then):
    return f'scan {direction} to the next hole, then {then}'

ROLE = {}
def P(prefix, direction, then):
    for i in '12': ROLE[prefix + i] = parser(direction, then)
def ADV(p, what, nonwrap, wrap):
    ROLE[p+'1'] = f'advance the {what} hole: fill it'
    ROLE[p+'2'] = f'advance the {what} hole: step right'
    ROLE[p+'3'] = f'advance the {what} hole: 1: not its last cell; 0: it was, wrap'
    ROLE[p+'4'] = f'advance the {what} hole: the new hole, then {nonwrap}'
    ROLE[p+'5'] = f'wrap the {what} hole: run left over the block'
    ROLE[p+'6'] = f'wrap the {what} hole: step over cell 0'
    ROLE[p+'7'] = f'wrap the {what} hole: the new hole at cell 1, then {wrap}'
def WALK(p, then):
    ROLE[p+'1'] = 'run right to three 0s in a row'
    ROLE[p+'2'] = 'run right to three 0s: one 0 seen'
    ROLE[p+'3'] = f'run right to three 0s: two 0s seen; on the third: {then}'

ADV('ca', 'counter', 'to the cycled block (PC)', 'to the cycled block (PC)')
