HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF LEHMER'S TOTIENT PROBLEM
; HAS A COUNTEREXAMPLE, i.e. iff some composite n has phi(n) | n - 1.
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/LehmerTotient/{lean}.lean,
; theorem TM.LehmerTotient.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / lehmertotient.txt with
;   states merged. States are merged only when their defined transitions
;   agree, so each state below plays one or more ROLES of the design (its name
;   joins them). Each transition line is tagged [role] with the role(s) that
;   use it. A '-' line is never used. The seed roles run once at the start and
;   only ever read 0, so all of them double as a step of some other routine.
;
; TAPE LAYOUT
;
;      1 K 00 1 R 00 [D 00 P]
;
;   K/R (as in ../carmichael): k and r slots, k + r = n, each with a HOLE (a
;   single 0) that ticks cyclically. The PAIR D 00 P (as in ../legendre):
;   D = 1 0 1^d (d + 2 cells, its hole on cell 1), P has p + 2 cells,
;   d + p = n - 1; d counts the coprime pairs so far.
;
; ALGORITHM (n = 3, 4, 5, ...)
;   count     for k = 2, ..., n - 1: the walk tests gcd(k, n - k) = 1 (K's
;             hole and R's hole tick in lockstep; when K's hole wraps, R's hole
;             on its first slot means coprime, on its last means not). Coprime:
;             the pair's separator moves one cell right (d += 1, p -= 1). Then
;             r = 1 ends the round, else K/R's separator moves right.
;             At the end d = phi(n) (k = 1 counted from the start: d = 1).
;   test      K/R -> (1, n); to the pair: p = 0 (n prime): next n. Else one
;             mod walk (p times advance the D hole cyclically, then P's hole):
;             the D hole back on cell 1 means phi(n) | p, so phi(n) | n - 1
;             with n composite: HALT.
;   next n    a cell after P; the separator and D's hole filled, D := 1
;             (1 0 1 00 from D's left end); back to R; K/R -> (2, n - 1).
;   seed      write round 3: 1 0 1 00 1 0 00 101 00 111, right to left.
; ============================================================================

blank_symbol: 0
"""


