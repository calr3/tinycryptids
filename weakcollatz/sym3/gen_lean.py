"""Emit lean/TinyCryptids/WeakCollatz3/Machine.lean from weakcollatz3.txt (3 symbols)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'tools'))
import tm
SYM = ['s0', 's1', 's2']
order, ST, _ = tm.parse(open(os.path.join(HERE, 'weakcollatz3.txt')).read())
L = ['import TinyCryptids.Core.Basic3', '',
     f'/-! The {len(order)}-state, 3-symbol machine, generated by `gen_lean.py` from `weakcollatz3.txt`. -/',
     '', 'namespace TM3.WeakCollatz', '', 'inductive St']
L += [f'  | {n}' for n in order] + ['  | halt', 'deriving DecidableEq, Repr', '', 'open St Sym Dir in',
      'def delta : St → Sym → Option (Sym × Dir × St)']
for n in order:
    for r, t in enumerate(ST[n]):
        if t is None: L.append(f'  | {n}, {SYM[r]} => none'); continue
        w, d, q = t
        L.append(f'  | {n}, {SYM[r]} => some ({SYM[w]}, {d}, {q if q in ST else "halt"})')
L += ['  | halt, _ => none', '', 'def start : Cfg St := ⟨St.disp, blank, blank⟩', '', 'end TM3.WeakCollatz', '']
out = os.path.join(HERE, '..', '..', 'lean', 'TinyCryptids', 'WeakCollatz3', 'Machine.lean')
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w').write('\n'.join(L))
print(len(order), 'states written')
