"""Generator for a 10-state, 3-symbol Turing machine that halts iff the Collatz
map C(x) = x/2 (x even), 3x+1 (x odd) has a cycle other than 1 -> 4 -> 2 -> 1.

The algorithm is the one of ../build.py (the 14-state, 2-symbol machine): rounds
M = 3, 4, 5, ...: v := M, then repeat v := T(v) until v = 1 or v >= M; halt iff
v = M, with T(x) = x/2 (x even), (3x+1)/2 (x odd) the shortcut map.

Tape C(M, v), 1 <= v <= M: cells 0 .. M-2 hold 1, except a HOLE (0) at cell
v-1; cell M-1 holds the END MARK 2; everything else is 0.  The head is on cell
0 in `disp`.  For v = M the end mark is the hole: the block is M-1 ones, then 2.

Step:
  v = 1     `disp` reads the hole on cell 0 and writes a 2 there; `toHO` runs to
            the end mark and makes it a 1, `hop` writes the new end mark on cell
            M, and `home` turns the 2 on cell 0 into a 1: C(M+1, M+1).
  halving   `disp` writes a MARKER (0) on cell 0.  Per round trip `toH` fills the
            hole (the end mark stays 2), `newH` writes the hole one cell left,
            `back` fills the marker and `mark` writes it one cell right.  They
            meet: on neighbouring cells (`newH` reads the marker, v = 2k): the
            marker, cell k-1, is the result hole;  on the same cell (`mark` reads
            the hole, v = 2k+1): the hole is on cell k.
  odd       `mark` writes the ODD MARKER (2) on cell k and `newH` the hole on
            k+1.  Per round trip `back` fills the odd marker and `markO` writes it
            one cell left; `toHO` fills the hole, `hop` skips a cell and `newH`
            writes the hole: on the end mark it leaves the 2 (the hole is on cell
            M-1).  When the marker passes cell 0 (`markO` reads 0) the hole is on
            cell 3k+1 = T(v)-1: `check` runs to it; the end mark means T(v) = M:
            HALT.  If the hole has to move past the end mark first (`toHO` reads
            the end mark, or `hop` does: T(v) > M), the end mark becomes a 1, `hop`
            writes a new one on cell M and `home` fills the odd marker: C(M+1, M+1).
  home      run left over 1s and 2s (writing 1s) to cell -1, step right.
On the blank tape `disp` acts as for v = 1 and makes C(3, 3).

Against the 14-state machine: the end mark makes `peek` unnecessary (the hole on
the end mark is T(v) = M) and lets one state, `hop`, both skip a cell and write a
new end mark; `back` serves both loops (the two markers differ); `home` also
fills the odd marker (no `fill`), and `newH` both moves the hole left (halving)
and writes it two cells right (odd).
"""
import sys
ST = {}
ORDER = []
def S(name, t0, t1, t2):
    assert name not in ST, name
    ST[name] = [t0, t1, t2]; ORDER.append(name)
def T(w, d, n): return (w, d, n)

def build(halt_state='halt'):
    ST.clear(); ORDER.clear()
    S('disp',  T(2,'R','toHO'), T(0,'R','toH'), None)          # 0: v = 1; 1: the marker on cell 0
    # halving: the hole moves left, the marker right
    S('toH',   T(1,'L','newH'), T(1,'R','toH'), T(2,'L','newH'))  # 2: the hole is the end mark
    S('newH',  T(0,'L','home'), T(0,'L','back'), T(2,'L','back'))  # 0: the marker is next to the hole (v even)
    S('back',  T(1,'R','mark'), T(1,'L','back'), T(1,'L','markO'))  # 0: halving marker; 2: odd marker
    S('mark',  T(2,'R','newH'), T(0,'R','toH'), None)          # 0: the marker meets the hole (v odd)
    # odd: the marker moves left, the hole right by two
    S('markO', T(0,'R','check'), T(2,'R','toHO'), None)        # 0: the marker passed cell 0
    S('toHO',  T(1,'R','hop'), T(1,'R','toHO'), T(1,'R','hop'))   # 2: the hole is on the end mark: T(v) > M
    S('hop',   T(2,'L','home'), T(1,'R','newH'), T(1,'R','hop'))  # 0: past the end mark; 2: T(v) > M
    S('home',  T(0,'R','disp'), T(1,'L','home'), T(1,'L','home'))
    S('check', T(0,'L','home'), T(1,'R','check'), T(1,'R',halt_state))  # 2: T(v) = M
    refs = {t[2] for v in ST.values() for t in v if t}
    assert not (refs - set(ST) - {halt_state}), refs - set(ST)
    assert not (set(ST) - refs - {ORDER[0]}), set(ST) - refs
    lines = ['; Halts iff the Collatz map has a cycle other than 1 -> 4 -> 2 -> 1.',
             f'; {len(ORDER)} states, 3 symbols. Generated by build.py.', '', 'blank_symbol: 0', '']
    for n in ORDER:
        lines.append(n)
        for r, t in enumerate(ST[n]):
            lines.append('    -' if t is None else f'    {r} {t[0]} {t[1]} {t[2]}')
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    out = build()
    open(sys.argv[1] if len(sys.argv) > 1 else 'weakcollatz3.txt', 'w').write(out)
    print(len(ORDER), 'states')
