"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design
(weakcollatz.txt, generated by build.py). The merged state is named after its
roles, listed with a description, and every transition line is tagged with the
roles that use it. Usage: python3 annotate.py merged.txt out.txt LeanName
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))  # tm.py
from collections import defaultdict
import tm

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF THE COLLATZ MAP HAS A
; CYCLE OTHER THAN 1 -> 4 -> 2 -> 1 (the weak Collatz conjecture is false).
; Collatz map: C(x) = x/2 for even x, 3x+1 for odd x.
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/WeakCollatz/{lean}.lean, theorem TM.WeakCollatz.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / weakcollatz.txt with
;   states merged. States are merged only when their defined transitions
;   agree, so each state below plays one or more ROLES of the design (its name
;   joins them). Each transition line is tagged [role] with the role(s) that
;   use it. A '-' line is never used.
;
; ALGORITHM: rounds n = 1, 2, 3, ...: x := n, then x := C(x) until x >= n or
;   x = 1; HALT iff x = n. A nontrivial cycle with largest element M makes
;   round M halt; a round can only run forever if its orbit stays in [2, n-1],
;   i.e. falls into a nontrivial cycle whose round already halted.
;
; TAPE: one block of n+2 cells (0 .. n+1), all 1 except the HOLE H (a single
;   0) at cell x, 1 <= x <= n.  Cells 0 and n+1 stay 1 between steps.
;
; STEP (head on H):
;   parity  run left to cell 0, walk right to H counting parity.
;   even    a second hole G walks from x-1 to the left end, 2 cells per round;
;           H moves left 1 cell per round: H ends at x/2.  x/2 = 1: next round.
;   odd     G := x, H := x+1; G walks to the left end 1 cell per round, H
;           moves right 2 cells per round: H ends at 3x+1.  H runs off the
;           block (3x+1 > n): next round.  3x+1 = n: HALT.
;   next    the block grows by one cell; H := the new last value cell n+1.
;   seed    write the tape of an aborted round 0.
; ============================================================================

blank_symbol: 0
"""

ROLE = {
    'seed': 'seed: write cell 0, then continue as after an odd step (hf)',
    's0': 'step start: run left to H, step over it',
    'gl': 'run left to the left end of the block, then count parity (p0)',
    'p0': 'parity walk, even so far; 0: H reached, x even (spawn the even loop)',
    'p1': 'parity walk, odd so far; 0: H reached, x odd (spawn the odd loop)',
    'sp': 'even: H moves to x-1; G starts (virtually) at x-1',
    'gm1': 'even loop: G moves left 2: step over the first cell',
    'gm2': 'even loop: G lands 2 cells left; 0: G ran off the left end (c0)',
    'hr': 'even loop: run right to H, fill it',
    'hm': 'even loop: H moves left 1 cell',
    'ge': 'even loop: run left to G, fill it',
    'c0': 'even done: step over cell 0',
    'c1': 'even done: 0: H at cell 1, x = 1: next round (b1); 1: continue the parity walk (p0)',
    'os': 'odd: H := x+1 (the old hole is G)',
    'go': 'odd loop: run left to G, fill it',
    'og': 'odd loop: G moves left 1; 0: G ran off the left end, find H (hf)',
    'hr2': 'odd loop: run right to H, fill it',
    'hx1': 'odd loop: H moves right: first cell; 0: off the block: next round (a2)',
    'hx2': 'odd loop: H lands 2 cells right; 0: off the block: next round (a2)',
    'hf': 'odd done: run right to H, step over it',
    'pk1': 'check: 0: H at cell n+1 (3x+1 > n): the block grows: next round',
    'pk2': 'check: 0: H at cell n, 3x+1 = n: HALT; 1: next step (s0)',
    'a2': 'next round: run left to G, fill it, then grow (b1)',
    'b1': 'next round: run right to the end, one more cell',
    'b2': 'next round: the old last cell becomes H; count parity from cell 0 (gl)',
}

SECTIONS = [
    ('STEP START AND PARITY', 's0 gl p0 p1'),
    ('x EVEN: H := x/2', 'sp gm1 gm2 hr hm ge c0 c1'),
    ('x ODD: H := 3x+1', 'os go og hr2 hx1 hx2'),
    ('CHECK 3x+1 = n; HALT if so', 'hf pk1 pk2'),
    ('NEXT ROUND', 'a2 b1 b2'),
    ('SEED only', 'seed'),
]

def main(src, dst, lean):
    o, S, _ = tm.parse(open('weakcollatz.txt').read())
    o2, S2, _ = tm.parse(open(src).read())
    phi, todo = {o[0]: o2[0]}, [o[0]]
    while todo:
        q = todo.pop()
        for b, t in enumerate(S[q]):
            if t is None or t[2] not in S: continue
            t2 = S2[phi[q]][b]
            assert t2 is not None and t2[:2] == t[:2]
            if t[2] in phi: assert phi[t[2]] == t2[2]
            else: phi[t[2]] = t2[2]; todo.append(t[2])
    assert set(phi) == set(o) and set(ROLE) == set(o), set(o) ^ set(ROLE)
    cls = defaultdict(list)
    for q in o: cls[phi[q]].append(q)
    sec_of = {r: i for i, (_, rs) in enumerate(SECTIONS) for r in rs.split()}
    pos = {r: i for i, r in enumerate(o)}
    name = {}
    for c, members in cls.items():
        work = [r for r in members if r != 'seed']
        name[c] = '_'.join(work) if work else members[0]
    name[o2[0]] = 'start_' + name[o2[0]]
    def key(c):
        prim = next((r for r in cls[c] if r != 'seed'), cls[c][0])
        return (c != o2[0], sec_of[prim], pos[prim])
    out = [HEADER.format(n=len(o2), N=len(o), lean=lean)]
    cur = None
    for c in sorted(o2, key=key):
        sec = key(c)[1] if c != o2[0] else -1
        if sec != cur:
            title = 'START' if sec == -1 else SECTIONS[sec][0]
            out += ['', f'; ---------- {title} ' + '-' * max(0, 60 - len(title)), '']
            cur = sec
        for r in cls[c]:
            out.append(f'; {r:6} {ROLE[r]}')
        out.append(name[c])
        for b, t in enumerate(S2[c]):
            if t is None:
                out.append('    -'); continue
            users = [r for r in cls[c] if S[r][b] is not None]
            tgt = name.get(t[2], t[2])
            out.append(f'    {b} {t[0]} {t[1]} {tgt:20} ; [{", ".join(users)}]')
    text = '\n'.join(out) + '\n'
    # the annotated machine must be the same machine (up to state names)
    o3, S3, _ = tm.parse(text)
    assert o3[0] == name[o2[0]] and len(o3) == len(o2)
    for c in o2:
        assert S3[name[c]] == [None if t is None else (t[0], t[1], name.get(t[2], t[2])) for t in S2[c]]
    open(dst, 'w').write(text)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'M23')
