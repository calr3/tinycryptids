HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF A PERFECT CUBOID EXISTS:
; positive integers a, b, c with a^2+b^2, a^2+c^2, b^2+c^2 and a^2+b^2+c^2 all
; perfect squares (a box whose edges, face diagonals and space diagonal are all
; integers). Started on a blank tape in the first state.
; Lean proof: lean/TinyCryptids/PerfectCuboid/{lean}.lean,
; theorem TM.PerfectCuboid.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / perfectcuboid.txt with
;   states merged (only states whose defined transitions agree). Each state
;   below plays one or more ROLES of the design (its name joins them); each
;   transition line is tagged [role] with the role(s) that use it. A '-' line is
;   never used.
;
; TAPE LAYOUT (blank on both sides)
;
;      A 00 B 00 C 00 Z  G  S
;
;   A, B, C: blocks of L >= 4 ones, standing for the edges v(L) = L/2 - 1.
;   Z = 111: a block worth 0 that closes the queue A B C Z.
;   G: eight cells, the window counter W: 00000000 (W = 0), 00001100 (W = 1),
;      00110000 (W = 2).
;   S: a counter: a leading 1, 2k+1 cycle cells with one hole, a terminator 1.
;      The hole on cycle cell j means N = k^2 + j units; N is a square iff j = 0.
;
; ALGORITHM
;   A block X of L cells, set up, has its hole h on its last cell and a mark m
;   on cell L-3: the region m+2 .. L-1 (of 1, 3, 5, ... cells, as m moves two
;   cells left after each full cycle of h). One unit = h one cell further in
;   its region (cyclically), then S one step (a full cycle of S grows it by
;   two). So X adds v(L)^2 units to S (1 + 3 + ... + (2v - 1)).
;   The blocks run cyclically (A B C Z A ...). After each block the next one is
;   set up and S is checked: not a square -> the next tuple. A square: W ticks;
;   when it wraps, S is reset. The windows between resets are
;   [A B C] [Z A B] [C Z A] [B C Z], so the checks test a^2+b^2, a^2+b^2+c^2,
;   c^2+a^2 and b^2+c^2. At the end of the queue with W = 2 (the fourth
;   window passed): HALT.
;   The next tuple: S's hole home, W := 2, the holes of the block in hand
;   filled, then NEXCOM on (A, B, C) (compositions of every total, parts at
;   least 4 cells, A with the free end on the left).
;   Start: S's leading 1; the abort routine writes the rest of S and G, finds no
;   queue, and a chain writes Z and (4, 4, 4).
; ============================================================================

blank_symbol: 0
"""

