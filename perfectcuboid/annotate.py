"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design (perfectcuboid.txt,
generated by build.py). The merged state is named after its roles, listed with a
description, and every transition line is tagged with the roles that use it.
Usage: python3 annotate.py merged.txt out.txt LeanName
"""
