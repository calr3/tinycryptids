"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design
(legendre.txt, generated by build.py). The merged state is named after its
roles, listed with a description, and every transition line is tagged with the
roles that use it. Usage: python3 annotate.py merged.txt out.txt LeanName
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))  # tm.py
import sys
from collections import defaultdict
import tm

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF LEGENDRE'S CONJECTURE
; IS FALSE, i.e. iff for some n >= 1 no prime p satisfies n^2 < p < (n+1)^2.
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/LegendreSieve/{lean}.lean, theorem TM.LegendreSieve.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {nd}-state design of build.py / legendre.txt with
;   states merged. States are merged only when their defined transitions
;   agree, so each state below plays one or more ROLES of the design (its name
;   joins them). Each transition line is tagged [role] with the role(s) that
;   use it. A '-' line is never used. The seed roles run once at the start and
;   only ever read 0, so most states double as a seed step.
;
; TAPE LAYOUT at checkpoint m (after deciding m; blocks of 1s):
;
;      M 00 P_k 00 ... 00 P_1 000 S 0 F
;
;   M     1^(m+2), a plain counter (the only block without a hole).
;   P_i   one block per prime p <= m, largest first: a 1, a region of p
;         cells holding one HOLE (a single 0), a 1. The hole sits at region
;         index p-1-(m mod p): it moves one cell LEFT per step and wraps from
;         index 0 to index p-1 exactly when p divides the new m.
;   S     the square counter, same shape with a region of 2n+1 cells
;         (n = isqrt m), hole at index 2n-(m-n^2). It wraps exactly when the
;         new m is a square, (n+1)^2.
;   F     one cell: 1 iff a prime was seen since the last square n^2.
;   The 000 in front of S is the only run of exactly three 0s; the left end
;   of the tape is the only run of four or more.
;
; ALGORITHM (one round per m, starting from m = 1)
;   home      go left to the left end (four 0s) and add a 1 to M.
;   sweep     scan right; at every hole move it one cell left (or wrap it).
;             Two copies: "prime so far" and "composite" (some block wrapped,
;             so a prime <= m divides m+1). The 000 ends the sweep.
;   S, composite   move S's hole; if it wraps, m+1 = (n+1)^2: if F = 0 no
;             prime was seen in (n^2, (n+1)^2): HALT. Otherwise the F cell
;             becomes S's new right guard (region += 2, F cleared). Go home.
;   S, prime  move S's hole (it cannot wrap), set F, go home and copy M to
;             its left: old M (length m+3 = p+2) becomes the block of the new
;             prime p = m+1, with its hole at the last index (p | p).
; ============================================================================

blank_symbol: 0
"""

ROLE = {
    'hg1': 'home: scan left over 1s', 'hg2': 'home: one 0 seen', 'hg3': 'home: two 0s seen',
    'hg4': 'home: three 0s seen; a fourth 0 is the left end',
    'hg5': 'home: turn round (this is the checkpoint)', 'hg6': 'home: step right',
    'hg7': 'home: write a 1 left of M (M += 1), start the sweep',
    'hc1': 'home before copying: scan left over 1s', 'hc2': 'home before copying: one 0 seen',
    'hc3': 'home before copying: two 0s seen',
    'hc4': 'home before copying: three 0s seen; at the fourth write the new M\'s first 1',
    'hc5': 'copy setup: new M\'s second 1', 'hc6': 'copy setup: separator', 'hc7': 'copy setup: separator',
    'hc8': 'copy setup: step over old M\'s left guard', 'hc9': 'copy setup: cursor at old M index 0',
    'cL1': 'copy: left over old M', 'cL2': 'copy: separator', 'cL3': 'copy: left over the new M, add a 1',
    'cR1': 'copy: back right to the cursor (parser)', 'cR2': 'copy: parser, 1 = one past the cursor',
    'cQ2': 'copy: 0 = cursor was at the last index (done, go home); 1 = move it right',
    'cQ3': 'copy: new cursor', 'cQ4': 'copy: fill the old cursor',
    'W2': 'wrap: to the separator after the block', 'W3': 'wrap: right guard',
    'W4': 'wrap: hole at the last index; continue in composite mode',
    'sp1': 'S (prime mode): find the hole', 'sp2': 'S (prime mode): parser, found',
    'sA': 'S (prime mode): fill the hole', 'sB': 'S (prime mode): step left', 'sC': 'S (prime mode): look two left',
    'sD': 'S (prime mode): new hole one cell left', 'sE': 'S (prime mode): to the right end',
    'sG': 'S (prime mode): F := 1, go home and copy',
    'sq1': 'S (composite): find the hole', 'sq2': 'S (composite): parser, found',
    'tA': 'S (composite): fill the hole', 'tB': 'S (composite): step left',
    'tC': 'S (composite): look two left; 0 = hole was at index 0: square',
    'tD': 'S (composite): new hole one cell left, go home',
    'tW': 'square: to the cell after S\'s right guard',
    'tF': 'square: F = 0 -> HALT; F = 1 -> it becomes the new guard, go home',
}
for m, mode in (('p', 'prime so far'), ('q', 'composite')):
    ROLE.update({
        m+'1': f'sweep ({mode}): scan right over 1s', m+'2': f'sweep ({mode}): one 0 seen; 1 = a hole',
        m+'3': f'sweep ({mode}): two 0s seen; a third 0 ends the sweep (S follows)',
        m+'A': f'sweep ({mode}): fill the hole', m+'B': f'sweep ({mode}): step left',
        m+'C': f'sweep ({mode}): look two left; 0 = hole was at index 0: wrap',
        m+'D': f'sweep ({mode}): new hole one cell left'})
SEED = '111' + '000' + '11101'
for i, ch in enumerate(SEED):
    ROLE[f'seed{i}'] = f'seed: write {ch} (cell {i} of the seed, the tape at m = 1)'

SECTIONS = [
    ('HOME and grow M', 'hg1 hg2 hg3 hg4 hg5 hg6 hg7'),
    ('SWEEP, prime so far', 'p1 p2 p3 pA pB pC pD'),
    ('SWEEP, composite', 'q1 q2 q3 qA qB qC qD W2 W3 W4'),
    ('S after a prime-mode sweep', 'sp1 sp2 sA sB sC sD sE sG'),
    ('S after a composite-mode sweep; HALT', 'sq1 sq2 tA tB tC tD tW tF'),
    ('COPY M (new prime)', 'hc1 hc2 hc3 hc4 hc5 hc6 hc7 hc8 hc9 cL1 cL2 cL3 cR1 cR2 cQ2 cQ3 cQ4'),
    ('SEED only', ' '.join(f'seed{i}' for i in range(len(SEED)))),
]

def main(src, dst, lean):
    o, S, _ = tm.parse(open('legendre.txt').read())
    o2, S2, _ = tm.parse(open(src).read())
    phi, todo = {o[0]: o2[0]}, [o[0]]
    while todo:
        q = todo.pop()
        for b, t in enumerate(S[q]):
            if t is None or t[2] not in S: continue
            t2 = S2[phi[q]][b]
            assert t2 is not None and t2[:2] == t[:2]
            if t[2] in phi: assert phi[t[2]] == t2[2]
            else: phi[t[2]] = t2[2]; todo.append(t[2])
    assert set(phi) == set(o) and set(ROLE) == set(o), set(o) ^ set(ROLE)
    cls = defaultdict(list)
    for q in o: cls[phi[q]].append(q)
    sec_of = {r: i for i, (_, rs) in enumerate(SECTIONS) for r in rs.split()}
    pos = {r: i for i, r in enumerate(o)}
    name = {}
    for c, members in cls.items():
        work = [r for r in members if not r.startswith('seed')]
        name[c] = '_'.join(work) if work else members[0]
    name[o2[0]] = 'start_' + name[o2[0]]
    def key(c):
        prim = next((r for r in cls[c] if not r.startswith('seed')), cls[c][0])
        return (c != o2[0], sec_of[prim], pos[prim])
    out = [HEADER.format(n=len(o2), nd=len(o), lean=lean)]
    cur = None
    for c in sorted(o2, key=key):
        sec = key(c)[1] if c != o2[0] else -1
        if sec != cur:
            title = 'START' if sec == -1 else SECTIONS[sec][0]
            out += ['', f'; ---------- {title} ' + '-' * max(0, 60 - len(title)), '']
            cur = sec
        for r in cls[c]:
            out.append(f'; {r:6} {ROLE[r]}')
        out.append(name[c])
        for b, t in enumerate(S2[c]):
            if t is None:
                out.append('    -'); continue
            users = [r for r in cls[c] if S[r][b] is not None]
            tgt = name.get(t[2], t[2])
            out.append(f'    {b} {t[0]} {t[1]} {tgt:24} ; [{", ".join(users)}]')
    open(dst, 'w').write('\n'.join(out) + '\n')
    # sanity: the annotated file is the same machine
    o3, S3, _ = tm.parse(open(dst).read())
    ren = {name[c]: c for c in o2}
    assert len(o3) == len(o2)
    for s in o3:
        for b in range(2):
            t3, t2 = S3[s][b], S2[ren[s]][b]
            assert (t3 is None) == (t2 is None)
            if t3: assert t3[:2] == t2[:2] and ren.get(t3[2], t3[2]) == t2[2]

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'M45')
