"""Emit lean/TinyCryptids/TwinPrimes4/Machine.lean from twinprimes4.txt (4 symbols, the model
of Core/Multi.lean): `delta`, and `deltaNB`, the machine without its beep transition (state
`beep` reading 0)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'tools'))
import tm
BEEP = ('beep', 0)
order, ST, _ = tm.parse(open(os.path.join(HERE, 'twinprimes4.txt')).read())
nsym = len(ST[order[0]])

def table(name):
    L = ['open St TM.Dir in', f'def {name} : St → Nat → Option (Nat × TM.Dir × St)']
    for n in order:
        for r, t in enumerate(ST[n]):
            if t is None: continue
            w, d, q = t
            L.append(f'  | {n}, {r} => some ({w}, {d}, {q})')
    return L + ['  | _, _ => none']

L = ['import TinyCryptids.Core.Multi', '',
     '/-!', f'The {len(order)}-state, {nsym}-symbol machine, generated by `twinprimes/sym4/gen_lean.py` '
     'from `twinprimes4.txt`.', f'`delta` is the machine; `deltaNB` is `delta` without its beep '
     f'transition (`{BEEP[0]}` reading {BEEP[1]}).', '-/', '',
     'namespace TMK.TwinPrimes4', '', 'inductive St']
L += [f'  | {n}' for n in order] + ['deriving DecidableEq, Repr', '']
L += table('delta') + ['', f'/-- `delta` without its beep transition (`{BEEP[0]}` reading {BEEP[1]}) -/',
      'def deltaNB (q : St) (b : Nat) : Option (Nat × TM.Dir × St) :=',
      f'  if q = St.{BEEP[0]} ∧ b = {BEEP[1]} then none else delta q b', '']
L += [f'def start : Cfg St := ⟨St.{order[0]}, blank, blank⟩', '', 'end TMK.TwinPrimes4', '']
out = os.path.join(HERE, '..', '..', 'lean', 'TinyCryptids', 'TwinPrimes4', 'Machine.lean')
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w').write('\n'.join(L))
print(len(order), 'states written')
