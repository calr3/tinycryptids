"""Generator for a 10-state, 4-symbol beeping Turing machine with 27 instructions that never
halts and beeps (state `beep` reading 0) infinitely often iff the twin prime conjecture is
true: it QUASIHALTS iff the conjecture is FALSE.

The algorithm is the one of ../build.py (the 18/19-state 2-symbol machine): candidates m,
trial divisors d = 2, 3, ..., one mod walk per d testing both m and m + 2. The extra symbols
let D and R be told apart without a separator.

Symbols: 0 blank, 1 an R cell, 2 the D marker or the R cursor, 3 a D cell.

Tape (blank elsewhere):  D R
  - D (d cells, cells 0..d-1): 3s, except the MARKER 2 on cell c: a counter mod d.
  - R (r = m - d cells): 1s; during the mod walk the CURSOR 2 moves left through it.
Walk (from R's last cell, D's marker on its last cell): r times: make the cursor one cell
  further left (`cur`), run left to the marker (`toM`), move it one cell right (`adv`; past
  D's last cell `adv` reads R's cell 0, a 1 or the cursor, and `wrap` puts it on cell 0), run
  right to the cursor (`toR`) and fill it. The marker ends on c = (m - 1) mod d.
Check, when `cur` reaches D's last cell: the marker on d - 1 (d | m) or on d - 3 (d | m + 2)
  is a FAIL; on d - 2 (`chk2`) or further left (`wrap` runs to it) d passed.
Shift (d passed): `grow` erases the marker, runs right and puts it on R's cell 0: d := d + 1,
  r := r - 1, the marker on D's new last cell; `toR` runs to R's end and the walk starts.
FAIL: `reb` turns every D cell into an R cell (a zigzag: `3 -> 1 R`, then back over the 1),
  writes a 3 on the blank left of the tape, and `grow` makes the old cell 0 the marker:
  D = 3 2, R = 1^(m-1): candidate m + 1, d = 2.
BEEP: when R is empty after a shift (d = m: every d < m passed, m and m + 2 are prime), the
  walk ends at once, the check fails (the marker on d - 1), and `reb` reads the blank right
  of D: it writes a 3 there, `grow` a 1, and `beep` reads the blank: the beep. Then `reb`
  converts the tape as for a FAIL: candidate m + 3 (m + 1 and m + 2 are no lesser twin
  primes for m >= 5; after m = 3 the twin prime 5 is skipped).
Start: `reb` on the blank tape takes the beep path with an empty D (one extra beep, at step
  2) and builds candidate 3.
"""
import sys
ST = {}          # name -> [t0, t1, t2, t3]
ORDER = []
BEEP = ('beep', 0)
def S(name, *ts):
    assert name not in ST, name
    ST[name] = list(ts); ORDER.append(name)
def T(w, d, n): return (w, d, n)
_ = None

def build(variant=None):
    """variant='halt': halt instead of beeping (test: halts at step 2, then at no other
    point). variant='halt2': halt at the second beep (m = 3)."""
    ST.clear(); ORDER.clear()
    beep_next = 'reb'
    #        0                 1                 2                 3
    S('reb',  T(3,'R','grow'),  T(1,'L','reb'),   _,                T(1,'R','reb'))
    S('toR',  T(0,'L','cur'),   T(1,'R','toR'),   T(1,'L','cur'),   T(3,'R','toR'))
    S('cur',  _,                T(2,'L','toM'),   T(1,'R','reb'),   T(3,'L','chk2'))
    S('toM',  _,                T(1,'L','toM'),   T(3,'R','adv'),   T(3,'L','toM'))
    S('adv',  _,                T(1,'L','wrap'),  T(2,'L','wrap'),  T(2,'R','toR'))
    S('wrap', T(0,'R','adv'),   _,                T(3,'R','grow'),  T(3,'L','wrap'))
    S('chk2', _,                _,                T(3,'R','grow'),  T(3,'L','chk3'))
    S('chk3', _,                _,                T(1,'R','reb'),   T(3,'L','wrap'))
    S('grow', T(1,'R','beep'),  T(2,'R','toR'),   _,                T(3,'R','grow'))
    S('beep', T(0,'L',beep_next), _,              _,                _)
    if variant == 'halt':
        ST['beep'][0] = T(0, 'L', 'halt')
    lines = ['; Beeps (state beep reading 0) once at step 2 and once for every lesser twin prime',
             '; p >= 3 except 5; quasihalts (beeps finitely often) iff the twin prime conjecture',
             f'; is false. {len(ORDER)} states, 4 symbols, '
             f'{sum(t is not None for v in ST.values() for t in v)} instructions. Generated by build.py.',
             '', 'blank_symbol: 0', '']
    for n in ORDER:
        lines.append(n)
        for r, t in enumerate(ST[n]):
            mark = '   ; BEEP' if (n, r) == BEEP else ''
            lines.append('    -' if t is None else f'    {r} {t[0]} {t[1]} {t[2]}{mark}')
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    out = build()
    open(sys.argv[1] if len(sys.argv) > 1 else 'twinprimes4.txt', 'w').write(out)
    print(len(ORDER), 'states,', sum(t is not None for v in ST.values() for t in v), 'instructions')
