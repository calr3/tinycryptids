"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design
(twinprimes.txt, generated by build.py). The merged state is named after its
roles, listed with a description, and every transition line is tagged with the
roles that use it; the beep transition is marked BEEP.
Usage: python3 annotate.py merged.txt out.txt LeanName
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))  # tm.py
from collections import defaultdict
import tm, leangen

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol BEEPING Turing machine that QUASIHALTS IFF THE TWIN
; PRIME CONJECTURE IS FALSE.
;
; THE BEEP is the transition of state {beep} reading 0 (marked BEEP below).
; Started on a blank tape in the first state, the machine never halts, and it
; takes the beep transition exactly once for every lesser twin prime p >= 3
; (p and p + 2 both prime), in increasing order: 3, 5, 11, 17, 29, 41, ...
; So it beeps infinitely often iff there are infinitely many twin primes, and
; it quasihalts (beeps only finitely often) iff the conjecture is false.
; Lean proof: lean/TinyCryptids/TwinPrimes/{lean}.lean,
; theorem TM.TwinPrimes.{lean}.quasihalts_iff (and never_halts).
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / twinprimes.txt with states
;   merged. States are merged only when their defined transitions agree, and
;   no state that reads 0 joins the beep state, so the beep transition is taken
;   exactly where the design takes it. Each state below plays one or more
;   ROLES of the design (its name joins them); each transition line is tagged
;   [role] with the role(s) that use it. A '-' line is never used.
;
; THE IDEA
;   For m >= 3, m and m + 2 are both prime iff no d with 2 <= d <= m - 1
;   divides m or m + 2. The machine tests m = 3, 4, 5, ... in turn, each by
;   trial division with d = 2, 3, ..., m - 1; one mod walk per d tests both
;   m and m + 2. When every d has passed, it beeps.
;
; TAPE LAYOUT (blank left of D and right of R)
;
;      D 0 R
;
;   D: d cells, all 1 except a HOLE (a single 0) at cell c: a counter mod d.
;   one 0: the separator.
;   R: r = m - d cells; during the mod walk a hole moves left through it.
;   Holes are found by scanners that count zeros: from one block, pass the
;   separator, stop at the next 0. A hole may sit next to the separator.
;
; ALGORITHM (candidate m, divisor d)
;   walk     D's hole starts on its last cell. r times: make R's hole one cell
;            further left (R's last cell first), scan left to D's hole and move
;            it one cell right (from the last cell back to cell 0), scan right
;            to R's hole. D's hole ends on cell (m - 1) mod d.
;   check    read D's cells d-1, d-2, d-3 from the separator: the hole on
;            d - 1 means d | m, on d - 3 means d | m + 2: FAIL. Otherwise d
;            passed.
;   shift    d := d + 1, r := r - 1: fill the hole; the separator becomes D's
;            last cell (the next hole), R's cell 0 the separator. R empty now:
;            d = m was reached, every d passed: BEEP. Its successor sees the
;            walk end at once and the check fail (m divides m).
;   rebuild  FAIL: fill the hole and the separator, add a 1 at the left end,
;            write D = 10 and the separator: candidate m + 1, d = 2.
;   start    a 1 and the FAIL path once (a pseudo-round): m = 3, d = 2.
; ============================================================================

blank_symbol: 0
"""

ROLE = {
    'Z2': 'scan right to R\'s hole (the 0 after the separator), fill it, step left (B2)',
    'Z1': 'scan right to the separator, then to R\'s hole (Z2)',
    'B2': 'make R\'s hole here and scan left to D\'s hole (Y1); 0: the separator, the walk is over: check (X1)',
    'Y1': 'scan left to the separator, then to D\'s hole (Y2)',
    'Y2': 'scan left to D\'s hole, fill it, step right (A2)',
    'A2': 'advance D\'s hole: the new hole here, then to R\'s hole (Z1); 0: the separator, wrap (W1)',
    'W1': 'wrap: run left to the blank before D',
    'W2': 'wrap: the new hole on D\'s cell 0, then to R\'s hole (Z1)',
    'X1': 'check D\'s cell d - 1: 0: d | m, FAIL (C1)',
    'X2': 'check D\'s cell d - 2: 0: the hole, d passed (H1)',
    'X3': 'check D\'s cell d - 3: 0: d | m + 2, FAIL (C1); 1: d passed (H0)',
    'H0': 'd passed: scan left to the hole, fill it (H1)',
    'H1': 'shift: run right to the separator; it stays 0: D\'s new last cell, the hole',
    'G1': 'shift / rebuild: write the separator (R\'s cell 0)',
    'G2': 'R\'s cell 0 (1): to R\'s end (SC); 0: R is empty, every d passed: BEEP, then the walk ends at once (B2)',
    'SC': 'run right to the end of R, step left: start the walk (B2)',
    'C1': 'FAIL: run right to the separator, fill it',
    'C4': 'rebuild: run left to the blank before D, write a 1 there',
    'C5': 'rebuild: D = 10, the hole on its last cell; then the separator (G1)',
}

SECTIONS = [
    ('WALK: trial division of m = d + r by d', 'B2 Y1 Y2 A2 W1 W2 Z1'),
    ('CHECK: does d divide m or m + 2?', 'X1 X2 X3 H0'),
    ('SHIFT: d := d + 1, r := r - 1, and the BEEP', 'H1 G1 G2 SC'),
    ('REBUILD: the next candidate m + 1, d := 2', 'C1 C4 C5'),
]

def main(src, dst, lean):
    o, S, _ = tm.parse(open('twinprimes.txt').read())
    o2, S2, _ = tm.parse(open(src).read())
    phi = leangen.state_map(o, S, o2, S2)
    assert set(ROLE) == set(o), set(o) ^ set(ROLE)
    bs, bb = 'G2', 0
    cls = defaultdict(list)
    for q in o: cls[phi[q]].append(q)
    sec_of = {r: i for i, (_, rs) in enumerate(SECTIONS) for r in rs.split()}
    pos = {r: i for i, r in enumerate(o)}
    name = {c: '_'.join(m) for c, m in cls.items()}
    name[o2[0]] = 'start_' + name[o2[0]]
    def key(c):
        return (c != o2[0], sec_of.get(cls[c][0], -1), pos[cls[c][0]])
    out = [HEADER.format(n=len(o2), N=len(o), lean=lean, beep=name[phi[bs]])]
    cur = None
    for c in sorted(o2, key=key):
        sec = key(c)[1] if c != o2[0] else -1
        if sec != cur:
            title = 'START (the first step of the walk\'s R scan)' if sec == -1 else SECTIONS[sec][0]
            out += ['', f'; ---------- {title} ' + '-' * max(0, 60 - len(title)), '']
            cur = sec
        for r in cls[c]:
            out.append(f'; {r:6} {ROLE[r]}')
        out.append(name[c])
        for b, t in enumerate(S2[c]):
            if t is None:
                out.append('    -'); continue
            users = [r for r in cls[c] if S[r][b] is not None]
            tgt = name.get(t[2], t[2])
            mark = '   BEEP' if (c, b) == (phi[bs], bb) else ''
            out.append(f'    {b} {t[0]} {t[1]} {tgt:20} ; [{", ".join(users)}]{mark}')
    text = '\n'.join(out) + '\n'
    # the annotated machine must be the same machine (up to state names)
    o3, S3, _ = tm.parse(text)
    assert o3[0] == name[o2[0]] and len(o3) == len(o2)
    for c in o2:
        assert S3[name[c]] == [None if t is None else (t[0], t[1], name.get(t[2], t[2])) for t in S2[c]]
    open(dst, 'w').write(text)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'M18')
