"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design
(zerofree.txt, generated by build.py). The merged state is named after its
non-seed roles, listed with a description, and every transition line is tagged
with the roles that use it. Usage: python3 annotate.py merged.txt out.txt LeanName
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))  # tm.py
from collections import defaultdict
import tm, build

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF SOME POWER 2^n WITH
; n > 86 HAS NO DECIMAL DIGIT 0 (2^86 is conjectured to be the last such power).
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/ZeroFree/{lean}.lean, theorem TM.ZeroFree.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / zerofree.txt with
;   states merged. States are merged only when their defined transitions
;   agree, so each state below plays one or more ROLES of the design (its name
;   joins them). Each transition line is tagged [role] with the role(s) that
;   use it. A '-' line is never used.
;
; TAPE:  v5 g5 v4 g4 ... v0 g0 | 0 0 | b x y z | b x y z | ... | blank
;   counter (bits v_i, guards g_i = 1; starts at 27, overflows at 64), the
;   separator, then the decimal digits of 2^n, least significant first.  A digit
;   d = 2a + b: its parity b, then a (0..4) in three cells x y z.
;
; CODES: between rounds a is in code A: {A}.
;   The pass writes x y z in code B, from the old digit d (b, a), one cell at a
;   time as it reads them; B determines the new a' = (2a + b) mod 5:
;   {B}
;
; ROUND (2^n on the tape, head on the first parity cell):
;   pass    double, least significant digit first: the parity cell takes the
;           carry, x y z are rewritten into code B; carry out = [d >= 5].  A
;           blank group ends the number (carry 1: it becomes the digit 1).
;   scan    right to left: rewrite each digit from B into A, look for the digit 0.
;   found   a digit 0: rewrite the rest into A, then the next pass.
;   count   no digit 0 (the separator 0 0 is reached): add 1 to the counter
;           (HALT if it overflows: the 37th power without a 0), next pass.
; ============================================================================

blank_symbol: 0
"""

def roles():
    """A description of every design state."""
    o, S, _ = tm.parse(build.build())
    R = {}
    for q in o:
        if q.startswith('seed'):
            R[q] = f'seed: write cell {q[4:]} of the counter / separator'
        elif q in ('C0', 'C1'):
            R[q] = f'pass, carry {q[1]}, parity cell: write the carry, read the parity'
        elif q.startswith('P'):
            b, pre = q[1], q[3:]
            cell = 'xyz'[len(pre)]
            R[q] = f'pass, old parity {b}, cell {cell} (read so far: {pre or "-"}): write code B'
        elif q in ('Z1', 'Z2'):
            R[q] = 'pass, blank group: clear it, back to its parity cell'
        elif q == 'Z3':
            R[q] = 'blank group: 0: the number ended, scan the top digit; 1: carry, the new digit 1'
        elif q.startswith('N'):
            R[q] = f'new top digit 1: cell {"xyz"[int(q[1])]} of its code B word'
        elif q[0] in 'SF' and q[1] in 'zyx':
            m = 'scan' if q[0] == 'S' else 'found'
            R[q] = f'{m}, cell {q[1]} (read so far, z first: {q[2:] or "-"}): rewrite into code A'
        elif q == 'Sb1':
            R[q] = 'scan, parity cell of a digit with a = 0: 0: the digit 0 (found)'
        elif q == 'Sb0':
            R[q] = 'scan, parity cell'
        elif q == 'Fb':
            R[q] = 'found, parity cell'
        elif q == 'Fs':
            R[q] = 'found, at the separator: on to the first parity cell (next pass)'
        elif q == 'G':
            R[q] = 'counter, guard cell; 0 (past the top bit): overflow, HALT'
        elif q == 'I':
            R[q] = 'counter, bit: 0 -> 1 (done, go back right); 1 -> 0 (carry left)'
        elif q in ('R1', 'R2'):
            R[q] = 'back right over the counter, stop after the separator 0 0'
    assert set(R) == set(o), set(o) - set(R)
    return o, S, R

SECTIONS = [
    ('PASS: double, code A -> code B', lambda q: q in ('C0', 'C1') or q.startswith('P')),
    ('END OF THE NUMBER', lambda q: q[0] in 'ZN'),
    ('SCAN: code B -> code A, look for the digit 0', lambda q: q.startswith('S') and q != 'Sz' or q == 'Sz'),
    ('FOUND: code B -> code A', lambda q: q.startswith('F')),
    ('COUNTER', lambda q: q in ('G', 'I', 'R1', 'R2')),
    ('SEED only', lambda q: q.startswith('seed')),
]

def main(src, dst, lean):
    o, S, ROLE = roles()
    o2, S2, _ = tm.parse(open(src).read())
    phi, todo = {o[0]: o2[0]}, [o[0]]
    while todo:
        q = todo.pop()
        for b, t in enumerate(S[q]):
            if t is None or t[2] not in S: continue
            t2 = S2[phi[q]][b]
            assert t2 is not None and t2[:2] == t[:2]
            if t[2] in phi: assert phi[t[2]] == t2[2]
            else: phi[t[2]] = t2[2]; todo.append(t[2])
    assert set(phi) == set(o)
    cls = defaultdict(list)
    for q in o: cls[phi[q]].append(q)
    sec_of = {q: next(i for i, (_, p) in enumerate(SECTIONS) if p(q)) for q in o}
    pos = {r: i for i, r in enumerate(o)}
    name = {}
    for c, members in cls.items():
        work = [r for r in members if not r.startswith('seed')]
        name[c] = '__'.join(work) if work else members[0]
    name[o2[0]] = 'start_' + name[o2[0]]
    def key(c):
        prim = next((r for r in cls[c] if not r.startswith('seed')), cls[c][0])
        return (c != o2[0], sec_of[prim], pos[prim])
    words = lambda f: ' '.join(f(i) for i in range(5))
    A = words(lambda a: f'{a}={build.A[a]}')
    B = '\n;   '.join(' '.join(f'({b},{a})->{build.BETA[f"{b}{a}"]}' for a in range(5)) for b in (0, 1))
    out = [HEADER.format(n=len(o2), N=len(o), lean=lean, A=A, B=B)]
    cur = None
    for c in sorted(o2, key=key):
        sec = key(c)[1] if c != o2[0] else -1
        if sec != cur:
            title = 'START' if sec == -1 else SECTIONS[sec][0]
            out += ['', f'; ---------- {title} ' + '-' * max(0, 60 - len(title)), '']
            cur = sec
        for r in cls[c]:
            out.append(f'; {r:6} {ROLE[r]}')
        out.append(name[c])
        for b, t in enumerate(S2[c]):
            if t is None:
                out.append('    -'); continue
            users = [r for r in cls[c] if S[r][b] is not None]
            tgt = name.get(t[2], t[2])
            out.append(f'    {b} {t[0]} {t[1]} {tgt:24} ; [{", ".join(users)}]')
    text = '\n'.join(out) + '\n'
    o3, S3, _ = tm.parse(text)
    assert o3[0] == name[o2[0]] and len(o3) == len(o2)
    for c in o2:
        assert S3[name[c]] == [None if t is None else (t[0], t[1], name.get(t[2], t[2])) for t in S2[c]]
    open(dst, 'w').write(text)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'M44')
