"""Write a commented version of a merged machine.

Each state of the merged machine is a class of states of the design
(goormaghtigh.txt, generated by build.py). The merged state is named after its
roles, listed with a description, and every transition line is tagged with the
roles that use it. Usage: python3 annotate.py merged.txt out.txt LeanName
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))  # tm.py
from collections import defaultdict
import tm

HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF THE GOORMAGHTIGH
; CONJECTURE IS FALSE, i.e. iff some value other than 31 and 8191 is a repunit
; 1 + x + ... + x^(m-1) = 1 + y + ... + y^(n-1) with 1 < y < x and m, n > 2.
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/Goormaghtigh/{lean}.lean,
; theorem TM.Goormaghtigh.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / goormaghtigh.txt with
;   states merged. States are merged only when their defined transitions agree,
;   so each state below plays one or more ROLES of the design (its name joins
;   them). Each transition line is tagged [role] with the role(s) that use it.
;   A '-' line is never used. The seed roles run once at the start and only
;   ever read 0, so each of them doubles as a step of some other routine.
;
; THE SEARCH: for V = 4, 5, ... and each base b = 2 .. V-2, walk
;   r = 1, b+1, b^2+b+1, ... (r := r*b + 1) while r < V. A HIT is r = V: V is
;   a repunit in base b (of length >= 3, as b <= V-2). V is BAD if it has two
;   hits. 31 and 8191 are the first two bad values; the machine halts at the
;   third, so it needs neither constant.
;
; TAPE LAYOUT (blank on both sides):
;
;      F 0^(1+f) Vb 00 Rg
;
;   F   the countdown: 4 - g - f cells, g = bad values so far, f = min(hits of
;       this V, 2): a hit erases F's last cell while f < 2
;   Vb  V cells; the base hole K has b cells to its right. During a step the
;       pass cursor P runs from K+2 to Vb's last cell (b - 1 passes)
;   Rg  V+1 cells: R (r cells) H D (V - r cells). A step turns H into the
;       marker M and punches a new H on D's first cell; in each pass the copy
;       cursor C walks R and moves H one cell right per cell of R (a tick).
;       Filling M then gives R = r*b + 1 cells. H past the region's end:
;       overflow (r*b + 1 > V); H on its last cell after a step: a hit.
;
; ROUTINES
;   step      X: D empty? hit. Else H -> M, new H; to K, punch P at K+2;
;             passes (C walks R, ticks move H); P moves after each pass;
;             P falls off Vb: merge (fill M), back to X.
;   overflow  fill M, C, P, K; next base.
;   hit       fill H; past K to the run before Vb: f := min(f + 1, 2)
;             (erase F's last cell if f < 2); back to K, fill it; next base.
;   next base K moves one cell left (b + 1); R = 1, H, D = V - 1. If K was on
;             Vb's cell 1: next value.
;   next V    Vb grows on the left; F gets its f cells back (one fewer after
;             a bad V: if F is then empty, HALT) and moves one cell left; K on
;             Vb's cell V-2 (b = 2); the region grows by one cell.
;   seed      writes F (4 cells) 0 1111 00 1111, the tape of V = 3 in the
;             middle of its next-value step.
; ============================================================================

blank_symbol: 0
"""

ROLE = {
    'X': 'step check, on the cell after H: 1: D is not empty, start a step (H becomes M, new H here); 0: a hit',
    'SA': 'step start: step left over M',
    'SB': 'step start: run left over R',
    'SC': 'step start: the separator',
    'SD': 'step start: run left over Vb to K',
    'SE': 'step start: step over K+1',
    'SF': 'step start: punch P on K+2 (the first pass)',
    'G1': 'pass: run right over Vb to the separator',
    'G2': 'pass: the separator',
    'G3': 'pass: punch C on R\'s first cell',
    'TJ': 'tick: run right over R to M',
    'TK': 'tick: run right over Q to H, fill it',
    'TL': 'tick: 1: punch the new H, back; 0: H was on the region\'s last cell: overflow',
    'TM': 'tick: run left over Q to M',
    'TN': 'tick: run left over R to C, fill it',
    'TO': 'tick: 1: C moves here, next tick; 0: this is M: the pass is done',
    'PQ': 'pass done: run left over R',
    'PR': 'pass done: the separator',
    'PS': 'pass done: run left over Vb to P, fill it',
    'PT': 'pass done: 1: P moves here, next pass; 0: P was on Vb\'s last cell: merge',
    'MU': 'merge: the separator',
    'MV': 'merge: run right over R to M, fill it',
    'MW': 'merge: run right over Q to H, then check (X)',
    'O1': 'overflow: run left over Q to M, fill it',
    'O2': 'overflow: run left over R to C, fill it',
    'O3': 'overflow: run left over R',
    'O4': 'overflow: the separator',
    'O5': 'overflow: run left over Vb to P, fill it',
    'O6': 'to K: run left over Vb, fill K, then the next base (K2)',
    'Y0': 'hit: fill H',
    'A1': 'hit: run left over the region',
    'A2': 'hit: the separator',
    'A3': 'hit: run left over Vb\'s cells right of K, step over K',
    'A4': 'hit: run left over Vb\'s cells left of K',
    'A5': 'hit: 1: f = 0, erase F\'s last cell (f = 1); 0: f >= 1',
    'A6': 'hit: 1: f = 1, erase F\'s last cell (f = 2); 0: f = 2, nothing',
    'B1': 'hit: back right over the zeros',
    'B2': 'hit: run right over Vb to K, fill it, then the next base (K2)',
    'K2': 'next base: step left from K',
    'K3': 'next base: 1: K moves one cell left; 0: K was on Vb\'s cell 1: next value (Vb grows here)',
    'K4': 'next base: punch the new K',
    'KR1': 'next base: run right over Vb to the separator',
    'KR2': 'next base: the separator',
    'H1': 'reset the region: step over R = 1',
    'H2': 'reset the region: punch H on cell 1, then the step check (X)',
    'VF1': 'next value: 1: f = 0, F\'s last cell goes; 0: f >= 1',
    'VF2': 'next value: 1: f = 1; 0: f = 2 (a bad value), fill this cell',
    'VFh': 'next value after a bad value: 0: F is empty: the third bad value, HALT',
    'VF3': 'next value: run left over F, one more cell at its left end',
    'VR1': 'next value: run right over F',
    'VR2': 'next value: run right over Vb to the separator',
    'V2': 'next value: step left',
    'V3': 'next value: step left',
    'V4': 'next value: punch K on Vb\'s third cell from the right (b = 2)',
    'V5': 'next value: run right to the separator',
    'V6': 'next value: the separator',
    'V7': 'next value: run right over the region, one more cell at its end',
    'V14': 'next value: run left over the region, then reset it (H1)',
}
SEED = ('1111' + '0' + '1111' + '00' + '1111')[::-1]
for i, ch in enumerate(SEED):
    ROLE[f'seed{i}'] = f'seed: write {ch} and step ' + ('right' if i + 1 == len(SEED) else 'left')

SECTIONS = [
    ('STEP: r := r*b + 1, check r = V', 'X SA SB SC SD SE SF G1 G2 G3 TJ TK TL TM TN TO PQ PR PS PT MU MV MW'),
    ('OVERFLOW: clean up, to K', 'O1 O2 O3 O4 O5 O6'),
    ('HIT: count it in F', 'Y0 A1 A2 A3 A4 A5 A6 B1 B2'),
    ('NEXT BASE', 'K2 K3 K4 KR1 KR2 H1 H2'),
    ('NEXT VALUE: HALT at the third bad value', 'VF1 VF2 VFh VF3 VR1 VR2 V2 V3 V4 V5 V6 V7 V14'),
    ('SEED only', ' '.join(f'seed{i}' for i in range(len(SEED)))),
]

def main(src, dst, lean):
    o, S, _ = tm.parse(open('goormaghtigh.txt').read())
    o2, S2, _ = tm.parse(open(src).read())
    phi, todo = {o[0]: o2[0]}, [o[0]]
    while todo:
        q = todo.pop()
        for b, t in enumerate(S[q]):
            if t is None or t[2] not in S: continue
            t2 = S2[phi[q]][b]
            assert t2 is not None and t2[:2] == t[:2]
            if t[2] in phi: assert phi[t[2]] == t2[2]
            else: phi[t[2]] = t2[2]; todo.append(t[2])
    assert set(phi) == set(o) and set(ROLE) == set(o), set(o) ^ set(ROLE)
    cls = defaultdict(list)
    for q in o: cls[phi[q]].append(q)
    sec_of = {r: i for i, (_, rs) in enumerate(SECTIONS) for r in rs.split()}
    pos = {r: i for i, r in enumerate(o)}
    name = {}
    for c, members in cls.items():
        work = [r for r in members if not r.startswith('seed')]
        name[c] = '_'.join(work) if work else members[0]
    name[o2[0]] = 'start_' + name[o2[0]]
    def key(c):
        prim = next((r for r in cls[c] if not r.startswith('seed')), cls[c][0])
        return (c != o2[0], sec_of[prim], pos[prim])
    out = [HEADER.format(n=len(o2), N=len(o), lean=lean)]
    cur = None
    for c in sorted(o2, key=key):
        sec = key(c)[1] if c != o2[0] else -1
        if sec != cur:
            title = 'START' if sec == -1 else SECTIONS[sec][0]
            out += ['', f'; ---------- {title} ' + '-' * max(0, 60 - len(title)), '']
            cur = sec
        for r in cls[c]:
            out.append(f'; {r:6} {ROLE[r]}')
        out.append(name[c])
        for b, t in enumerate(S2[c]):
            if t is None:
                out.append('    -'); continue
            users = [r for r in cls[c] if S[r][b] is not None]
            tgt = name.get(t[2], t[2])
            out.append(f'    {b} {t[0]} {t[1]} {tgt:20} ; [{", ".join(users)}]')
    text = '\n'.join(out) + '\n'
    # the annotated machine must be the same machine (up to state names)
    o3, S3, _ = tm.parse(text)
    assert o3[0] == name[o2[0]] and len(o3) == len(o2)
    for c in o2:
        assert S3[name[c]] == [None if t is None else (t[0], t[1], name.get(t[2], t[2])) for t in S2[c]]
    open(dst, 'w').write(text)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'M53')
