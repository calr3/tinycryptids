HEADER = """\
; ============================================================================
; A {n}-state, 2-symbol Turing machine that HALTS IFF BROCARD'S PROBLEM HAS A
; SOLUTION BEYOND THE KNOWN ONES: iff n! + 1 = m^2 for some n >= 8.
; (The known solutions are n = 4, 5, 7.)
; Start on a blank tape in the first state. A transition to `halt` halts.
; Lean proof: lean/TinyCryptids/Brocard/{lean}.lean, theorem TM.Brocard.{lean}.halts_iff.
; ============================================================================
;
; HOW TO READ THIS FILE
;   The machine is the {N}-state design of build.py / brocard.txt with states
;   merged. States are merged only when their defined transitions agree, so
;   each state below plays one or more ROLES of the design (its name joins
;   them). Each transition line is tagged [role] with the role(s) that use it.
;   A '-' line is never used. The seed roles run once at the start and only
;   ever read 0, so each of them doubles as a step of some other routine.
;
; TAPE LAYOUT (blocks of 1s separated by 00):
;
;      W 00 N 00 F 00 S      during the square test
;      W 00 N 00 F 00 Q      during the multiplication
;
;   F  n!+4 cells. In the test, its HOLE (a single 0) at cell u+1 counts the
;      units of n!+1 used so far; in the multiplication it is the copy cursor
;      (cells 3 .. n!+2)
;   S  d+2 cells: the odd number d = 2j+1 being subtracted, with a cyclic hole
;   Q  the copies of F made so far
;   N  n+2 cells: the round n; in the multiplication its hole counts the copies
;   W  countdown of the warm-up rounds n < 8 (no test); N grows into it
;
; ALGORITHM (round n = 1, 2, 3, ...)
;   test      (n >= 8) one unit at a time: advance the F hole, then the S hole;
;             when the S hole wraps, d += 2. So after 1 + 3 + ... + (2j+1)
;             units the S hole is back at cell 1. When F runs out (n!+1 units)
;             with the S hole at cell 1, n!+1 = (j+1)^2: HALT. Else erase S.
;   multiply  n times: copy the n! cells of F onto Q; merge Q into F:
;             F = (n+1)!.
;   grow      N := n+1, taking a cell from W. If W is now empty, write S = 101
;             and put the F hole at cell 1 for the next test.
;   seed      write 1111111 00 101 00 11101: round 1, multiplication started.
; ============================================================================

blank_symbol: 0
"""

R = 'right'; L = 'left'
def parser(direction, then):
    return f'scan {direction} to the next hole, then {then}'

